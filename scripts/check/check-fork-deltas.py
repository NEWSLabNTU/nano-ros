#!/usr/bin/env python3
"""phase-523 W4 — every fork the tree carries has a delta page that is current.

Offline and buildless. Reads `.gitmodules`, the index's gitlinks and
`docs/reference/forks/`:

  - every submodule with `branch =` (a patch line or an authored repository)
    has a row in `docs/reference/forks/forks.toml`, as a `[[fork]]` or as
    `[[ours]]`, and no row names a path that is not such a submodule;
  - every `[[fork]]` row has `docs/reference/forks/<name>.md`, generated (its
    stamp line), naming the commit the superproject pins on its
    `**Pinned commit:**` line.

A pin moved without `python3 scripts/gen-fork-deltas.py` fails here, so a delta
page never describes a patch set the tree no longer carries. The page content
itself comes from GitHub's compare API, which this gate does not call.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # Python < 3.11
    import tomli as tomllib  # type: ignore[no-redef]

ROOT = Path(__file__).resolve().parents[2]
TABLE = "docs/reference/forks/forks.toml"
PAGES = "docs/reference/forks"
STAMP = "<!-- GENERATED by scripts/gen-fork-deltas.py"
PIN = re.compile(r"^\*\*Pinned commit:\*\* `([0-9a-f]{40})`$", re.M)


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], check=True,
                          capture_output=True, text=True).stdout


def branch_submodules() -> set[str]:
    out = subprocess.run(["git", "-C", str(ROOT), "config", "-f", ".gitmodules",
                          "--get-regexp", r"\.branch$"],
                         capture_output=True, text=True).stdout
    return {line.split()[0].removeprefix("submodule.").removesuffix(".branch")
            for line in out.splitlines() if line.strip()}


def gitlinks(paths: set[str]) -> dict[str, str]:
    out = {}
    for path in paths:
        fields = git("ls-files", "-s", "--", path).split()
        if len(fields) >= 2 and fields[0] == "160000":
            out[path] = fields[1]
    return out


def errors(table: dict, branched: set[str], links: dict[str, str],
           pages: dict[str, str]) -> list[str]:
    errs = []
    forks = table.get("fork", [])
    rows = {r["path"] for r in forks} | {r["path"] for r in table.get("ours", [])}
    for path in sorted(branched - rows):
        errs.append(f"{path}: tracks a branch in .gitmodules but has no row in {TABLE} "
                    "(a [[fork]] with its upstream and base, or [[ours]])")
    for path in sorted(rows - branched):
        errs.append(f"{TABLE}: names {path}, which is not a branch-tracking submodule")
    for row in forks:
        name, path = row["name"], row["path"]
        page = f"{PAGES}/{name}.md"
        text = pages.get(name)
        if text is None:
            errs.append(f"{page}: missing; run `python3 scripts/gen-fork-deltas.py {name}`")
            continue
        if not text.startswith(STAMP):
            errs.append(f"{page}: not generated (no stamp line); regenerate it")
        found = PIN.search(text)
        want = links.get(path)
        if want is None:
            errs.append(f"{path}: no gitlink in the index")
        elif not found:
            errs.append(f"{page}: no `**Pinned commit:**` line")
        elif found.group(1) != want:
            errs.append(f"{page}: describes {found.group(1)[:12]}, but the superproject pins "
                        f"{want[:12]}; run `python3 scripts/gen-fork-deltas.py {name}`")
    return errs


def self_test() -> None:
    sha, other = "a" * 40, "b" * 40
    table = {"fork": [{"name": "f", "path": "x/f"}], "ours": [{"path": "x/o"}]}
    page = f"{STAMP} -->\n\n**Pinned commit:** `{sha}`\n"
    ok = errors(table, {"x/f", "x/o"}, {"x/f": sha}, {"f": page})
    assert not ok, ok
    assert errors(table, {"x/f", "x/o", "x/new"}, {"x/f": sha}, {"f": page}), \
        "a branch-tracking submodule with no row was not caught"
    assert errors(table, {"x/f"}, {"x/f": sha}, {"f": page}), \
        "a row naming no branch-tracking submodule was not caught"
    assert errors(table, {"x/f", "x/o"}, {"x/f": sha}, {}), "a missing page was not caught"
    assert errors(table, {"x/f", "x/o"}, {"x/f": other}, {"f": page}), \
        "a moved pin with a stale page was not caught"
    assert errors(table, {"x/f", "x/o"}, {"x/f": sha}, {"f": page.replace(STAMP, "<!-- x")}), \
        "a hand-written page was not caught"


def main() -> int:
    self_test()
    table = tomllib.loads((ROOT / TABLE).read_text())
    branched = branch_submodules()
    links = gitlinks(branched)
    pages = {}
    for row in table.get("fork", []):
        p = ROOT / PAGES / f"{row['name']}.md"
        if p.is_file():
            pages[row["name"]] = p.read_text()
    errs = errors(table, branched, links, pages)
    for e in errs:
        print(f"check-fork-deltas: {e}", file=sys.stderr)
    if errs:
        return 1
    print(f"check-fork-deltas: OK ({len(table.get('fork', []))} fork page(s) name their pin; "
          f"{len(table.get('ours', []))} authored repo(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
