#!/usr/bin/env python3
"""phase-523 W4 — every fork the tree carries has a delta page that is current.

Offline and buildless. Reads `.gitmodules`, the index's gitlinks and
`book/src/reference/forks.md`:

  - every submodule with `branch =` (a patch line or an authored repository)
    has a row in `docs/reference/forks/forks.toml`, as a `[[fork]]` or as
    `[[ours]]`, and no row names a path that is not such a submodule;
  - every `[[fork]]` row has its section of `book/src/reference/forks.md`
    (`<!-- fork: <name> -->` … `<!-- /fork: <name> -->`), on a generated page
    (its stamp line), naming the commit the superproject pins on its
    `**Pinned commit:**` line.

  - no tracked build input (`scripts/`, `just/`, the justfile, `cmake/`, the
    workflows, `nros-sdk-index.toml`) fetches a `[[fork]]`'s UPSTREAM
    repository by URL. A fork exists because upstream lacks our patches, so a
    build that clones upstream builds the component without them (issue 2978:
    `scripts/xrce-agent/build.sh` cloned eProsima's tag for the ROS-paired
    agent, so the agent's oversized-sample fix never reached that build).

A pin moved without `python3 scripts/gen-fork-deltas.py` fails here, so a delta
page never describes a patch set the tree no longer carries. The page content
itself comes from GitHub's compare API, which this gate does not call.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # Python < 3.11
    import tomli as tomllib  # type: ignore[no-redef]

ROOT = Path(__file__).resolve().parents[2]
TABLE = "docs/reference/forks/forks.toml"
PAGE = "book/src/reference/forks.md"
STAMP = "<!-- GENERATED by scripts/gen-fork-deltas.py"
PIN = re.compile(r"^\*\*Pinned commit:\*\* `([0-9a-f]{40})`$", re.M)

# Where a build fetches sources from. Tracked files only.
BUILD_INPUTS = ("scripts", "just", "justfile", "cmake", ".github/workflows",
                "nros-sdk-index.toml")

# A use of a fork's upstream URL that is not a build fetching it, each with
# its reason. Keyed by (file, upstream).
UPSTREAM_URL_EXEMPT = {
    ("nros-sdk-index.toml", "eProsima/Micro-XRCE-DDS-Agent"):
        "the SDK's 2.4.3-nros1 agent was built from upstream v2.4.3; this row moves to "
        "the fork with the 2.4.3-nros2 release (issue 2978), with its new dist rows",
}


def upstream_url(upstream: str) -> "re.Pattern[str]":
    """`upstream`'s GitHub URL, not a longer repository name sharing its prefix
    (`apache/nuttx` is not `apache/nuttx-apps`)."""
    return re.compile(r"github\.com[/:]" + re.escape(upstream) + r"(?:\.git)?(?![\w.-])")


def upstream_fetches(table: dict, files: "dict[str, str]") -> list[str]:
    errs = []
    for row in table.get("fork", []):
        rx = upstream_url(row["upstream"])
        for path, text in sorted(files.items()):
            if (path, row["upstream"]) in UPSTREAM_URL_EXEMPT:
                continue
            for m in rx.finditer(text):
                line = text.count("\n", 0, m.start()) + 1
                errs.append(
                    f"{path}:{line}: fetches {row['upstream']}, the UPSTREAM of the "
                    f"{row['name']} fork, so that build lacks our patches; fetch the fork "
                    f"(the submodule's URL and patch-line branch) instead")
    return errs


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], check=True,
                          capture_output=True, text=True).stdout


def branch_submodules() -> set[str]:
    out = subprocess.run(["git", "-C", str(ROOT), "config", "-f", ".gitmodules",
                          "--get-regexp", r"\.branch$"],
                         capture_output=True, text=True).stdout
    return {line.split()[0].removeprefix("submodule.").removesuffix(".branch")
            for line in out.splitlines() if line.strip()}


def gitlinks(paths: set[str]) -> dict[str, str]:
    out = {}
    for path in paths:
        fields = git("ls-files", "-s", "--", path).split()
        if len(fields) >= 2 and fields[0] == "160000":
            out[path] = fields[1]
    return out


def errors(table: dict, branched: set[str], links: dict[str, str],
           pages: dict[str, str]) -> list[str]:
    errs = []
    forks = table.get("fork", [])
    rows = {r["path"] for r in forks} | {r["path"] for r in table.get("ours", [])}
    for path in sorted(branched - rows):
        errs.append(f"{path}: tracks a branch in .gitmodules but has no row in {TABLE} "
                    "(a [[fork]] with its upstream and base, or [[ours]])")
    for path in sorted(rows - branched):
        errs.append(f"{TABLE}: names {path}, which is not a branch-tracking submodule")
    for row in forks:
        name, path = row["name"], row["path"]
        page = f"{PAGE}#{name}"
        text = pages.get(name)
        if text is None:
            errs.append(f"{page}: missing; run `python3 scripts/gen-fork-deltas.py {name}`")
            continue
        if not text.startswith(STAMP):
            errs.append(f"{page}: not generated (no stamp line); regenerate it")
        found = PIN.search(text)
        want = links.get(path)
        if want is None:
            errs.append(f"{path}: no gitlink in the index")
        elif not found:
            errs.append(f"{page}: no `**Pinned commit:**` line")
        elif found.group(1) != want:
            errs.append(f"{page}: describes {found.group(1)[:12]}, but the superproject pins "
                        f"{want[:12]}; run `python3 scripts/gen-fork-deltas.py {name}`")
    return errs


def self_test() -> None:
    sha, other = "a" * 40, "b" * 40
    table = {"fork": [{"name": "f", "path": "x/f"}], "ours": [{"path": "x/o"}]}
    page = f"{STAMP} -->\n\n**Pinned commit:** `{sha}`\n"
    ok = errors(table, {"x/f", "x/o"}, {"x/f": sha}, {"f": page})
    assert not ok, ok
    assert errors(table, {"x/f", "x/o", "x/new"}, {"x/f": sha}, {"f": page}), \
        "a branch-tracking submodule with no row was not caught"
    assert errors(table, {"x/f"}, {"x/f": sha}, {"f": page}), \
        "a row naming no branch-tracking submodule was not caught"
    assert errors(table, {"x/f", "x/o"}, {"x/f": sha}, {}), "a missing page was not caught"
    assert errors(table, {"x/f", "x/o"}, {"x/f": other}, {"f": page}), \
        "a moved pin with a stale page was not caught"
    assert errors(table, {"x/f", "x/o"}, {"x/f": sha}, {"f": page.replace(STAMP, "<!-- x")}), \
        "a hand-written page was not caught"
    forks = {"fork": [{"name": "nuttx", "upstream": "apache/nuttx"}]}
    assert upstream_fetches(forks, {"s.sh": "git clone https://github.com/apache/nuttx s"}), \
        "a clone of a fork's upstream was not caught"
    assert upstream_fetches(forks, {"s.sh": 'url = "https://github.com/apache/nuttx.git"'}), \
        "a .git upstream URL was not caught"
    assert not upstream_fetches(forks, {"s.sh": "git clone https://github.com/apache/nuttx-apps"}), \
        "a different repository sharing the upstream's prefix was flagged"
    assert not upstream_fetches(forks, {"s.sh": "git clone https://github.com/me/nuttx"}), \
        "the fork itself was flagged"


def main() -> int:
    self_test()
    table = tomllib.loads((ROOT / TABLE).read_text())
    branched = branch_submodules()
    links = gitlinks(branched)
    pages = {}
    p = ROOT / PAGE
    text = p.read_text() if p.is_file() else ""
    stamp = text.split("\n", 1)[0] + "\n" if text.startswith(STAMP) else ""
    for row in table.get("fork", []):
        m = re.search(rf"<!-- fork: {re.escape(row['name'])} -->\n.*?<!-- /fork: "
                      rf"{re.escape(row['name'])} -->", text, re.S)
        if m:
            # Each section is judged as the page's: generated when the page is.
            pages[row["name"]] = stamp + m.group(0)
    errs = errors(table, branched, links, pages)
    listed = git("ls-files", "-z", "--", *BUILD_INPUTS).split("\0")
    files = {}
    for rel in listed:
        f = ROOT / rel
        # This file names upstream URLs in its own self-test.
        if rel and f.is_file() and f.resolve() != Path(__file__).resolve():
            try:
                files[rel] = f.read_text(encoding="utf-8")
            except UnicodeDecodeError:
                continue
    errs += upstream_fetches(table, files)
    for e in errs:
        print(f"check-fork-deltas: {e}", file=sys.stderr)
    if errs:
        return 1
    print(f"check-fork-deltas: OK ({len(table.get('fork', []))} fork section(s) name their pin; "
          f"{len(table.get('ours', []))} authored repo(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
