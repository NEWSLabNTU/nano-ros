#!/usr/bin/env python3
"""Render the CLI-owned tables of migrating/retired-names from the CLI's source.

Two tables on that page restate a list the CLI keeps, so they are rendered
from it between markers and never typed (RFC-0124 Principle 9, phase-537 W12):

* Retired board names: `RETIRED_BOARD_KEYS` (renamed) and `REMOVED_BOARD_KEYS`
  (gone) in `packages/cli/nros-entry-lower/src/lib.rs`, the tables
  `retired_board_key_hint` answers a refused board word from.
* Old command spellings: `user::ALIASES` in
  `packages/cli/nros-cli-core/src/cmd/user.rs`, with `user::RETIRING` marking
  the ones that warn on every run. `dev::ALIASES` is not rendered: those are
  spellings of the developer tier, which the user book never names
  (Principle 5).

The rest of the page is hand-kept. The source is read as text, so the page
renders without building the CLI. Internal ids in a reason (`phase-500`,
`RFC-0093 R3`, `issue 2063`) are dropped: the reader has no tree to look
them up in.

Run:  python3 scripts/gen-retired-names.py [--check | --self-test]
Gate: just check retired-names
"""

from __future__ import annotations

import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE / "lib"))
import book_pages  # noqa: E402

PAGE = "migrating/retired-names.md"
BOARDS_SRC = ROOT / "packages/cli/nros-entry-lower/src/lib.rs"
ALIASES_SRC = ROOT / "packages/cli/nros-cli-core/src/cmd/user.rs"
REGIONS = {
    "retired-boards": "<!-- retired-boards:begin (generated by scripts/gen-retired-names.py) -->",
    "old-commands": "<!-- old-commands:begin (generated by scripts/gen-retired-names.py) -->",
}
ID = r"(?:RFC-?\d{4}(?: [A-Z]\d+)?|[Ii]ssue \d{3,4}|[Pp]hase[- ]\d{2,4}(?: W\d+)?)"

STRING = re.compile(r'"((?:[^"\\]|\\.)*)"', re.S)


def rust_str(lit: str) -> str:
    """A Rust string literal's value: `\\` + newline + indent is nothing."""
    lit = re.sub(r"\\\n\s*", "", lit)
    return lit.replace('\\"', '"').replace("\\\\", "\\")


def const_block(src: str, name: str) -> str:
    m = re.search(r"pub const " + name + r": &\[[^\]]*\] = &\[(.*?)\n\];", src, re.S)
    if not m:
        sys.exit(f"gen-retired-names: no `pub const {name}` table in the source")
    return m.group(1)


ITEM = re.compile(r'"(?:[^"\\]|\\.)*"|[A-Z][A-Z0-9_]+|[()]', re.S)


def tuples(block: str) -> list[list[str]]:
    """Each `( … )` of a const table, as its string literals and identifiers.

    Tokenised rather than matched with one pattern: a reason may hold a `)`
    inside its string."""
    out, cur = [], None
    for tok in ITEM.findall(re.sub(r"//[^\n]*", "", block)):
        if tok == "(":
            cur = []
        elif tok == ")":
            if cur is not None:
                out.append(cur)
            cur = None
        elif cur is not None:
            cur.append(tok)
    return out


def scrub(text: str) -> str:
    text = re.sub(r"\s*\((?:" + ID + r"[,;]?\s*)+\)", "", text)
    if re.search(ID, text):
        sys.exit(f"gen-retired-names: an id this script cannot drop: {text!r}")
    return text


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def board_rows(src: str) -> list[tuple[str, str, str]]:
    consts = {m.group(1): rust_str(m.group(2))
              for m in re.finditer(r'const ([A-Z0-9_]+): &str = "((?:[^"\\]|\\.)*)";', src, re.S)}
    rows = []
    for t in tuples(const_block(src, "RETIRED_BOARD_KEYS")):
        old, new, why = (rust_str(x[1:-1]) for x in t)
        rows.append((old, new, why))
    for t in tuples(const_block(src, "REMOVED_BOARD_KEYS")):
        old = rust_str(t[0][1:-1])
        why = consts[t[1]] if not t[1].startswith('"') else rust_str(t[1][1:-1])
        rows.append((old, "", why))
    return rows


def render_boards(rows: list[tuple[str, str, str]]) -> str:
    lines = ["| Retired | Use instead | Why |", "| --- | --- | --- |"]
    groups: list[tuple[list[str], str, str]] = []
    for old, new, why in rows:
        # Removed words that share one reason are one row: they named one board.
        if groups and not new and not groups[-1][1] and groups[-1][2] == why:
            groups[-1][0].append(old)
        else:
            groups.append(([old], new, why))
    for olds, new, why in groups:
        why = scrub(why)
        why = why[0].upper() + why[1:]
        words = ", ".join(f"`{o}`" for o in olds)
        lines.append(f"| {words} | {f'`{new}`' if new else 'nothing: removed'} | {cell(why)} |")
    return "\n".join(lines)


def alias_rows(src: str) -> tuple[list[tuple[str, str]], set[str]]:
    rows = [(rust_str(a), rust_str(b)) for a, b in
            re.findall(r'\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\)',
                       const_block(src, "ALIASES"))]
    m = re.search(r"pub const RETIRING: &\[&str\] = &\[(.*?)\];", src, re.S)
    retiring = {rust_str(x) for x in STRING.findall(m.group(1))} if m else set()
    return rows, retiring


def render_aliases(rows: list[tuple[str, str]], retiring: set[str]) -> str:
    lines = ["| Old spelling | Now | What happens |", "| --- | --- | --- |"]
    for old, new in rows:
        what = ("runs, and warns on every run that it will be removed" if old in retiring
                else "runs, with a note naming the new spelling when stderr is a terminal")
        lines.append(f"| `nros {old}` | `nros {new}` | {what} |")
    return "\n".join(lines)


def end(key: str) -> str:
    return f"<!-- {key}:end -->"


def splice(page: str, key: str, body: str) -> str:
    begin = REGIONS[key]
    i, j = page.find(begin), page.find(end(key))
    if i < 0 or j < i:
        sys.exit(f"gen-retired-names: {PAGE} has no {begin!r} … {end(key)!r} region")
    return page[:i] + begin + "\n" + body + "\n" + page[j:]


def render(page: str) -> str:
    page = splice(page, "retired-boards", render_boards(board_rows(BOARDS_SRC.read_text())))
    rows, retiring = alias_rows(ALIASES_SRC.read_text())
    return splice(page, "old-commands", render_aliases(rows, retiring))


def self_test() -> None:
    src = '''pub const RETIRED_BOARD_KEYS: &[(&str, &str, &str)] = &[
    (
        "native",
        "linux",
        "`native` names every host \\
         (phase-500)",
    ),
];

pub const REMOVED_BOARD_KEYS: &[(&str, &str)] = &[
    ("esp32", GONE),
];

const GONE: &str = "the board is retired (RFC-0113 D5; issue 1525)";
'''
    rows = board_rows(src)
    assert rows == [("native", "linux", "`native` names every host (phase-500)"),
                    ("esp32", "", "the board is retired (RFC-0113 D5; issue 1525)")], rows
    out = render_boards(rows)
    assert "| `native` | `linux` | `native` names every host |" in out, out
    assert "| `esp32` | nothing: removed | The board is retired |" in out, out
    asrc = 'pub const ALIASES: &[(&str, &str)] = &[\n    ("sync", "configure"),\n    ("init", "setup presets"),\n];\npub const RETIRING: &[&str] = &["sync"];\n'
    r, ret = alias_rows(asrc)
    assert r == [("sync", "configure"), ("init", "setup presets")] and ret == {"sync"}, (r, ret)
    a = render_aliases(r, ret)
    assert "| `nros sync` | `nros configure` | runs, and warns on every run" in a, a
    page = f"x\n{REGIONS['old-commands']}\nold\n{end('old-commands')}\ny\n"
    assert splice(page, "old-commands", "new") == f"x\n{REGIONS['old-commands']}\nnew\n{end('old-commands')}\ny\n"
    try:
        scrub("left (see RFC-0001 here)")
    except SystemExit:
        pass
    else:
        raise AssertionError("an id inside prose must stop the render")


def main() -> int:
    self_test()
    if "--self-test" in sys.argv:
        print("gen-retired-names: self-test OK")
        return 0
    path = next((p.current() or p.target) for p in book_pages.load()
                if p.book == "user" and p.path == PAGE and p.verb != "merge-into")
    page = path.read_text()
    new = render(page)
    if "--check" in sys.argv:
        if new != page:
            print(f"gen-retired-names: {PAGE} differs from the CLI's tables; "
                  "run scripts/gen-retired-names.py", file=sys.stderr)
            return 1
        print("retired-names OK (board and command tables match the CLI's source)")
        return 0
    path.write_text(new)
    print(f"gen-retired-names: wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
