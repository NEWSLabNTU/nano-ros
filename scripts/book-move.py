#!/usr/bin/env python3
"""Move book pages by the page map (RFC-0123, phase-532 W0).

    book-move.py --plan [BATCH]     what BATCH (default: every pending batch) does
    book-move.py --apply BATCH      do it: git mv, stubs, SUMMARY, links, literals, redirects
    book-move.py --rewrite          repair references only (for a branch rebased over a move)
    book-move.py --summary          regenerate both SUMMARY.md files from the map only
    book-move.py --check-summary    exit 1 if either SUMMARY.md differs from the map

`--apply` is the only spelling that moves files. Everything after the moves is
the same repair `--rewrite` does, so applying a batch and rebasing over one
leave a tree in the same state:

* both SUMMARY.md files are rebuilt from the map: parts in RFC-0123 D2 order,
  pages in map order, each at its CURRENT location (so a half-migrated tree has
  a valid TOC), titles kept from the old SUMMARY. The board generator's marked
  region is carried through verbatim;
* every relative link in either book whose target no longer exists is
  re-resolved through the map (from the linking page's OLD location if it
  moved too). A link that crosses books becomes a relative `.html` link
  between the two deploy roots (user at `/`, Internals at `/internals/`);
* every `book/src/<old>` literal in tracked text files (scripts, recipes,
  workflows, docs) is rewritten to the page's current location. Archived
  records, the changelog and the map's own docs are left as history;
* each moved page gets an `[output.html.redirect]` row in its old book's
  `book.toml`.

`merge-into` rows are reported, never automated: merging two pages is an edit
a person makes (W5). After the merge, delete the merged page and run
`--rewrite`; its links and literals then follow the map to the target.
"""

from __future__ import annotations

import argparse
import os
import pathlib
import posixpath
import re
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "lib"))
import book_pages as bp  # noqa: E402

ROOT = bp.ROOT
USER_SRC = bp.BOOKS["user"]
DEPLOY = bp.DEPLOY  # RFC-0123 D7
BOOK_TOML = {"user": ROOT / "book" / "book.toml", "internals": ROOT / "book-internals" / "book.toml"}
GEN_BEGIN = "<!-- BEGIN GENERATED by scripts/gen-board-support.py: board pages -->"
GEN_END = "<!-- END GENERATED board pages -->"
LINK = re.compile(r"(\]\()(\s*)([^)\s#]+)(#[^)\s]*)?(\s*\))")
SUMMARY_ENTRY = re.compile(r"^\s*-\s*\[(.+?)\]\((?:\./)?([^)#]+\.md)\)")
LITERAL_SKIP = (
    "book/page-map.toml",
    "CHANGELOG.md",
    "docs/design/0123-two-books-by-audience.md",
    "docs/roadmap/phase-532-two-books-by-audience.md",
    # Its "Recently resolved" block is content-frozen (check-issue-index):
    # a path inside it is part of a record. Old paths keep a moved stub.
    "docs/issues/README.md",
)


def git(*args: str, check: bool = True) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, check=check, text=True, capture_output=True).stdout


def rel(path: pathlib.Path) -> str:
    return str(path.relative_to(ROOT))


url_of = bp.deploy_url
book_of = bp.book_of


def url_of_old(old_file: pathlib.Path) -> str:
    """Deploy URL a page had at its old (user book) location."""
    return str(old_file.resolve().relative_to(USER_SRC.resolve()).with_suffix(".html"))


def source_of_url(url: str) -> pathlib.Path | None:
    """The source file that serves deploy URL `url`: the first candidate that
    exists, else the last (user-book) reading, so a page that has since moved
    can be followed through the map. Until W4, a URL under `internals/` may be
    either book's (RFC-0123 D7)."""
    if not url.endswith(".html") or url.startswith(".."):
        return None
    cands = []
    for b in ("internals", "user"):  # longest prefix first
        prefix = DEPLOY[b]
        if url.startswith(prefix):
            cands.append(bp.BOOKS[b] / pathlib.PurePosixPath(url[len(prefix):]).with_suffix(".md"))
    for c in cands:
        if c.exists():
            return c
    return cands[-1] if cands else None


# ---------------------------------------------------------------- plan / apply


def pending(pages: list[bp.Page], batch: str | None) -> list[bp.Page]:
    out = []
    for p in pages:
        if batch and p.batch != batch:
            continue
        if p.verb == "keep":
            continue
        if p.verb in ("new", "import") and p.target.exists():
            continue
        if p.verb in ("move", "split") and p.target.exists():
            continue
        if p.verb == "merge-into" and not (p.old and (USER_SRC / p.old).exists()):
            continue
        out.append(p)
    return out


def describe(p: bp.Page) -> str:
    dst = f"{p.book}:{p.path}"
    if p.verb in ("move", "split"):
        extra = f"  (then split into internals:{p.arg})" if p.verb == "split" else ""
        return f"mv    {p.old} -> {dst}{extra}"
    if p.verb == "merge-into":
        return f"MERGE {p.old} -> user:{p.arg}  (manual, W5)"
    if p.verb == "new":
        return f"stub  {dst}  (owner {p.arg})"
    if p.verb == "import":
        return f"imp   {p.arg} -> {dst}  (a moved stub stays)"
    return f"?     {p}"


def plan(pages: list[bp.Page], batch: str | None) -> int:
    todo = pending(pages, batch)
    batches: dict[str, list[bp.Page]] = {}
    for p in todo:
        batches.setdefault(p.batch, []).append(p)
    if not batches:
        print(f"book-move: nothing pending{' in ' + batch if batch else ''}")
        return 0
    for b, rows in batches.items():
        print(f"[{b}] {len(rows)} page(s)")
        for p in rows:
            print(f"  {describe(p)}")
    return 0


def title_guess(p: bp.Page) -> str:
    stem = pathlib.Path(p.path).stem.replace("-", " ")
    return stem[:1].upper() + stem[1:]


def write_stub(p: bp.Page) -> None:
    p.target.parent.mkdir(parents=True, exist_ok=True)
    owner = p.arg or "phase-532"
    body = f"# {title_guess(p)}\n\n"
    if p.note:
        body += f"{p.note[:1].upper() + p.note[1:]}.\n\n"
    if p.book == "user":
        # RFC-0123 D3: a user page names no phase. Its owner is in the map.
        body += "*This page is coming soon.*\n"
    else:
        body += f"*This page is a placeholder. It is written by {owner}.*\n"
    p.target.write_text(body)
    git("add", rel(p.target))


def import_doc(p: bp.Page) -> None:
    """Move a document from outside the books into its page, and leave a
    one-line stub at the old path: CLAUDE.md, AGENTS.md, issues and commit
    messages link to these files, and a dead link there helps nobody."""
    src = p.source
    assert src is not None and src.exists(), p
    first = src.read_text().lstrip().splitlines()[:1]
    title = first[0][2:].strip() if first and first[0].startswith("# ") else title_guess(p)
    p.target.parent.mkdir(parents=True, exist_ok=True)
    git("mv", rel(src), rel(p.target))
    book = "nano-ros Internals" if p.book == "internals" else "the nano-ros Book"
    src.write_text(f"# {title}\n\nMoved to {book}: [{title}]({os.path.relpath(p.target, src.parent)}).\n")
    git("add", rel(src))


def apply(pages: list[bp.Page], batch: str) -> int:
    todo = pending(pages, batch)
    if not todo:
        print(f"book-move: nothing pending in {batch}")
        return 0
    moved: list[bp.Page] = []
    for p in todo:
        print(f"  {describe(p)}")
        if p.verb in ("move", "split"):
            p.target.parent.mkdir(parents=True, exist_ok=True)
            git("mv", rel(USER_SRC / p.old), rel(p.target))
            moved.append(p)
        elif p.verb == "new":
            write_stub(p)
        elif p.verb == "import":
            import_doc(p)
    add_redirects(moved)
    repair(pages)
    # A generated page's content is its generator's output, never the link
    # repair's: re-run EVERY generator the map names, so each committed page is
    # exactly what `--check` regenerates. Not only the moved pages' generators:
    # a literal rewrite can change a generator's INPUT (W4: the board
    # registry names chapter paths, so its data hash and every view moved).
    for script in sorted({p.generated for p in pages if p.generated}):
        print(f"  regen {script}")
        subprocess.run([sys.executable, str(ROOT / script)], cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
    return 0


# ------------------------------------------------------------------ SUMMARY


def old_titles() -> dict[pathlib.Path, str]:
    """Title of every page some SUMMARY.md links, keyed by resolved file."""
    titles: dict[pathlib.Path, str] = {}
    for src in bp.BOOKS.values():
        s = src / "SUMMARY.md"
        if not s.exists():
            continue
        for line in s.read_text().splitlines():
            m = SUMMARY_ENTRY.match(line)
            if m:
                titles[(src / m.group(2)).resolve()] = m.group(1)
    return titles


def page_title(p: bp.Page, cur: pathlib.Path, titles: dict[pathlib.Path, str]) -> str:
    for key in (cur.resolve(), (USER_SRC / p.old).resolve() if p.old else None):
        if key is not None and key in titles:
            return titles[key]
    first = cur.read_text().lstrip().splitlines()[:1]
    if first and first[0].startswith("# "):
        return first[0][2:].strip()
    return title_guess(p)


def generated_region() -> list[str]:
    s = USER_SRC / "SUMMARY.md"
    lines = s.read_text().splitlines() if s.exists() else []
    try:
        i, j = lines.index(GEN_BEGIN), lines.index(GEN_END)
    except ValueError:
        return []
    return lines[i : j + 1]


def render_summary(book: str, pages: list[bp.Page], titles: dict[pathlib.Path, str]) -> str:
    src = bp.BOOKS[book]
    region = generated_region() if book == "user" else []
    in_region = {(src / m.group(2)).resolve() for m in map(SUMMARY_ENTRY.match, region) if m}
    out = ["# Summary", ""]
    placed: set[pathlib.Path] = set()
    for i, (d, heading) in enumerate(bp.PARTS[book]):
        rows = []
        for p in pages:
            if p.book != book or p.part != d or p.verb == "merge-into":
                continue
            cur = p.current()
            if cur is None or cur.resolve() in placed:
                continue
            placed.add(cur.resolve())
            rows.append((p, cur))
        if book == "user" and i == 0:
            # mdBook prefix chapters: the introduction sits above the first part.
            for p, cur in rows:
                out.append(f"[{page_title(p, cur, titles)}](./{cur.relative_to(src)})")
            out.append("")
            continue
        body = []
        for p, cur in rows:
            if cur.resolve() in in_region:
                continue
            body.append(f"- [{page_title(p, cur, titles)}](./{cur.relative_to(src)})")
            # A page waiting to be merged into this one keeps a line nested
            # under it until W5 folds it in, so the half-migrated book still
            # reaches it.
            for q in pages:
                if q.book == book and q.verb == "merge-into" and q.arg == p.path and q.old:
                    old = USER_SRC / q.old
                    if old.exists():
                        body.append(f"  - [{page_title(q, old, titles)}](./{old.relative_to(src)})")
        if d == "reference" and region:
            body.extend(region)
        if body:
            out += [f"# {heading}", ""] + body + [""]
    return "\n".join(out).rstrip() + "\n"


def write_summaries(pages: list[bp.Page]) -> None:
    titles = old_titles()
    for book, src in bp.BOOKS.items():
        if not src.exists():
            continue
        (src / "SUMMARY.md").write_text(render_summary(book, pages, titles))


def stale_summaries(pages: list[bp.Page]) -> list[str]:
    """SUMMARY.md files that differ from what the map renders."""
    titles = old_titles()
    out = []
    for book, src in bp.BOOKS.items():
        s = src / "SUMMARY.md"
        if s.exists() and s.read_text() != render_summary(book, pages, titles):
            out.append(rel(s))
    return out


# -------------------------------------------------------------------- links


def locate_old(pages: list[bp.Page], file: pathlib.Path) -> pathlib.Path:
    """Where `file` was before its batch ran (itself, if it never moved)."""
    for p in pages:
        if p.old and p.target.resolve() == file.resolve():
            return USER_SRC / p.old
        if p.verb == "import" and p.target.resolve() == file.resolve():
            return p.source
    return file


def imported_target(pages: list[bp.Page], path: pathlib.Path) -> pathlib.Path | None:
    """If `path` is an imported document's old location (now a stub), the
    page it moved to."""
    for p in pages:
        if p.verb == "import" and p.source and p.source.resolve() == path.resolve() and p.target.exists():
            return p.target
    return None


def resolve_via_map(pages: list[bp.Page], old_target: pathlib.Path) -> pathlib.Path | None:
    imp = imported_target(pages, old_target)
    if imp is not None:
        return imp
    try:
        old_rel = str(old_target.resolve().relative_to(USER_SRC.resolve()))
    except ValueError:
        return None
    p = bp.by_old(pages).get(old_rel)
    if p is None:
        return None
    if p.verb == "merge-into":
        tgt = next((q for q in pages if q.book == "user" and q.path == p.arg and q.verb != "merge-into"), None)
        return tgt.current() if tgt else None
    return p.current()


link_text = bp.link


def repair_links(pages: list[bp.Page]) -> int:
    fixed = 0
    for src in bp.BOOKS.values():
        if not src.exists():
            continue
        for f in [f for f in bp.book_files() if src.resolve() in f.resolve().parents]:
            text = f.read_text()
            was = locate_old(pages, f)

            def sub(m: re.Match) -> str:
                nonlocal fixed
                target = m.group(3)
                if re.match(r"^(?:[a-z][a-z0-9+.-]*:|//|/)", target, re.I):
                    return m.group(0)
                here = (f.parent / target).resolve()
                if here.exists():
                    imp = imported_target(pages, here)
                    if imp is None:
                        return m.group(0)
                    fixed += 1  # it names an imported doc's stub: point at the page
                    return f"{m.group(1)}{m.group(2)}{os.path.relpath(imp, f.parent)}{m.group(4) or ''}{m.group(5)}"
                if target.endswith(".html"):
                    # A cross-book link names a deploy URL. Read it from where
                    # the page is now; if that serves nothing, from where the
                    # page used to be (the link was written there). If the page
                    # it named has moved, follow the map. `api/` and anything
                    # unmapped are left alone.
                    # An imported doc's old location is outside every book, so
                    # it has no old URL to read from.
                    in_old_book = was != f and USER_SRC.resolve() in was.resolve().parents
                    bases = [url_of(f)] + ([url_of_old(was)] if in_old_book else [])
                    for i, base in enumerate(bases):
                        src_page = source_of_url(posixpath.normpath(posixpath.join(posixpath.dirname(base), target)))
                        if src_page is None:
                            continue
                        if src_page.exists():
                            if i == 0:
                                return m.group(0)  # resolves where the page is now
                            dest = src_page
                        else:
                            dest = resolve_via_map(pages, src_page)
                        if dest is None:
                            continue
                        new = link_text(f, dest)
                        if new == target:
                            return m.group(0)
                        fixed += 1
                        return f"{m.group(1)}{m.group(2)}{new}{m.group(4) or ''}{m.group(5)}"
                    return m.group(0)
                if target.endswith(".md"):
                    dest = resolve_via_map(pages, was.parent / target)
                    if dest is None:
                        dest = resolve_via_map(pages, f.parent / target)
                    if dest is not None:
                        fixed += 1
                        return f"{m.group(1)}{m.group(2)}{link_text(f, dest)}{m.group(4) or ''}{m.group(5)}"
                # Not a mapped page: a repo file or directory the page reached
                # from where it used to live. Keep pointing at the same thing.
                old_abs = (was.parent / target).resolve()
                if was != f and old_abs.exists():
                    old_abs = imported_target(pages, old_abs) or old_abs
                    trail = "/" if target.endswith("/") else ""
                    fixed += 1
                    new = os.path.relpath(old_abs, f.parent) + trail
                    return f"{m.group(1)}{m.group(2)}{new}{m.group(4) or ''}{m.group(5)}"
                return m.group(0)

            new = LINK.sub(sub, text)
            if new != text:
                f.write_text(new)
    return fixed


def repair_doc_links(pages: list[bp.Page]) -> int:
    """Dead relative links from repo documents OUTSIDE the books (docs/,
    READMEs, archived records included) into a moved book page are repointed
    through the map. An archived record keeps its words; only a link whose
    target moved is respelled, so it still opens the page it meant."""
    files = git("ls-files", "-z", "--", "*.md").split("\0")
    n = 0
    for name in files:
        if not name or name.startswith(("book/", "book-internals/")):
            continue
        path = ROOT / name
        text = path.read_text()

        def sub(m: re.Match) -> str:
            nonlocal n
            target = m.group(3)
            if not target.endswith(".md") or re.match(r"^(?:[a-z][a-z0-9+.-]*:|/)", target, re.I):
                return m.group(0)
            old_abs = (path.parent / target).resolve()
            if old_abs.exists():
                imp = imported_target(pages, old_abs)
                if imp is None or path.resolve() == old_abs:
                    return m.group(0)
                n += 1  # it names an imported doc's stub: point at the page
                return f"{m.group(1)}{m.group(2)}{os.path.relpath(imp, path.parent)}{m.group(4) or ''}{m.group(5)}"
            dest = resolve_via_map(pages, old_abs)
            if dest is None:
                return m.group(0)
            n += 1
            return f"{m.group(1)}{m.group(2)}{os.path.relpath(dest, path.parent)}{m.group(4) or ''}{m.group(5)}"

        new = LINK.sub(sub, text)
        if new != text:
            path.write_text(new)
    return n


# ----------------------------------------------------------------- literals


def repair_literals(pages: list[bp.Page]) -> int:
    moves = {}
    for p in pages:
        if not p.old:
            continue
        cur = p.current() if p.verb != "merge-into" else resolve_via_map(pages, USER_SRC / p.old)
        if cur is None or cur.resolve() == (USER_SRC / p.old).resolve():
            continue
        moves["book/src/" + p.old] = rel(cur)
    stubs = set()
    for p in pages:
        if p.verb == "import" and p.target.exists():
            moves[p.arg] = rel(p.target)
            stubs.add(p.arg)
    if not moves:
        return 0
    pat = re.compile("|".join(re.escape(k) for k in sorted(moves, key=len, reverse=True)) + r"(?![\w/.-])")
    files = git("grep", "-lI", "-F", *sum((["-e", k] for k in moves), []), check=False).split()
    n = 0
    for name in files:
        if name in LITERAL_SKIP or name in stubs or "/archived/" in name or name.startswith("changelog.d/"):
            continue
        path = ROOT / name
        text = path.read_text()
        new = pat.sub(lambda m: moves[m.group(0)], text)
        if new != text:
            path.write_text(new)
            n += 1
    return n


# ---------------------------------------------------------------- redirects


def add_redirects(moved: list[bp.Page]) -> None:
    """Add a redirect row for each page's old URL, unless one exists (a hand
    row, e.g. one naming an anchor in the merge target, is kept)."""
    existing = BOOK_TOML["user"].read_text()
    rows = []
    for p in moved:
        old_url = str(pathlib.PurePosixPath(p.old).with_suffix(".html"))
        if f'"/{old_url}"' in existing:
            continue
        new_url = DEPLOY[p.book] + str(pathlib.PurePosixPath(p.path).with_suffix(".html"))
        rows.append(f'"/{old_url}" = "{os.path.relpath(new_url, os.path.dirname(old_url) or ".")}"')
    if not rows:
        return
    toml = BOOK_TOML["user"]
    text = toml.read_text()
    header = "[output.html.redirect]"
    if header not in text:
        text = text.rstrip() + "\n\n# RFC-0123 D7: every page phase-532 moved keeps its old URL for two releases.\n" + header + "\n"
    head, _, tail = text.partition(header + "\n")
    # Keep the table contiguous: new rows go right after the header.
    text = head + header + "\n" + "\n".join(rows) + "\n" + tail
    toml.write_text(text)


# --------------------------------------------------------------------- main


def repair(pages: list[bp.Page]) -> None:
    # Every mapped page whose old file is gone (moved, or merged by hand in
    # W5) keeps its old URL. Idempotent: existing rows are left alone.
    add_redirects([p for p in pages if p.old and p.verb in ("move", "split", "merge-into")
                   and not (USER_SRC / p.old).exists()])
    write_summaries(pages)
    n_links = repair_links(pages)
    n_lit = repair_literals(pages)
    n_doc = repair_doc_links(pages)
    print(f"book-move: SUMMARY rebuilt; {n_links} link(s) repaired; {n_lit} file(s) with path literals "
          f"rewritten; {n_doc} doc link(s) repointed")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--plan", nargs="?", const="", metavar="BATCH")
    g.add_argument("--apply", metavar="BATCH")
    g.add_argument("--rewrite", action="store_true")
    g.add_argument("--summary", action="store_true")
    g.add_argument("--check-summary", action="store_true")
    a = ap.parse_args()
    pages = bp.load()
    errs = bp.check(pages)
    if errs:
        print("book-move: the page map is not well-formed; run scripts/check-book-page-map.py")
        return 1
    if a.plan is not None:
        return plan(pages, a.plan or None)
    if a.apply:
        return apply(pages, a.apply)
    if a.summary:
        write_summaries(pages)
        return 0
    if a.check_summary:
        stale = stale_summaries(pages)
        for s in stale:
            print(f"{s}: differs from the page map; run scripts/book-move.py --summary")
        return 1 if stale else 0
    repair(pages)
    return 0


if __name__ == "__main__":
    sys.exit(main())
