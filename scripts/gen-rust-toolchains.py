#!/usr/bin/env python3
"""Generate `config/rust-toolchains.txt` — every pinned Rust toolchain the tree names.

Issue 1868. Merge-gating CI jobs installed toolchains at RUN time: the CI image
baked a floating `stable` and the pinned nightly, while the root
`rust-toolchain.toml` pins `1.99.0` and `packages/verification/nros-verification`
pins `1.93.0`. So the first `cargo` under either directory made the rustup proxy
download a channel from static.rust-lang.org in the middle of a gate, and a
failed download was a red `CI` with nothing wrong in the change
(`channel-rust-1.99.0.toml.sha256` in `setup-cli`, `channel-rust-1.93.0` in
`leaf-lockfiles`).

The fix is to bake every pinned channel, with the components and targets its
files declare, into `ci/docker/ci-base`. The image cannot read the toolchain
files themselves (its build context is the few files its `.dockerignore`
names), so this script folds them into ONE list the image COPYs and
`scripts/lib/install-rust-toolchains.sh` installs. The list is DERIVED, and
`--check` (gate `check-rust-toolchains-list`) refuses drift, so a toolchain bump
that forgets the list fails before it merges instead of downloading at run time
on every lane after it does.

Format, one channel per line, tab-separated, `-` for an empty set:

    <channel>  <components,comma,separated>  <targets,comma,separated>  <source files>

The ROOT `rust-toolchain.toml`'s channel is the first line: the image makes it
the default toolchain. Components and targets are the union over every file
naming that channel.

Run:  python3 scripts/gen-rust-toolchains.py [--check | --stdout | --files]
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "config" / "rust-toolchains.txt"

HEADER = """\
# GENERATED by scripts/gen-rust-toolchains.py from every tracked
# rust-toolchain.toml — do not edit; re-run the script (issue 1868).
# Gate: check-rust-toolchains-list. Consumers: ci/docker/ci-base/Dockerfile
# (bakes each channel) and scripts/lib/install-rust-toolchains.sh.
#
# channel<TAB>components<TAB>targets<TAB>sources   (`-` = none; line 1 = root)
"""


def toolchain_files():
    """Every tracked rust-toolchain file, the root first.

    The git index, never a walk: a walk reaches other agents' worktrees under
    `.claude/` and every build dir (issue 1565). Submodules are not entered,
    which is right — a vendored crate's pin is not one our lanes install.
    """
    out = subprocess.run(
        ["git", "-C", str(REPO), "ls-files", "--", "*rust-toolchain.toml", "*rust-toolchain"],
        check=True, capture_output=True, text=True,
    ).stdout.split()
    files = sorted(set(out))
    for root in ("rust-toolchain.toml", "rust-toolchain"):
        if root in files:
            files.remove(root)
            files.insert(0, root)
    return files


def _array(text, key):
    m = re.search(r"^\s*%s\s*=\s*\[(.*?)\]" % key, text, re.M | re.S)
    if not m:
        return []
    return re.findall(r'"([^"]+)"', m.group(1))


def parse_text(text, where="<text>"):
    """(channel, components, targets) of one toolchain file's TEXT."""
    text = "\n".join(line.split("#", 1)[0] for line in text.splitlines())
    m = re.search(r'^\s*channel\s*=\s*"([^"]+)"', text, re.M)
    if not m:
        raise SystemExit("gen-rust-toolchains: no `channel = \"...\"` in %s" % where)
    return m.group(1), _array(text, "components"), _array(text, "targets")


def fold(parsed):
    """The list's text, from [(source, (channel, components, targets))], in order."""
    order, comps, targets, sources = [], {}, {}, {}
    for f, (ch, c, t) in parsed:
        if ch not in comps:
            order.append(ch)
            comps[ch], targets[ch], sources[ch] = set(), set(), []
        comps[ch].update(c)
        targets[ch].update(t)
        sources[ch].append(f)
    if not order:
        raise SystemExit("gen-rust-toolchains: no tracked rust-toolchain file")
    lines = [HEADER]
    for ch in order:
        lines.append("\t".join([
            ch,
            ",".join(sorted(comps[ch])) or "-",
            ",".join(sorted(targets[ch])) or "-",
            " ".join(sources[ch]),
        ]) + "\n")
    return "".join(lines)


def render():
    return fold([(f, parse_text((REPO / f).read_text(), f)) for f in toolchain_files()])


def self_test():
    """Negative controls, on the normal path (check-gate-selftests)."""
    bad = []
    root = parse_text(
        '[toolchain]\nchannel = "1.99.0"  # pinned\n'
        'components = ["rustfmt", "clippy"]\n'
        'targets = [\n    "thumbv7m-none-eabi",\n    # "commented-out",\n'
        '    "aarch64-unknown-none",\n]\n')
    if root != ("1.99.0", ["rustfmt", "clippy"], ["thumbv7m-none-eabi", "aarch64-unknown-none"]):
        bad.append("multi-line targets / trailing comment parsed as %r" % (root,))
    bare = parse_text('[toolchain]\nchannel = "1.93.0"\n')
    if bare != ("1.93.0", [], []):
        bad.append("a bare channel parsed as %r" % (bare,))
    text = fold([
        ("rust-toolchain.toml", root),
        ("a/rust-toolchain.toml", ("nightly-x", ["rust-src"], [])),
        ("b/rust-toolchain.toml", ("nightly-x", ["miri"], ["x86_64-unknown-none"])),
        ("c/rust-toolchain.toml", bare),
    ])
    rows = [l.split("\t") for l in text.splitlines() if l and not l.startswith("#")]
    if [r[0] for r in rows] != ["1.99.0", "nightly-x", "1.93.0"]:
        bad.append("the root channel is not line 1, or a channel repeated: %r" % rows)
    elif rows[1][1:3] != ["miri,rust-src", "x86_64-unknown-none"] or rows[2][1:3] != ["-", "-"]:
        bad.append("components/targets are not the per-channel union: %r" % rows)
    # The stale direction must be detectable: a list missing a channel differs.
    if fold([("rust-toolchain.toml", root)]) == text:
        bad.append("dropping a channel does not change the list")
    for b in bad:
        print("  self-test FAIL: " + b)
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="fail when the committed list is stale")
    g.add_argument("--stdout", action="store_true", help="print the list instead of writing it")
    g.add_argument("--files", action="store_true", help="print the toolchain files, one per line")
    args = ap.parse_args()

    if args.files:
        print("\n".join(toolchain_files()))
        return 0
    text = render()
    if args.stdout:
        sys.stdout.write(text)
        return 0
    if args.check:
        if self_test():
            return 1
        have = OUT.read_text() if OUT.is_file() else ""
        if have != text:
            print("check-rust-toolchains-list: config/rust-toolchains.txt is STALE against the")
            print("  tracked rust-toolchain.toml files (issue 1868). The CI image bakes that list,")
            print("  so a channel missing from it is downloaded at RUN time inside a merge-gating")
            print("  job. Regenerate and commit it:")
            print("    python3 scripts/gen-rust-toolchains.py")
            print("  (the ci-base image republishes on merge: the file is in images.yml's filter)")
            return 1
        n = sum(1 for l in text.splitlines() if l and not l.startswith("#"))
        print("check-rust-toolchains-list: OK — %d pinned channel(s)" % n)
        return 0
    OUT.write_text(text)
    print("wrote %s" % OUT.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
