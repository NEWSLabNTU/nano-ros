#!/usr/bin/env python3
"""A release's notes: one book page per release, and the GitHub release body.

User ruling (2026-11-15): a release's notes are written in the book, one file
per release, and `release-nros.yml` publishes that file as the GitHub release
body. A release whose file is missing is REFUSED, and the refusal fires in the
dry run (`publish=false`) too, so a missing page surfaces when the release is
rehearsed rather than at the moment it is cut. `0.6.0-nros11` is the first
release that goes through it.

The file is named by the FULL store version the workflow is dispatched with
(`book/src/migrating/releases/0.6.0-nros11.md`), so nothing maps one spelling
to another. The body is the page minus its leading `# ` title (the release
already carries the title `nros <version>`, and GitHub would show it twice),
then a GENERATED footer: the codegen version the built binary reports and the
install line. Page = prose, workflow = facts (manager ruling 2026-11-15): a
fact the workflow already knows is never hand-copied into the page, because a
copy is how it drifts, so a page that types the install line is refused.

  release_notes.py --check <version>        refuse a missing or empty page (the workflow's early step)
  release_notes.py --body <version> <out> --codegen <N> --repo <owner/name>
                                            write the release body (page + footer) to <out>
  release_notes.py --self-test              negative controls
  release_notes.py --gate                   self-test, then the workflow reaches the refusal on every run
"""
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RELEASES = Path("book/src/migrating/releases")
VERSION = re.compile(r"^\d+\.\d+\.\d+(-[0-9A-Za-z.]+)?$")


class Refused(Exception):
    pass


def page(version: str, root: Path = ROOT) -> Path:
    if not VERSION.match(version):
        raise Refused(f"`{version}` is not a store version (e.g. 0.6.0-nros11)")
    return root / RELEASES / f"{version}.md"


def body(version: str, root: Path = ROOT) -> str:
    p = page(version, root)
    rel = p.relative_to(root)
    if not p.is_file():
        raise Refused(f"no release notes for {version}: {rel} does not exist. "
                      "A release publishes its book page as the release body, so write the page "
                      "first (book/src/migrating/releases/, one file per release).")
    lines = p.read_text().splitlines()
    i = 0
    while i < len(lines) and not lines[i].strip():
        i += 1
    if i < len(lines) and lines[i].startswith("# "):
        i += 1
    text = "\n".join(lines[i:]).strip()
    if not text:
        raise Refused(f"the release notes for {version} are empty: {rel} has no body under its title")
    if INSTALL_LINE.search(text):
        raise Refused(f"{rel} types the install line; the workflow appends it (and the codegen "
                      "version) as a generated footer, so delete it from the page")
    return text + "\n"


INSTALL_LINE = re.compile(r"scripts/install\.sh\s*\|\s*sh")


def footer(codegen: str, repo: str) -> str:
    if not re.fullmatch(r"\d+", codegen or ""):
        raise Refused(f"codegen version `{codegen}` is not a number (from `nros --codegen-version`)")
    if not re.fullmatch(r"[\w.-]+/[\w.-]+", repo or ""):
        raise Refused(f"`{repo}` is not <owner>/<name>")
    return "\n".join([
        "---",
        "",
        f"Codegen version **{codegen}**. A project generated by a release that declares the same",
        "codegen version needs no re-emit (RFC-0097 D7): `nros pin <version>` reads both manifests",
        "out of your store and says so before it moves your `nros-toolchain.toml`.",
        "",
        "Install:",
        "",
        "```",
        f"curl -fsSL https://raw.githubusercontent.com/{repo}/main/scripts/install.sh | sh",
        "```",
        "",
        "Contributors build from source instead: inside a checkout the tree's own build is the only",
        "correct binary.",
        "",
    ])


def release_body(version: str, codegen: str, repo: str, root: Path = ROOT) -> str:
    return body(version, root) + "\n" + footer(codegen, repo)


WORKFLOW = Path(".github/workflows/release-nros.yml")


def wiring_problems(workflow_text: str) -> list:
    """The refusal is only a refusal if the workflow reaches it on EVERY run.

    The `--check` step must be in the build job, unconditional (no `if:`, so a
    dry run reaches it), and ahead of every step that builds; the publish step,
    in whichever job holds it (`publish` since phase-551 W8), must take its body
    from `--body`.
    """
    import yaml

    wf = yaml.safe_load(workflow_text) or {}
    jobs = wf.get("jobs") or {}
    steps = (jobs.get("build") or {}).get("steps") or []
    every_step = [s for j in jobs.values() for s in ((j or {}).get("steps") or [])]
    bad = []
    check_at = next((i for i, s in enumerate(steps)
                     if "release_notes.py --check" in str(s.get("run", ""))), None)
    if check_at is None:
        bad.append("the build job has no `release_notes.py --check` step")
    else:
        if "if" in steps[check_at]:
            bad.append("the `--check` step is conditional, so a dry run can skip it")
        before = [s.get("name", s.get("uses", "?")) for s in steps[:check_at] if "run" in s]
        if before:
            bad.append(f"the `--check` step runs after {before}; it must come before anything builds")
    pub = [s for s in every_step if "gh release create" in str(s.get("run", ""))]
    if not pub:
        bad.append("no step runs `gh release create`")
    for s in pub:
        run = str(s.get("run", ""))
        if "release_notes.py --body" not in run:
            bad.append("the publish step does not take its body from `release_notes.py --body`")
        elif "--codegen" not in run:
            bad.append("the publish step's `--body` is not given `--codegen`, so the footer has no codegen version")
    return bad


def self_test(quiet: bool = False) -> None:
    """Each case must give the stated answer, or the refusal is not a refusal."""
    cases = []
    with tempfile.TemporaryDirectory() as d:
        root = Path(d)
        rel = root / RELEASES
        rel.mkdir(parents=True)

        def refused(version):
            try:
                body(version, root)
                return False
            except Refused:
                return True

        cases.append(("a missing page is refused", refused("0.6.0-nros11")))
        (rel / "0.6.0-nros11.md").write_text("# nros 0.6.0-nros11\n\n")
        cases.append(("a title-only page is refused", refused("0.6.0-nros11")))
        (rel / "0.6.0-nros11.md").write_text("")
        cases.append(("an empty page is refused", refused("0.6.0-nros11")))
        (rel / "0.6.0-nros11.md").write_text("# nros 0.6.0-nros11\n\nCodegen 22.\n\n- one\n")
        cases.append(("a written page passes, minus its title",
                      not refused("0.6.0-nros11") and body("0.6.0-nros11", root) == "Codegen 22.\n\n- one\n"))
        (rel / "nros11.md").write_text("# nros11\n\ntext\n")
        cases.append(("the short spelling does not stand in for the version", refused("0.6.0-nros12")))
        cases.append(("a page with no title is the body as written",
                      (rel / "0.6.0-nros13.md").write_text("text\n") is not None
                      and body("0.6.0-nros13", root) == "text\n"))
        # A page that EXISTS outside the releases directory, so only the
        # version check can refuse it.
        (rel.parent / "escape.md").write_text("# x\n\ntext\n")
        cases.append(("a non-version is refused even when its path exists", refused("../escape")))
        (rel / "0.6.0-nros14.md").write_text("# x\n\ncurl -fsSL https://x/scripts/install.sh | sh\n")
        cases.append(("a page that types the install line is refused", refused("0.6.0-nros14")))
        full = release_body("0.6.0-nros11", "22", "o/r", root)
        cases.append(("the body is the page, then the generated footer",
                      full.startswith("Codegen 22.\n\n- one\n\n---\n")
                      and "Codegen version **22**" in full and "githubusercontent.com/o/r/main/scripts/install.sh" in full))
        for bad_cg in ("", "v21", "21\n"):
            try:
                footer(bad_cg, "o/r")
                cases.append((f"a codegen of {bad_cg!r} is refused", False))
            except Refused:
                cases.append((f"a codegen of {bad_cg!r} is refused", True))

    check = {"name": "notes", "run": 'python3 scripts/lib/release_notes.py --check "$VERSION"'}
    build = {"name": "build", "run": "cargo build"}
    pub = {"name": "publish", "if": "${{ inputs.publish }}",
           "run": 'python3 scripts/lib/release_notes.py --body "$VERSION" n.md --codegen "$cg" --repo o/r\ngh release create t'}

    def wf(*steps):
        import yaml
        return yaml.safe_dump({"jobs": {"build": {"steps": [{"uses": "actions/checkout@v4"}, *steps]}}})

    cases.append(("a wired workflow passes", wiring_problems(wf(check, build, pub)) == []))
    cases.append(("no `--check` step fails", wiring_problems(wf(build, pub)) != []))
    cases.append(("a `--check` gated on publish fails",
                  wiring_problems(wf({**check, "if": "${{ inputs.publish }}"}, build, pub)) != []))
    cases.append(("a `--check` after the build fails", wiring_problems(wf(build, check, pub)) != []))
    cases.append(("a body with no generated codegen fails",
                  wiring_problems(wf(check, build, {**pub, "run": 'python3 scripts/lib/release_notes.py --body "$V" n.md\ngh release create t'})) != []))
    cases.append(("a body not from the page fails",
                  wiring_problems(wf(check, build, {**pub, "run": "gh release create t --notes x"})) != []))
    # phase-551 W8: the publish step in its own job, after every build row.
    import yaml as _yaml
    split = _yaml.safe_dump({"jobs": {
        "build": {"steps": [{"uses": "actions/checkout@v4"}, check, build]},
        "publish": {"steps": [{"uses": "actions/checkout@v4"}, pub]}}})
    cases.append(("a publish step in its own job passes", wiring_problems(split) == []))
    bad_split = _yaml.safe_dump({"jobs": {
        "build": {"steps": [{"uses": "actions/checkout@v4"}, check, build]},
        "publish": {"steps": [{**pub, "run": "gh release create t --notes x"}]}}})
    cases.append(("a publish job whose body is not from the page fails",
                  wiring_problems(bad_split) != []))
    failed = [name for name, ok in cases if not ok]
    if failed:
        sys.exit("release_notes.py: SELFTEST FAILED -- " + "; ".join(failed))
    if not quiet:
        print(f"release_notes.py: selftest OK ({len(cases)} cases)")


def main(argv) -> int:
    try:
        if argv[:1] == ["--self-test"] and len(argv) == 1:
            self_test()
            return 0
        if argv[:1] == ["--gate"] and len(argv) == 1:
            self_test(quiet=True)
            bad = wiring_problems((ROOT / WORKFLOW).read_text())
            if bad:
                print(f"check-release-notes: FAILED -- {WORKFLOW}:", file=sys.stderr)
                for b in bad:
                    print(f"  {b}", file=sys.stderr)
                return 1
            print(f"check-release-notes: OK (a missing page is refused, and {WORKFLOW} refuses it on every run)")
            return 0
        if argv[:1] == ["--check"] and len(argv) == 2:
            self_test(quiet=True)
            body(argv[1])
            print(f"release notes: OK ({page(argv[1]).relative_to(ROOT)})")
            return 0
        if argv[:1] == ["--body"] and len(argv) == 7 and argv[3] == "--codegen" and argv[5] == "--repo":
            Path(argv[2]).write_text(release_body(argv[1], argv[4], argv[6]))
            return 0
    except Refused as e:
        print(f"release notes: REFUSED -- {e}", file=sys.stderr)
        return 1
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
