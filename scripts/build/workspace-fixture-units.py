#!/usr/bin/env python3
"""Partition workspace-fixture rows into BUILD UNITS that may run at once.

phase-535 W3. `workspace-fixtures-build.sh` used to fan out one make target
per workspace DIRECTORY and build every row of a directory serially. That was
right while a workspace held two or three rows. The phase-535 pilot moved the
FreeRTOS example pairs into the four language workspaces, which made the
per-language chains 9/11/7 rows long, and the measured wall clock grew 63 %
while the CPU fell 14 %: the work got cheaper and stopped overlapping.

Two rows of one workspace may build at once unless they WRITE the same thing.
What a row writes, by road:

  cmake  its `build_subdir` — one `nros build` configure (the generated root
         `build/<coord>/CMakeLists.txt` and the ninja tree under it). Rows that
         share a configure are the cheap case (the second image is a link), and
         they must never build concurrently.
  cargo  its `target_dir` (default `target`) — cargo locks a target dir, so two
         rows on one would only queue on that lock while holding pool tokens.
  both   the generated entry of its image, `build/<coord>/<entry>/`, keyed on
         `<bringup>:<image>`; two rows naming the same image write it.

So rows are joined when they share any of those keys, transitively, and every
resulting unit is independent of every other. What is NOT a key:

  codegen_out  `nros dev codegen system --out` writes it, and rows of one
               bringup share it, but no build reads it (an image row's entry is
               generated by `nros build`). Joining on it would chain every
               image of a bringup; the builder serialises that one step with a
               lock instead.
  the workspace's sync outputs  `nros configure` runs once per workspace,
               serially, before any unit starts; the implicit configure inside
               each `nros build` takes the project's exclusive lock and finds
               the stamp current.

Input: the `\\x1f`-separated records of `fixtures-manifest.py list-workspaces`
on stdin, one per line. Output (`group`): `<unit>\\t<record>` per record, units
numbered from 0 in order of first appearance, records in input order.
`plan` prints the same partition for a reader.
"""

from __future__ import annotations

import sys

SEP = "\x1f"


def keys(record: str) -> list[str]:
    f = record.split(SEP)
    f += [""] * (14 - len(f))
    _id, lang, ws, bringup, _entry, build_subdir, target_dir = f[:7]
    image = f[13]
    out = []
    if lang == "rust":
        out.append(f"{ws}|cargo:{target_dir or 'target'}")
    else:
        out.append(f"{ws}|cmake:{build_subdir}")
    if image:
        out.append(f"{ws}|image:{bringup.rstrip('/').rsplit('/', 1)[-1]}:{image}")
    return out


def group(records: list[str]) -> list[int]:
    parent: dict[str, str] = {}

    def find(k: str) -> str:
        parent.setdefault(k, k)
        while parent[k] != k:
            parent[k] = parent[parent[k]]
            k = parent[k]
        return k

    for r in records:
        ks = keys(r)
        for k in ks[1:]:
            a, b = find(ks[0]), find(k)
            if a != b:
                parent[b] = a
    unit_of_root: dict[str, int] = {}
    units = []
    for r in records:
        root = find(keys(r)[0])
        if root not in unit_of_root:
            unit_of_root[root] = len(unit_of_root)
        units.append(unit_of_root[root])
    return units


def _rec(id_, lang, ws, bringup="src/b", subdir="", target="", image=""):
    f = [id_, lang, ws, bringup, "e", subdir, target] + [""] * 6 + [image]
    return SEP.join(f)


def self_test() -> int:
    cases = [
        (
            "one cmake configure is one unit; another configure is another",
            [
                _rec("a", "c", "w", subdir="build/x/cmake", image="i1"),
                _rec("b", "c", "w", subdir="build/x/cmake", image="i2"),
                _rec("c", "c", "w", subdir="build/y/cmake", image="i3"),
            ],
            [0, 0, 1],
        ),
        (
            "cargo rows on distinct target dirs fan out",
            [
                _rec("a", "rust", "w", target="t/a", image="i1"),
                _rec("b", "rust", "w", target="t/b", image="i2"),
            ],
            [0, 1],
        ),
        (
            "cargo rows on one target dir (or both defaulted) are one unit",
            [
                _rec("a", "rust", "w", target="t", image="i1"),
                _rec("b", "rust", "w", target="t", image="i2"),
                _rec("c", "rust", "w", image="i3"),
                _rec("d", "rust", "w", image="i4"),
            ],
            [0, 0, 1, 1],
        ),
        (
            "one image on two roots shares its generated entry: joined",
            [
                _rec("a", "rust", "w", target="t/a", image="i"),
                _rec("b", "rust", "w", target="t/b", image="i"),
            ],
            [0, 0],
        ),
        (
            "joining is transitive",
            [
                _rec("a", "rust", "w", target="t/a", image="i1"),
                _rec("b", "rust", "w", target="t/b", image="i1"),
                _rec("c", "rust", "w", target="t/b", image="i2"),
                _rec("d", "rust", "w", target="t/d", image="i3"),
            ],
            [0, 0, 0, 1],
        ),
        (
            "the same keys in two workspaces are two units",
            [
                _rec("a", "c", "w1", subdir="build/x/cmake", image="i"),
                _rec("b", "c", "w2", subdir="build/x/cmake", image="i"),
            ],
            [0, 1],
        ),
        (
            "same image id under two bringups is two images",
            [
                _rec("a", "c", "w", "src/b1", subdir="build/x/cmake", image="i"),
                _rec("b", "c", "w", "src/b2", subdir="build/y/cmake", image="i"),
            ],
            [0, 1],
        ),
        (
            "rows sharing only codegen_out are NOT joined",
            [
                SEP.join(
                    ["a", "rust", "w", "src/b", "e", "", "t/a", "out"]
                    + [""] * 5
                    + ["i1"]
                ),
                SEP.join(
                    ["b", "rust", "w", "src/b", "e", "", "t/b", "out"]
                    + [""] * 5
                    + ["i2"]
                ),
            ],
            [0, 1],
        ),
    ]
    bad = 0
    for name, recs, want in cases:
        got = group(recs)
        if got != want:
            print(f"FAIL: {name}: want {want}, got {got}", file=sys.stderr)
            bad += 1
    if bad:
        return 1
    print(f"workspace-fixture-units self-test: {len(cases)} case(s) OK")
    return 0


def main(argv: list[str]) -> int:
    mode = argv[1] if len(argv) > 1 else ""
    if mode == "--self-test":
        return self_test()
    if mode not in ("group", "plan"):
        print(
            "usage: workspace-fixture-units.py group|plan|--self-test < records",
            file=sys.stderr,
        )
        return 2
    records = [line.rstrip("\n") for line in sys.stdin if line.strip()]
    units = group(records)
    if mode == "group":
        for u, r in zip(units, records):
            print(f"{u}\t{r}")
        return 0
    n = max(units) + 1 if units else 0
    print(f"{len(records)} row(s) in {n} unit(s)")
    for u in range(n):
        rows = [r for uu, r in zip(units, records) if uu == u]
        first = rows[0].split(SEP)
        print(f"  unit {u}: {first[2]} [{keys(rows[0])[0].split('|', 1)[1]}]")
        for r in rows:
            print(f"    {r.split(SEP)[0]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
