#!/usr/bin/env python3
"""Partition workspace-fixture rows into BUILD UNITS that may run at once.

phase-535 W3. `workspace-fixtures-build.sh` used to fan out one make target
per workspace DIRECTORY and build every row of a directory serially. That was
right while a workspace held two or three rows. The phase-535 pilot moved the
FreeRTOS example pairs into the four language workspaces, which made the
per-language chains 9/11/7 rows long, and the measured wall clock grew 63 %
while the CPU fell 14 %: the work got cheaper and stopped overlapping.

Two rows of one workspace may build at once unless they WRITE the same thing.
What a row writes, by road:

  cmake  its `build_subdir` — one `nros build` configure (the generated root
         `build/<coord>/CMakeLists.txt` and the ninja tree under it). Rows that
         share a configure are the cheap case (the second image is a link), and
         they must never build concurrently.
  cargo  its `target_dir` (default `target`) — cargo locks a target dir, so two
         rows on one would only queue on that lock while holding pool tokens.
  both   the generated entry of its image, `build/<coord>/<entry>/`, keyed on
         `<bringup>:<image>`; two rows naming the same image write it.

So rows are joined when they share any of those keys, transitively, and every
resulting unit is independent of every other. What is NOT a key:

  codegen_out  `nros dev codegen system --out` writes it, and rows of one
               bringup share it, but no build reads it (an image row's entry is
               generated by `nros build`). Joining on it would chain every
               image of a bringup; the builder serialises that one step with a
               lock instead.
  the workspace's sync outputs  `nros configure` runs once per workspace,
               serially, before any unit starts; the implicit configure inside
               each `nros build` takes the project's exclusive lock and finds
               the stamp current.

Issue 2840 (c2) — ORDER across units, by build class. Under the lane's
`NROS_BUILD_CLASS_ROOT` every cargo image of one build class shares ONE cargo
build dir, and cargo locks a build dir for a whole invocation: the leaves of a
class queue on it, each holding a pool slot while it waits. So the unit that
holds the FIRST row of a class LEADS it, and every other unit with a row of
that class waits for its leader (`after`): the leader builds the class's
shared units while the classes' leaders run side by side, and the rest then
reuse them. A leader waits for nothing, so the edges form no cycle. The class
key itself is computed by `nros build`, so this orders by a proxy the record
states (`class_proxy`); a wrong guess costs parallelism, never correctness.

Input: the `\\x1f`-separated records of `fixtures-manifest.py list-workspaces`
on stdin, one per line. Output (`group`): `<unit>\\t<record>` per record, units
numbered from 0 in order of first appearance, records in input order.
`plan` prints the same partition for a reader.
"""

from __future__ import annotations

import sys

SEP = "\x1f"


def row_road(lang: str, builder: str) -> str:
    """Issue 2463 — the road a row builds on: its authored `builder`, else its
    language. The Python twin of `nros_ws_row_road` (scripts/lib/fixture-road.sh);
    `check-workspace-fixture-road` holds the two to each other."""
    return builder or ("cargo" if lang == "rust" else "cmake")


def keys(record: str) -> list[str]:
    f = record.split(SEP)
    f += [""] * (15 - len(f))
    _id, lang, ws, bringup, _entry, build_subdir, target_dir = f[:7]
    image = f[13]
    # phase-535 W6 — the row's authored builder (15th column, present only when
    # authored) wins over the language, as in `workspace-fixtures-build.sh`.
    road = row_road(lang, f[14])
    out = []
    if road == "cargo":
        out.append(f"{ws}|cargo:{target_dir or 'target'}")
    else:
        out.append(f"{ws}|cmake:{build_subdir}")
    if image:
        out.append(f"{ws}|image:{bringup.rstrip('/').rsplit('/', 1)[-1]}:{image}")
    return out


def group(records: list[str]) -> list[int]:
    parent: dict[str, str] = {}

    def find(k: str) -> str:
        parent.setdefault(k, k)
        while parent[k] != k:
            parent[k] = parent[parent[k]]
            k = parent[k]
        return k

    for r in records:
        ks = keys(r)
        for k in ks[1:]:
            a, b = find(ks[0]), find(k)
            if a != b:
                parent[b] = a
    unit_of_root: dict[str, int] = {}
    units = []
    for r in records:
        root = find(keys(r)[0])
        if root not in unit_of_root:
            unit_of_root[root] = len(unit_of_root)
        units.append(unit_of_root[root])
    return units


def class_proxy(record: str) -> str | None:
    """Issue 2840 — a cargo row's stand-in for its build class: what the record
    states of the image's configuration (image id, env, cargo args, board).
    None for a cmake row, which has no shared class dir."""
    f = record.split(SEP)
    f += [""] * (15 - len(f))
    if row_road(f[1], f[14]) != "cargo":
        return None
    return "|".join([f[13], f[9], f[10], f[11]])


def after(records: list[str], units: list[int]) -> dict[int, list[int]]:
    """Issue 2840 — for each unit that leads no class, the leader units of the
    classes it holds rows of. A class's leader is its SMALLEST unit (fewest
    rows, then first), so the wait behind it is one image build and never a
    workspace's serial chain; leaders get no edge."""
    size: dict[int, int] = {}
    for u in units:
        size[u] = size.get(u, 0) + 1
    leader: dict[str, int] = {}
    for r, u in zip(records, units):
        c = class_proxy(r)
        if c is not None and (c not in leader or (size[u], u) < (size[leader[c]], leader[c])):
            leader[c] = u
    leading = set(leader.values())
    out: dict[int, list[int]] = {}
    for r, u in zip(records, units):
        c = class_proxy(r)
        if c is None or u in leading:
            continue
        lu = leader[c]
        if lu != u and lu not in out.setdefault(u, []):
            out[u].append(lu)
    return {u: sorted(v) for u, v in out.items() if v}


def _rec(id_, lang, ws, bringup="src/b", subdir="", target="", image=""):
    f = [id_, lang, ws, bringup, "e", subdir, target] + [""] * 6 + [image]
    return SEP.join(f)


def self_test() -> int:
    cases = [
        (
            "one cmake configure is one unit; another configure is another",
            [
                _rec("a", "c", "w", subdir="build/x/cmake", image="i1"),
                _rec("b", "c", "w", subdir="build/x/cmake", image="i2"),
                _rec("c", "c", "w", subdir="build/y/cmake", image="i3"),
            ],
            [0, 0, 1],
        ),
        (
            "cargo rows on distinct target dirs fan out",
            [
                _rec("a", "rust", "w", target="t/a", image="i1"),
                _rec("b", "rust", "w", target="t/b", image="i2"),
            ],
            [0, 1],
        ),
        (
            "cargo rows on one target dir (or both defaulted) are one unit",
            [
                _rec("a", "rust", "w", target="t", image="i1"),
                _rec("b", "rust", "w", target="t", image="i2"),
                _rec("c", "rust", "w", image="i3"),
                _rec("d", "rust", "w", image="i4"),
            ],
            [0, 0, 1, 1],
        ),
        (
            "one image on two roots shares its generated entry: joined",
            [
                _rec("a", "rust", "w", target="t/a", image="i"),
                _rec("b", "rust", "w", target="t/b", image="i"),
            ],
            [0, 0],
        ),
        (
            "joining is transitive",
            [
                _rec("a", "rust", "w", target="t/a", image="i1"),
                _rec("b", "rust", "w", target="t/b", image="i1"),
                _rec("c", "rust", "w", target="t/b", image="i2"),
                _rec("d", "rust", "w", target="t/d", image="i3"),
            ],
            [0, 0, 0, 1],
        ),
        (
            "the same keys in two workspaces are two units",
            [
                _rec("a", "c", "w1", subdir="build/x/cmake", image="i"),
                _rec("b", "c", "w2", subdir="build/x/cmake", image="i"),
            ],
            [0, 1],
        ),
        (
            "same image id under two bringups is two images",
            [
                _rec("a", "c", "w", "src/b1", subdir="build/x/cmake", image="i"),
                _rec("b", "c", "w", "src/b2", subdir="build/y/cmake", image="i"),
            ],
            [0, 1],
        ),
        (
            "rows sharing only codegen_out are NOT joined",
            [
                SEP.join(
                    ["a", "rust", "w", "src/b", "e", "", "t/a", "out"]
                    + [""] * 5
                    + ["i1"]
                ),
                SEP.join(
                    ["b", "rust", "w", "src/b", "e", "", "t/b", "out"]
                    + [""] * 5
                    + ["i2"]
                ),
            ],
            [0, 1],
        ),
    ]
    bad = 0
    for name, recs, want in cases:
        got = group(recs)
        if got != want:
            print(f"FAIL: {name}: want {want}, got {got}", file=sys.stderr)
            bad += 1
    # Issue 2840 — the class order. Each case: records (one unit per
    # workspace), and the `after` edges wanted.
    order_cases = [
        (
            "one class over three leaves: the first leads, the rest wait for it",
            [
                _rec("a", "rust", "w1", image="linux"),
                _rec("b", "rust", "w2", image="linux"),
                _rec("c", "rust", "w3", image="linux"),
            ],
            {1: [0], 2: [0]},
        ),
        (
            "different classes run side by side",
            [
                _rec("a", "rust", "w1", image="linux"),
                _rec("b", "rust", "w2", image="linux_cyclonedds"),
            ],
            {},
        ),
        (
            "crossed classes never wait on each other (no cycle): one unit leads both",
            [
                _rec("a", "rust", "w1", target="t/a", image="linux"),
                _rec("b", "rust", "w2", target="t/b", image="linux_xrce"),
                _rec("c", "rust", "w2", target="t/b", image="linux"),
                _rec("d", "rust", "w1", target="t/a", image="linux_xrce"),
            ],
            {1: [0]},
        ),
        (
            "a cmake row is never ordered",
            [
                _rec("a", "c", "w1", subdir="build/x/cmake", image="linux"),
                _rec("b", "c", "w2", subdir="build/x/cmake", image="linux"),
            ],
            {},
        ),
        (
            "the smallest unit leads, not a long serial chain that came first",
            [
                _rec("a", "rust", "w1", target="t", image="linux"),
                _rec("b", "rust", "w1", target="t", image="linux_two"),
                _rec("c", "rust", "w2", image="linux"),
                _rec("d", "rust", "w3", image="linux_two"),
            ],
            {0: [1, 2]},
        ),
        (
            "a unit trailing two classes waits for both leaders",
            [
                _rec("a", "rust", "w1", image="linux"),
                _rec("b", "rust", "w2", image="linux_xrce"),
                _rec("c", "rust", "w3", target="t", image="linux"),
                _rec("d", "rust", "w3", target="t", image="linux_xrce"),
            ],
            {2: [0, 1]},
        ),
    ]
    for name, recs, want in order_cases:
        got = after(recs, group(recs))
        if got != want:
            print(f"FAIL: {name}: want {want}, got {got}", file=sys.stderr)
            bad += 1
    if bad:
        return 1
    print(
        f"workspace-fixture-units self-test: {len(cases)} partition + "
        f"{len(order_cases)} class-order case(s) OK"
    )
    return 0


def main(argv: list[str]) -> int:
    mode = argv[1] if len(argv) > 1 else ""
    if mode == "--self-test":
        return self_test()
    if mode not in ("group", "plan", "after"):
        print(
            "usage: workspace-fixture-units.py group|plan|after|--self-test < records",
            file=sys.stderr,
        )
        return 2
    records = [line.rstrip("\n") for line in sys.stdin if line.strip()]
    units = group(records)
    if mode == "group":
        for u, r in zip(units, records):
            print(f"{u}\t{r}")
        return 0
    if mode == "after":
        # Issue 2840: `<unit>\t<leader unit> ...`, one line per waiting unit.
        for u, leaders in sorted(after(records, units).items()):
            print(f"{u}\t{' '.join(map(str, leaders))}")
        return 0
    n = max(units) + 1 if units else 0
    print(f"{len(records)} row(s) in {n} unit(s)")
    for u in range(n):
        rows = [r for uu, r in zip(units, records) if uu == u]
        first = rows[0].split(SEP)
        print(f"  unit {u}: {first[2]} [{keys(rows[0])[0].split('|', 1)[1]}]")
        for r in rows:
            print(f"    {r.split(SEP)[0]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
