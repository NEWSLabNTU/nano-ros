#!/usr/bin/env python3
"""Every guard on a knob-sized C array must FIRE at 0, proven by compiling it.

The build-tier half of `check-c-array-pool-floors`. That gate is on the fast
line, must run on a bare worktree, and therefore reasons about the SOURCE: it
checks that a guard sits after the `#ifndef` fallback that defines its knob.
That catches the two shapes that shipped, and nothing else.

This one asks the compiler. It is the only way to answer "can this guard fire"
for a guard that is unreachable for a reason no static rule enumerates -- nested
inside an unrelated `#if`, disabled by a config header, or in a file the
translation unit never reaches.

WHY IT IS A SEPARATE GATE AND NOT A BRANCH OF THE OTHER ONE

It needs the zenoh-pico submodule, which the push lane does not check out. A
gate that silently weakens depending on which lane ran it reports the same OK
either way, and the reader cannot tell which answer they got -- the shape this
campaign has removed four times. Two gates, two lanes, two honest answers.

WHAT IT DOES

For every macro `check-c-array-pool-floors` classifies as GUARDED:

  * compile the file at DEFAULTS and require NO guard to fire. This is the
    half that catches `#607`: a guard placed before its `#define` reads the
    macro as undefined, which the preprocessor evaluates as 0, so it fired on
    every build.
  * compile with `-D<KNOB>=0` and require THAT guard to fire. This is the half
    that catches the first attempted fix: a guard inside the `#ifndef` is
    skipped by the very `-D` it is meant to catch.

Failures that are not a guard diagnostic are ignored on purpose. This asks one
question about the preprocessor; whether the whole TU type-checks is
`check-c`'s job, and coupling the two would make this red for reasons that say
nothing about guards.

Run:  python3 scripts/check-c-array-guard-probe.py [--self-test]
"""

import importlib.util
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# A guard says "must be >= N", and N is not always 1: `STRESS_SIZE`'s floor is
# 16 because `build_payload()` writes a 12-byte header with no bounds test
# (issue 1131). Matching the literal "must be >= 1" read every such guard as
# absent — and this gate reports an unreachable guard and a MISSPELLED one with
# the same message, so a substring was the wrong thing to key on.
GUARD_TEXT = re.compile(r"must be >= \d+")

# HOW EACH GUARDED FILE IS REACHED (issue 1131).
#
# This table used to be one hardcoded include set, because every guarded array
# lived in `zpico.c`. When issue 1131 ruled nine more knobs in six other files,
# the gate went red on all nine at once — not because a guard was unreachable
# but because the probe could not compile a ThreadX, Zephyr or XRCE translation
# unit with zenoh-pico's flags. A gate whose reach is narrower than the rule it
# enforces is issue 0196's shape, and here it failed CLOSED, which is the good
# direction and still wrong.
#
# Two modes, and the difference is stated per file rather than inferred:
#
#   "compile"     the real translation unit, real headers, `-fsyntax-only`.
#                 The strongest answer: an enclosing `#if` fed by a config
#                 header is evaluated as the build evaluates it.
#
#   "preprocess"  `#include` lines stripped, and every enclosing condition the
#                 guard sits under SUPPLIED here by name. For a file whose
#                 headers belong to a cross toolchain no host lane has, this is
#                 the honest maximum: it still proves the guard is positioned
#                 correctly relative to its own `#ifndef` and fires at 0, and it
#                 still catches both shapes that shipped (#607 and its first
#                 fix). What it CANNOT catch is an enclosing condition that is
#                 false in every real build — so that condition is written down
#                 here, where a reviewer can disagree with it.
#
# A guarded file in NEITHER mode is a failure. The gate must not grow a guard it
# silently does not probe.
