INCLUDE_LINE = re.compile(r"^\s*#\s*include\b")

# The submodule whose absence means this gate cannot run. Named as a FILE, not a
# directory: an initialised-but-empty submodule dir is the state that makes a
# "does the directory exist" probe lie.
SUBMODULE_PROBE = "packages/rmw/zenoh/zpico-sys/zenoh-pico/include/zenoh-pico/config.h"


def guarded_knobs():
    """{macro: path} for everything the source-level gate calls GUARDED."""
    path = os.path.join(ROOT, "scripts", "check-c-array-pool-floors.py")
    spec = importlib.util.spec_from_file_location("pool_floors", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    found = mod.scan(mod.read_sources())
    return {m: i["path"] for m, i in found.items() if i["guarded"]}


def compile_probe(rel_path, extra, ctx=None):
    """Guard diagnostics from probing `rel_path`. (text, ran) — never raises.

    `ctx` is the file's `PROBE_CONTEXT` entry; the default keeps the old zpico
    behaviour so the self-test can drive this with synthetic C.
    """
    ctx = ctx or PROBE_CONTEXT["packages/rmw/zenoh/zpico-sys/c/zpico/zpico.c"]
    src = os.path.join(ROOT, rel_path)
    tmp = None
    if ctx["mode"] == "preprocess":
        # Strip the includes rather than resolve them. See PROBE_CONTEXT: this
        # is the honest maximum for a file whose headers belong to a toolchain
        # no host lane has, and every condition it therefore cannot evaluate is
        # supplied by name in `defines`.
        suffix = ".cpp" if ctx["cc"] == "c++" else ".c"
        fd, tmp = tempfile.mkstemp(suffix=suffix)
        with os.fdopen(fd, "w") as out, open(src, errors="ignore") as inp:
            for line in inp:
                out.write("\n" if INCLUDE_LINE.match(line) else line)
        src = tmp
    cmd = [ctx["cc"]]
    cmd += ["-E", "-P"] if ctx["mode"] == "preprocess" else ["-fsyntax-only"]
    cmd += [f"-std={ctx['std']}", *ctx.get("defines", []), *extra]
    for inc in ctx.get("includes", []):
        cmd += ["-I", os.path.join(ROOT, inc)]
    cmd.append(src)
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError) as exc:
        return f"could not run the compiler: {exc}", False
    finally:
        if tmp:
            os.unlink(tmp)
    return r.stderr, True


def main():
    if "--self-test" in sys.argv:
        return self_test()
    if self_test() != 0:
        return 1

    if not os.path.isfile(os.path.join(ROOT, SUBMODULE_PROBE)):
        sys.path.insert(0, os.path.join(ROOT, "scripts", "build"))
        print(
            "[SKIPPED] c-array-guard-probe: zenoh-pico submodule not checked out "
            "(git submodule update --init packages/rmw/zenoh/zpico-sys/zenoh-pico)"
        )
        return 0

    knobs = guarded_knobs()
    if not knobs:
        sys.stderr.write(
            "check-c-array-guard-probe: the source gate reports NO guarded knob, "
            "so this would compile nothing and pass vacuously.\n"
        )
        return 1

    problems = []
    files = sorted(set(knobs.values()))

    # A guarded file this gate does not know how to reach is a FAILURE, never a
    # quiet omission: the whole point is that no guard ships unprobed.
    unknown = [f for f in files if f not in PROBE_CONTEXT]
    for rel in unknown:
        problems.append(
            f"{rel} carries a guard and has no PROBE_CONTEXT entry, so this gate\n"
            "      does not probe it. Add one: `compile` with the include set the\n"
            "      real TU needs, or `preprocess` naming WHY the headers are not\n"
            "      here and WHICH enclosing conditions the guard sits under."
        )

    # The OTHER direction, and the reason it exists (phase-427 W4).
    #
    # The check above asks "is every discovered guard probed?". Nothing asked
    # the reverse — "does every entry still name a file that exists?" — so when
    # `component_node.hpp` was deleted, its key became dead config and this gate
    # kept printing OK over a table with one fewer file. A gate whose subject
    # disappears passes vacuously; that is the failure this campaign keeps
    # hitting, and a table key is exactly where it hides.
    #
    # Keyed on the FILE existing, not on it being discovered: a header that
    # exists but has (legitimately) lost its last guard is not an error, while a
    # key pointing at nothing can only ever be stale.
    for rel in sorted(PROBE_CONTEXT):
        if not os.path.exists(os.path.join(ROOT, rel)):
            problems.append(
                f"{rel} has a PROBE_CONTEXT entry and DOES NOT EXIST. The entry is\n"
                "      dead config: this gate only consults the table for files the\n"
                "      scan discovers, so a key naming a deleted file is never read\n"
                "      and never reported. Move the entry with the guard, or delete it."
            )
    files = [f for f in files if f in PROBE_CONTEXT]

    # One probe per file at defaults: nothing may fire.
    for rel in files:
        out, ran = compile_probe(rel, [], PROBE_CONTEXT[rel])
        if not ran:
            sys.stderr.write(f"check-c-array-guard-probe: {out}\n")
            return 1
        fired = [l for l in out.split("\n") if GUARD_TEXT.search(l)]
        if fired:
            problems.append(
                f"{rel} fires {len(fired)} guard at DEFAULT knob values.\n"
                "      A guard that fires with no `-D` at all is not guarding a "
                "zero — it is\n"
                "      reading its macro as UNDEFINED, which the preprocessor "
                "evaluates as 0.\n"
                "      First: " + fired[0].strip()
            )

    # One probe per knob at zero: exactly that knob's guard must fire.
    for macro, rel in sorted(knobs.items()):
        if rel not in PROBE_CONTEXT:
            continue  # already reported above
        out, ran = compile_probe(rel, [f"-D{macro}=0"], PROBE_CONTEXT[rel])
        if not ran:
            sys.stderr.write(f"check-c-array-guard-probe: {out}\n")
            return 1
        if not any(GUARD_TEXT.search(l) and macro in l for l in out.split("\n")):
            problems.append(
                f"{macro} ({rel}) has a guard that does NOT fire at `-D{macro}=0`.\n"
                "      The `#if` is present but the preprocessor never reaches it "
                "with the\n"
                "      macro set — inside its own `#ifndef` (a `-D` skips the "
                "block), behind\n"
                "      an unrelated `#if`, or in a file this TU does not include."
            )

    if problems:
        sys.stderr.write(
            "check-c-array-guard-probe: %d problem(s)\n\n" % len(problems)
        )
        for p in problems:
            sys.stderr.write(f"  [FAIL] {p}\n\n")
        return 1

    print(
        "check-c-array-guard-probe: OK — %d guard(s) across %d file(s) fire at 0 "
        "and are silent at defaults." % (len(knobs), len(files))
    )
    return 0


def self_test():
    """Prove the probe can fail, on synthetic C rather than on the tree."""
    import tempfile

    good = ("#ifndef K\n#define K 8\n#endif\n"
            "#if K < 1\n#error \"K must be >= 1\"\n#endif\n"
            "int a[K];\n")
    before = ("#if K < 1\n#error \"K must be >= 1\"\n#endif\n"
              "#ifndef K\n#define K 8\n#endif\nint a[K];\n")
    inside = ("#ifndef K\n#define K 8\n"
              "#if K < 1\n#error \"K must be >= 1\"\n#endif\n#endif\n"
              "int a[K];\n")
    bad = 0
    with tempfile.TemporaryDirectory() as d:
        for name, src, want_default, want_zero in [
            ("good", good, 0, 1),
            ("before", before, 1, 1),   # fires with NO -D at all
            ("inside", inside, 0, 0),   # never fires, even at -DK=0
        ]:
            p = os.path.join(d, f"{name}.c")
            open(p, "w").write(src)
            def probe(extra):
                r = subprocess.run(["cc", "-fsyntax-only", "-std=c11", *extra, p],
                                   capture_output=True, text=True)
                return sum(1 for l in r.stderr.split("\n") if "must be >= 1" in l)
            got_d, got_z = min(probe([]), 1), min(probe(["-DK=0"]), 1)
            if (got_d, got_z) != (want_default, want_zero):
                print(f"  self-test FAIL: {name} -> default={got_d} zero={got_z}, "
                      f"want default={want_default} zero={want_zero}")
                bad += 1
    # --- the `preprocess` mode and the floor-above-one guard (issue 1131) ---
    #
    # Six of the seven guarded files belong to a cross toolchain no host lane
    # has, so they are probed with `#include` lines stripped and their enclosing
    # conditions supplied. Two things must stay true of that, or the mode is a
    # way to pass rather than a way to answer: the guard must still FIRE at 0,
    # and it must still be seen NOT to fire when the enclosing condition is
    # absent — otherwise stripping the includes would launder an unreachable
    # guard into a reachable one, which is the failure this gate exists for.
    nested = (
        '#include <a/header/that/does/not/exist.h>\n'
        "#if FEATURE_ON == 1\n"
        "#ifndef K\n#define K 64\n#endif\n"
        '#if K < 16\n#error "K must be >= 16"\n#endif\n'
        "int a[K];\n"
        "#endif\n"
    )
    fd, path = tempfile.mkstemp(suffix=".c")
    with os.fdopen(fd, "w") as fh:
        fh.write(nested)
    try:
        on = {"mode": "preprocess", "cc": "cc", "std": "c11",
              "defines": ["-DFEATURE_ON=1"]}
        off = dict(on, defines=[])

        out, ran = compile_probe(path, [], on)
        assert ran, out
        if GUARD_TEXT.search(out):
            print("  self-test FAIL: preprocess mode fires at DEFAULT")
            bad += 1
        out, ran = compile_probe(path, ["-DK=0"], on)
        # `must be >= 16`, not `>= 1`: a substring match on "must be >= 1" reads
        # this guard as absent, which is how nine correct guards went red.
        if not (ran and GUARD_TEXT.search(out)):
            print("  self-test FAIL: preprocess mode did not fire at -DK=0")
            bad += 1
        out, ran = compile_probe(path, ["-DK=0"], off)
        if not ran or GUARD_TEXT.search(out):
            print("  self-test FAIL: a guard behind an UNSUPPLIED enclosing "
                  "condition must not read as reachable")
            bad += 1
        # And the include really was stripped, not resolved.
        out, ran = compile_probe(path, ["-DK=0"], dict(on, mode="compile"))
        if not ran or GUARD_TEXT.search(out):
            print("  self-test FAIL: compile mode should not reach the guard "
                  "past a missing include")
            bad += 1
    finally:
        os.unlink(path)

    if bad:
        print(f"check-c-array-guard-probe self-test: {bad} case(s) FAILED")
        return 1
    print("check-c-array-guard-probe self-test: OK (7 cases: good, "
          "guard-before-define, guard-inside-ifndef, preprocess x4)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
