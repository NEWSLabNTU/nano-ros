#!/usr/bin/env python3
"""phase-523 W4 — one delta page per fork the tree carries.

Reads `docs/reference/forks/forks.toml` and, for each `[[fork]]`, asks GitHub's
compare API for the commits the pinned fork commit carries on top of the named
upstream ref, then writes `docs/reference/forks/<name>.md` and the index page
`docs/reference/forks/README.md`. The pin is the gitlink the superproject
records (`git ls-files -s <path>`), never a submodule checkout, so the page
describes exactly what a clone builds.

Needs `gh` (authenticated) and the network; run it after moving a fork pin.
`just check fork-deltas` is the offline half: it refuses a page whose pin no
longer matches the gitlink.

  python3 scripts/gen-fork-deltas.py            # write every page
  python3 scripts/gen-fork-deltas.py zenoh-pico # one fork (and the index)
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # Python < 3.11
    import tomli as tomllib  # type: ignore[no-redef]

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "docs/reference/forks/forks.toml"
PAGES = ROOT / "docs/reference/forks"
STAMP = ("<!-- GENERATED by scripts/gen-fork-deltas.py from docs/reference/forks/"
         "forks.toml — do not edit; move the pin or the table and regenerate. -->")
PIN_LINE = "**Pinned commit:**"


def gitlink(path: str) -> str:
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-s", "--", path],
                         check=True, capture_output=True, text=True).stdout.split()
    if len(out) < 2 or out[0] != "160000":
        raise SystemExit(f"{path}: not a submodule gitlink in the index")
    return out[1]


def submodule_url(path: str) -> tuple[str, str]:
    def cfg(key: str) -> str:
        return subprocess.run(["git", "-C", str(ROOT), "config", "-f", ".gitmodules",
                               f"submodule.{path}.{key}"],
                              check=True, capture_output=True, text=True).stdout.strip()
    return cfg("url"), cfg("branch")


def github_repo(url: str) -> str:
    tail = url.split("github.com/", 1)[1] if "github.com/" in url else url.split(":", 1)[1]
    return tail.removesuffix(".git").strip("/")


def compare(upstream: str, base: str, fork: str, pin: str) -> dict:
    owner, repo = fork.split("/")
    out = subprocess.run(
        ["gh", "api", f"repos/{upstream}/compare/{base}...{owner}:{repo}:{pin}"],
        check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def render(row: dict, pin: str, fork: str, branch: str, cmp: dict) -> str:
    commits = cmp.get("commits", [])
    files = cmp.get("files", [])
    adds = sum(f.get("additions", 0) for f in files)
    dels = sum(f.get("deletions", 0) for f in files)
    base_sha = cmp["merge_base_commit"]["sha"]
    lines = [
        STAMP, "",
        f"# The {row['name']} fork: what it carries", "",
        f"nano-ros builds `{row['path']}` from the fork "
        f"[{fork}](https://github.com/{fork}), branch `{branch}`, not from upstream "
        f"[{row['upstream']}](https://github.com/{row['upstream']}).", "",
        "| | |", "| --- | --- |",
        f"| Upstream base | `{row['base']}` (merge base "
        f"[{base_sha[:12]}](https://github.com/{row['upstream']}/commit/{base_sha})) |",
        f"| Commits on top | {cmp['ahead_by']} |",
        f"| Upstream commits the pin lacks | {cmp['behind_by']} |",
        f"| Files changed | {len(files)}{'+' if len(files) >= 300 else ''}, "
        f"+{adds}/−{dels} |", "",
        f"{PIN_LINE} `{pin}`", "",
    ]
    if row.get("notes"):
        lines += [f"Why each patch exists, and what retires it: [{row['notes']}](../{row['notes']}).", ""]
    if cmp["behind_by"]:
        lines += [f"The pin is {cmp['behind_by']} upstream commit(s) behind `{row['base']}`'s "
                  "tip; the delta below is against the merge base.", ""]
    lines += ["## Commits on top of upstream", "", "| commit | subject |", "| --- | --- |"]
    for c in commits:
        subject = c["commit"]["message"].splitlines()[0].replace("|", "\\|")
        # A link, not a backticked hash: the commit is in the FORK, never in
        # this repository, and `check-doc-commit-citations` reads a backticked
        # 9-10 hex string as a claim about this repository's history.
        lines.append(f"| [{c['sha'][:10]}](https://github.com/{fork}/commit/{c['sha']}) "
                     f"| {subject} |")
    if len(commits) < cmp["ahead_by"]:
        lines += ["", f"The compare API lists {len(commits)} of {cmp['ahead_by']}; "
                  f"the rest: `git log {base_sha[:12]}..{pin[:12]}` in the fork."]
    lines += ["", "Reproduce:", "", "```bash",
              f"gh api repos/{row['upstream']}/compare/{row['base']}..."
              f"{fork.replace('/', ':')}:{pin} --jq '.ahead_by'",
              "```", ""]
    return "\n".join(lines)


def render_index(table: dict) -> str:
    lines = [STAMP, "", "# Forks nano-ros carries", "",
             "Every submodule that tracks a patch branch, and the page that lists its "
             "patches against a pinned upstream ref. Repositories nano-ros authors "
             "itself have no upstream and no page.", "",
             "| fork | upstream | base |", "| --- | --- | --- |"]
    for row in table.get("fork", []):
        lines.append(f"| [{row['name']}]({row['name']}.md) | `{row['upstream']}` | `{row['base']}` |")
    lines += ["", "Authored by nano-ros (no delta page): "
              + ", ".join(f"`{r['path']}`" for r in table.get("ours", [])) + ".", ""]
    return "\n".join(lines)


def main() -> int:
    table = tomllib.loads(TABLE.read_text())
    only = set(sys.argv[1:])
    for row in table.get("fork", []):
        if only and row["name"] not in only:
            continue
        pin = gitlink(row["path"])
        url, branch = submodule_url(row["path"])
        fork = github_repo(url)
        cmp = compare(row["upstream"], row["base"], fork, pin)
        (PAGES / f"{row['name']}.md").write_text(render(row, pin, fork, branch, cmp))
        print(f"{row['name']}: {cmp['ahead_by']} commit(s) on {row['base']}, "
              f"{cmp['behind_by']} behind")
    (PAGES / "README.md").write_text(render_index(table))
    return 0


if __name__ == "__main__":
    sys.exit(main())
