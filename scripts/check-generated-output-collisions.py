#!/usr/bin/env python3
"""No two images, and no two west leaves, may build into one output.

Issue 1582. `realtime-rust` declared `[image.zephyr]` in TWO bringups —
`demo_bringup` (authored tiers) and `derived_bringup` (derived tiers). A
generated entry is keyed on the image ID, `build/<platform>-<rmw>/<id>_entry/`,
and on the west road that directory IS the Zephyr application, so both west
leaves configured the same `APPLICATION_SOURCE_DIR`. Each `nros build`
rewrote its `lib.rs`; whichever ran last decided what BOTH images contained.
Measured: the authored-tier image `build-ws-rs-realtime-entry-zenoh` carried
the string `derived-telem_node`, and `sched_dims_applied_e2e`'s CorePin and
EdfDeadline cells failed on an image they never meant to test.

Nothing checked it. `check-west-leaf-vocabulary` (issue 1016) asks whether a
build-dir NAME is modelled, not whether two modelled names share an input.

`nros build` now refuses the collision itself, precisely, per road
(`cmd::build::generated_outputs`): cargo and west write the entry package and
its selection facade, cmake a target of that name in the coordinate root, and
a hand-written application suppresses all of it. This gate is the cheap,
static floor under that, over two tables no build has to run to read:

  1. THE TREE — in every tracked workspace, an image id that GENERATES its
     entry is declared by at most one bringup. That is deliberately a touch
     stricter than the CLI, which lets one id recur across bringups when every
     output lands on a distinct coordinate (a C image on two different
     boards). The tree keeps the simpler invariant because it is the one a
     reader can check by eye; a user's workspace gets the precise rule.
     "Generates" is the build's own predicate: no `src/<id>_entry/` holding a
     `Cargo.toml` or `CMakeLists.txt`, and no `[image.<id>] entry = "…"`.
     (`realtime-c`'s `zephyr_entry` is hand-written and serves both of its
     bringups; that sharing is legitimate — each leaf has its own west build
     dir and the application picks the bringup at configure time.)

  2. THE MANIFEST — over `fixtures-manifest.py west-leaves`, THE emitter the
     west lane builds from: no two leaves share a build-dir NAME (the routing
     key issue 1016 is about), no two share a leaf id, and no two GENERATED
     leaves share an application (workspace + image id) unless they are the
     same image.

Usage::

    check-generated-output-collisions.py [--selftest]
"""

from __future__ import annotations

import argparse
import collections
import contextlib
import io
import re
import subprocess
import sys
import tempfile
from pathlib import Path

try:
    import tomllib  # Python 3.11+
except ImportError:  # pragma: no cover
    import tomli as tomllib

ROOT = Path(__file__).resolve().parent.parent
MANIFEST_PY = ROOT / "scripts/build/fixtures-manifest.py"
SEP = "\x1f"


def package_name(image_id: str) -> str:
    """`nros_cli_core::builder::entry::package_name` — and `fixtures-manifest.py`'s
    `entry_name` spells it the same way (`-`, `.`, `/` become `_`)."""
    return "{}_entry".format(re.sub(r"[-./]", "_", image_id))


def image_generates(ws: Path, image_id: str, block: dict) -> bool:
    """Does `nros build` GENERATE this image's entry (rather than locate one)?"""
    if block.get("entry"):
        return False
    hand = ws / "src" / package_name(image_id)
    return not ((hand / "Cargo.toml").is_file() or (hand / "CMakeLists.txt").is_file())


def tree_collisions(root: Path, system_tomls: list[str]) -> list[str]:
    """Rule 1 over the given workspace-relative `*/src/<bringup>/system.toml` paths."""
    by_ws: dict[Path, dict[str, list[str]]] = collections.defaultdict(
        lambda: collections.defaultdict(list)
    )
    for rel in system_tomls:
        head, sep, tail = rel.partition("/src/")
        if not sep or "/" not in tail:
            continue
        bringup = tail.split("/", 1)[0]
        if tail != f"{bringup}/system.toml":
            continue
        ws = root / head
        with open(root / rel, "rb") as f:
            doc = tomllib.load(f)
        for image_id, block in (doc.get("image") or {}).items():
            if image_generates(ws, image_id, block or {}):
                by_ws[ws][image_id].append(bringup)
    out = []
    for ws, ids in sorted(by_ws.items()):
        for image_id, bringups in sorted(ids.items()):
            if len(bringups) > 1:
                rel_ws = ws.relative_to(root)
                out.append(
                    f"{rel_ws}: `[image.{image_id}]` is GENERATED by {len(bringups)} bringups "
                    f"({', '.join(sorted(bringups))}) into one `build/<coord>/"
                    f"{package_name(image_id)}` — give each its own image id"
                )
    return out


def manifest_collisions(records: list[list[str]]) -> list[str]:
    """Rule 2 over `west-leaves` records (split on the unit separator)."""
    out = []
    by_name = collections.defaultdict(list)
    by_id = collections.defaultdict(list)
    by_app = collections.defaultdict(set)
    for r in records:
        # <board> <lang> <lang_tag> <rmw> <role> <dir> <build_name> <id>
        # <zenoh> <xrce> <cyclone> <conf> <reserved> <ws_dir> <nros_image> <coord>
        if len(r) < 15:
            raise ValueError(f"west-leaves record has {len(r)} fields, expected >= 15: {r!r}")
        d, build_name, leaf_id, ws_dir, nros_image = r[5], r[6], r[7], r[13], r[14]
        by_name[build_name].append(leaf_id)
        by_id[leaf_id].append(build_name)
        # A GENERATED application: the emitter leaves `dir` as the workspace
        # (there is no `src/<pkg>` to name) and the row names its image.
        if nros_image and ws_dir and d.rstrip("/") == ws_dir.rstrip("/"):
            image_id = nros_image.split(":", 1)[-1]
            by_app[(ws_dir, image_id)].add(nros_image)
    for name, ids in sorted(by_name.items()):
        if len(ids) > 1:
            out.append(f"west build dir `{name}` is built by {len(ids)} leaves: {', '.join(ids)}")
    for leaf_id, names in sorted(by_id.items()):
        if len(names) > 1:
            out.append(f"west leaf id `{leaf_id}` names {len(names)} build dirs: {', '.join(names)}")
    for (ws_dir, image_id), images in sorted(by_app.items()):
        if len(images) > 1:
            out.append(
                f"{ws_dir}: west leaves {', '.join(sorted(images))} share ONE generated "
                f"application `build/<coord>/{package_name(image_id)}` — each overwrites "
                f"the other's source"
            )
    return out


def west_leaf_records() -> list[list[str]]:
    res = subprocess.run(
        [sys.executable, str(MANIFEST_PY), "west-leaves"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if res.returncode != 0:
        raise SystemExit(f"check-generated-output-collisions: west-leaves failed:\n{res.stderr}")
    return [line.split(SEP) for line in res.stdout.splitlines() if line]


def tracked_system_tomls() -> list[str]:
    res = subprocess.run(
        ["git", "ls-files", "*/src/*/system.toml"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return res.stdout.split()


def _write(p: Path, text: str) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)


def _selftest() -> int:
    """Each rule must FIRE on the shape it names, and stay quiet on the legal ones."""
    with tempfile.TemporaryDirectory() as t:
        root = Path(t)
        img = '[image.zephyr]\nboard = "zephyr"\n'
        # The reported shape: two bringups, one generated id.
        _write(root / "ws1/src/demo_bringup/system.toml", img)
        _write(root / "ws1/src/derived_bringup/system.toml", img)
        # Distinct ids: fine.
        _write(root / "ws2/src/a/system.toml", img)
        _write(root / "ws2/src/b/system.toml", '[image.zephyr_b]\nboard = "zephyr"\n')
        # realtime-c's shape: one HAND-WRITTEN application shared by two bringups.
        _write(root / "ws3/src/demo_bringup/system.toml", img)
        _write(root / "ws3/src/smp_bringup/system.toml", img)
        _write(root / "ws3/src/zephyr_entry/CMakeLists.txt", "")
        # An `entry =` names the application: not generated either.
        named = '[image.zephyr]\nentry = "app"\n'
        _write(root / "ws4/src/a/system.toml", named)
        _write(root / "ws4/src/b/system.toml", named)
        tomls = [
            str(p.relative_to(root)) for p in sorted(root.glob("*/src/*/system.toml"))
        ]
        got = tree_collisions(root, tomls)
        if len(got) != 1 or not got[0].startswith("ws1:"):
            print(f"selftest: tree rule answered {got!r}", file=sys.stderr)
            return 1

    def rec(build, leaf, d, ws, image):
        return ["b", "rust", "rust", "zenoh", "entry", d, build, leaf, "", "", "", "", "", ws, image, "c"]

    ws = "examples/workspaces/realtime-rust"
    clean = [
        rec("build-a", "id-a", ws, ws, "demo_bringup:zephyr"),
        rec("build-b", "id-b", ws, ws, "derived_bringup:zephyr_derived"),
        # Two HAND-WRITTEN leaves sharing an application dir is legal.
        rec("build-c", "id-c", "x/src/zephyr_entry", "x", ""),
        rec("build-d", "id-d", "x/src/zephyr_entry", "x", ""),
    ]
    if manifest_collisions(clean):
        print(f"selftest: clean manifest flagged: {manifest_collisions(clean)}", file=sys.stderr)
        return 1
    cases = [
        ("the reported shape", rec("build-b", "id-b", ws, ws, "derived_bringup:zephyr"), "share ONE"),
        ("a shared build dir", rec("build-a", "id-z", "y", "", ""), "build dir `build-a`"),
        ("a shared leaf id", rec("build-z", "id-a", "y", "", ""), "leaf id `id-a`"),
    ]
    for why, bad, needle in cases:
        rows = clean[:1] + [bad] if why == "the reported shape" else clean + [bad]
        got = manifest_collisions(rows)
        if not any(needle in g for g in got):
            print(f"selftest: {why} not caught: {got!r}", file=sys.stderr)
            return 1
    print("check-generated-output-collisions: selftest OK")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return _selftest()
    # Always, quietly: a negative control nobody runs decays into a comment.
    with contextlib.redirect_stdout(io.StringIO()) as out:
        rc = _selftest()
    if rc:
        sys.stdout.write(out.getvalue())
        return rc

    tomls = tracked_system_tomls()
    records = west_leaf_records()
    # Vacuity floor: a harvest that stopped matching would report a clean tree forever.
    if len(tomls) < 20 or len(records) < 20:
        print(
            f"check-generated-output-collisions: harvested only {len(tomls)} bringup "
            f"system.toml(s) and {len(records)} west leaves — the harvest is broken, "
            "not the tree clean",
            file=sys.stderr,
        )
        return 1
    problems = tree_collisions(ROOT, tomls) + manifest_collisions(records)
    if problems:
        print("check-generated-output-collisions: FAIL (issue 1582)", file=sys.stderr)
        for p in problems:
            print(f"  {p}", file=sys.stderr)
        return 1
    print(
        f"check-generated-output-collisions: {len(tomls)} bringups, {len(records)} west "
        "leaves — no shared generated output"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
