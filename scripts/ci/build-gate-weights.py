#!/usr/bin/env python3
"""Measure `.config/build-gate-weights.txt` from `host-suite` runs (phase-591 W6).

`scripts/build/gate-shard.py` balances `host-suite`' `check-build` shards
from that file, so the split is only as good as the measurement under it. The
file used to be refreshed by hand from one run's logs. On 2026-11-23 it was
twelve days old, measured on a different job, and the last shard took
102-113 min against 55-81 min for the others (runs 44449694164..45104661214).

This script takes the measurement:

  * each build test's weight is the MEAN of its nextest PASS/FAIL time over
    every listed run that ran it (`nros-gates::gates build::...` lines in the
    `check / build tier` shard logs);
  * `@host-suite-last-shard` is the work the LAST shard runs outside the list
    (`just check no-std` + `just check pristine-checkout`). It is measured as
    step wall time and converted to the same busy-time unit as the tests,
    using the runs' own ratio of summed test time to `just check build` step
    wall time. `just check build` charges it to the last shard through
    `gate-shard.py --preload-last` (`NROS_BUILD_GATE_PRELOAD_LAST`).

The weights decide BALANCE only. Coverage never depends on them: every build
test lands in exactly one shard whatever this file says (gate-shard.py).

Usage:
    scripts/ci/build-gate-weights.py <run-id>... > .config/build-gate-weights.txt
    scripts/ci/build-gate-weights.py --self-test

Needs `gh` with read access to the repository's Actions logs.
"""

import json
import re
import subprocess
import sys
from datetime import datetime

JOB = re.compile(r"build tier .*\[(\d+)/(\d+)\]")
TEST = re.compile(
    r"\b(?:PASS|FAIL)\b[^\[]*\[\s*([0-9.]+)s\]\s*\(\s*\d+/\d+\)\s+nros-gates::gates\s+(build::\S+)"
)
EXTRA_STEPS = ("just check no-std", "just check pristine-checkout")
BUILD_STEP = "just check build"
LAST_UNIT = "@host-suite-last-shard"


def gh(*args):
    return subprocess.run(
        ["gh", *args], check=True, capture_output=True, text=True
    ).stdout


def seconds(step):
    if not step.get("startedAt") or not step.get("completedAt"):
        return 0.0
    fmt = "%Y-%m-%dT%H:%M:%SZ"
    a = datetime.strptime(step["startedAt"], fmt)
    b = datetime.strptime(step["completedAt"], fmt)
    return (b - a).total_seconds()


def parse_log(text):
    """Return [(test, seconds)] from one shard's log."""
    return [(m.group(2), float(m.group(1))) for m in TEST.finditer(text)]


def measure(run_ids, fetch_jobs, fetch_log):
    times = {}  # test -> [seconds]
    busy = 0.0  # summed test seconds, every shard
    build_wall = 0.0  # summed `just check build` step seconds, every shard
    extras = []  # per run: last shard's no-std + pristine-checkout seconds
    for run in run_ids:
        jobs = [j for j in fetch_jobs(run) if JOB.search(j["name"])]
        if not jobs:
            raise SystemExit(f"build-gate-weights: run {run} has no `build tier` shard job")
        for job in jobs:
            k, n = (int(x) for x in JOB.search(job["name"]).groups())
            rows = parse_log(fetch_log(run, job["databaseId"]))
            if not rows:
                raise SystemExit(
                    f"build-gate-weights: run {run} shard {k}/{n} logged no build test "
                    "(log expired, or the job did not reach `just check build`)"
                )
            for test, s in rows:
                times.setdefault(test, []).append(s)
                busy += s
            steps = job.get("steps") or []
            build_wall += sum(seconds(s) for s in steps if s["name"].startswith(BUILD_STEP))
            if k == n:
                extras.append(sum(seconds(s) for s in steps if s["name"].startswith(EXTRA_STEPS)))
    ratio = busy / build_wall if build_wall else 1.0
    weights = {t: int(sum(v) / len(v) * 1000) for t, v in times.items()}
    if extras:
        weights[LAST_UNIT] = int(sum(extras) / len(extras) * ratio * 1000)
    return weights, ratio


def render(weights, run_ids, ratio):
    head = [
        "# Measured weight (ms) of each `build`-tier gate test, for balancing",
        "# `host-suite`' `check-build` shards (scripts/build/gate-shard.py, issue 2141).",
        "# GENERATED by scripts/ci/build-gate-weights.py (phase-591 W6) from runs",
        "#   " + " ".join(run_ids),
        "# A test's weight is its mean nextest time over those runs. "
        f"`{LAST_UNIT}` is the",
        "# last shard's `no-std` + `pristine-checkout` step time, in the same busy unit",
        f"# (x{ratio:.2f}, the runs' summed test time over `just check build` wall time).",
        "# Weights decide balance only; every build test lands in exactly one shard.",
        "# Refresh: scripts/ci/build-gate-weights.py <run-id>... > .config/build-gate-weights.txt",
    ]
    width = max(len(t) for t in weights) + 2
    body = [
        f"{t.ljust(width)}{w}"
        for t, w in sorted(weights.items(), key=lambda tw: (-tw[1], tw[0]))
    ]
    return "\n".join(head + body) + "\n"


def self_test(quiet=False):
    log = (
        "x\tUNKNOWN STEP\t2026Z         PASS [  55.400s] ( 1/31) nros-gates::gates build::check::a\n"
        "x\tUNKNOWN STEP\t2026Z         FAIL [ 100.000s] ( 2/31) nros-gates::gates build::check::b#c\n"
        "x\tUNKNOWN STEP\t2026Z         SKIP [   0.000s] nros-gates::gates build::check::d\n"
    )
    assert parse_log(log) == [("build::check::a", 55.4), ("build::check::b#c", 100.0)]

    def step(name, a, b):
        return {"name": name, "startedAt": f"2026-01-01T00:{a:02d}:00Z",
                "completedAt": f"2026-01-01T00:{b:02d}:00Z"}

    jobs = {
        "r1": [
            {"name": "check / build tier + no-std [1/2] (daily)", "databaseId": 1,
             "steps": [step("just check build (daily)", 0, 10)]},
            {"name": "check / build tier + no-std [2/2] (daily)", "databaseId": 2,
             "steps": [step("just check build (daily)", 0, 10),
                       step("just check pristine-checkout (daily)", 10, 15)]},
            {"name": "workspace unit tests", "databaseId": 3, "steps": []},
        ],
    }
    logs = {
        1: "PASS [ 600.000s] ( 1/1) nros-gates::gates build::check::a\n",
        2: "PASS [ 600.000s] ( 1/1) nros-gates::gates build::check::b\n",
    }
    w, ratio = measure(["r1"], jobs.__getitem__, lambda r, j: logs[j])
    # 1200 s of tests over 1200 s of build-step wall: ratio 1.
    assert abs(ratio - 1.0) < 1e-9, ratio
    assert w == {"build::check::a": 600000, "build::check::b": 600000, LAST_UNIT: 300000}, w
    text = render(w, ["r1"], ratio)
    assert "build::check::a" in text and text.endswith("\n")
    # A run with no shard job is an error, never an empty weights file.
    try:
        measure(["r2"], lambda r: [], lambda r, j: "")
    except SystemExit:
        pass
    else:
        raise AssertionError("a run with no shard job must fail")
    if not quiet:
        print("build-gate-weights: self-test OK")


def main(argv):
    if argv[1:] == ["--self-test"]:
        self_test()
        return 0
    # The negative control runs on the normal path too: a measurement from a
    # parser that no longer reads a shard log would write a wrong split.
    self_test(quiet=True)
    run_ids = argv[1:]
    if not run_ids:
        print(__doc__.strip().split("Usage:")[1], file=sys.stderr)
        return 2

    def fetch_jobs(run):
        return json.loads(gh("run", "view", run, "--json", "jobs"))["jobs"]

    def fetch_log(run, job):
        return gh("run", "view", run, "--log", "--job", str(job))

    weights, ratio = measure(run_ids, fetch_jobs, fetch_log)
    sys.stdout.write(render(weights, run_ids, ratio))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
