class Registry:
    def __init__(self, root: Path):
        self.root = root
        # RFC-0118 D4 (phase-528 W2): `emulator` is read from each row's board
        # descriptor, never typed here. `raw_doc` is the file as written (the
        # gate refuses a typed `emulator` in it); `doc` is what every view and
        # the data hash are made from, so a descriptor edit restamps the views.
        self.raw_doc = board_registry.load(root / REGISTRY)
        self.index = board_registry.descriptor_index(root)
        self.doc = board_registry.with_descriptor_facts(self.raw_doc, self.index)
        self.cell_table = self.doc.get("cell_table")
        if not self.cell_table:
            raise SystemExit(f"{REGISTRY}: no top-level `cell_table` naming the "
                             "registry's cell table")
        self.cells_path = (root / REGISTRY).parent / self.cell_table
        self.cells_doc = board_registry.load(self.cells_path)
        self.cells = self.cells_doc.get("cell", [])
        self.rows = self.doc.get("board", [])
        crates = [r["crate"] for r in self.rows]
        _SHARED.update(c for c in crates if crates.count(c) > 1)
        self.probes = self.doc.get("probe", [])
        # phase-524 W4a — a twin track's board facts, read from the descriptor
        # it names and the index's Zephyr module set; part of the data hash,
        # so a descriptor's `[board.run.<kind>]` edit restamps the views.
        sdk_index = board_registry.load(root / SDK_INDEX)
        self.twins = {p["track"]: twin_facts(self.index, sdk_index, p)
                      for p in self.probes if p.get("twin")}
        # phase-524 W4b — a twin track whose chapter is its board's own (the
        # registry row's `book_run` names it) runs the twin through the
        # chapter's `nros run` steps; any other twin track replays a shared
        # chapter's setup and leaves the run to the probe's twin smoke script.
        for p in self.probes:
            if p.get("twin") and chapter_runs_twin(self.rows, p):
                self.twins[p["track"]]["chapter_run"] = "1"
        self.stale_days = self.doc.get("manual_stale_days",
                                       board_registry.DEFAULT_STALE_DAYS)
        data = json.dumps([self.doc, self.cells_doc, self.twins], sort_keys=True).encode()
        self.digest = hashlib.sha256(data).hexdigest()[:16]
        fixtures = (root / FIXTURES).read_text()
        self.fixture_boards = set(re.findall(r'NROS_BOARD\s*=\s*"([^"]+)"', fixtures))

    def cells_for(self, plat: str) -> list[dict]:
        return [c for c in self.cells if c["at"][0] == plat]

    def built(self, row: dict) -> bool:
        plat = row.get("matrix_platform")
        if plat and any(c["status"].startswith(("Runtime", "BuildOnly"))
                        for c in self.cells_for(plat)):
            return True
        return board_registry.board_name(row) in self.fixture_boards

    # No clock for the COMMITTED views: a tracked file must not change on a day
    # nobody edited anything, or the gate turns red for every pull request on
    # day 121. The RENDERED book applies the date instead: book/book.toml runs
    # scripts/mdbook-board-status.py, which sets `today` and re-renders these
    # pages at build time (RFC-0114 D10, decision log 2026-11-01).
    today = None

    def status(self, row: dict) -> str:
        word = board_registry.status_word(row, self.built(row),
                                          stale_days=self.stale_days, today=self.today)
        until = board_registry.stale_from(row, self.stale_days)
        if until and not word.startswith("Builds"):
            word += f"; reads *Builds* from {until}"
        return word

    def stamp(self, comment: str) -> str:
        return (f"{comment} GENERATED by scripts/gen-board-support.py from {REGISTRY} "
                f"(registry data {self.digest}) — do not edit; edit the registry "
                "and regenerate.")


_SHARED: set[str] = set()


def page_name(row: dict) -> str:
    """The evidence page's file stem: the board name, or the matrix platform in
    kebab case when one package carries several rows (`nros-board-zephyr` is
    native_sim and the FVP)."""
    plat = row.get("matrix_platform")
    if plat and row["crate"] in _SHARED:
        return re.sub(r"(?<!^)(?=[A-Z])", "-", plat).lower()
    return board_registry.board_name(row)


# phase-524 W4a — what an emulator KIND needs of the probe host, beyond the
# board: a secret the run cannot start without, and `[prereq.*]` keys the
# harness installs into the probe container from the index. A fact of the
# kind's script (scripts/probe/twin/<kind>.sh), never of a board.
TWIN_KIND_NEEDS = {
    "renode": {},
}


def twin_facts(index: dict, sdk_index: dict, p: dict) -> dict:
    """The board facts a twin track runs on, from the descriptor `twin` names
    and the track's own image fields. Refuses a track whose board cannot say."""
    key = p["twin"]
    where = f"{REGISTRY}: [[probe]] `{p['track']}`"
    ref = index["by_name"].get(key)
    if ref is None:
        raise SystemExit(f"{where}: twin `{key}` names no nros-board.toml descriptor")
    entry = index["entries"][ref]
    run = entry.get("run") or {}
    emu = run.get("emulator") or ""
    kind, _, machine = emu.partition(":")
    if kind not in TWIN_KIND_NEEDS or not machine:
        raise SystemExit(f"{where}: twin `{key}` states `[board.run] emulator = {emu!r}`; "
                         f"a twin track needs one of {', '.join(sorted(TWIN_KIND_NEEDS))}")
    wiring = run.get(kind)
    if not isinstance(wiring, dict) or not wiring.get("link"):
        raise SystemExit(f"{where}: {ref[0]} has no `[board.run.{kind}] link`, the twin's "
                         "serial link the router opens")
    link = wiring["link"]
    west_board = (entry.get("zephyr") or {}).get("west_board")
    line = (entry.get("provisioning") or {}).get("zephyr_line")
    if not west_board or not line:
        raise SystemExit(f"{where}: {ref[0]} states no `[board.zephyr] west_board` or "
                         "`[board.provisioning] zephyr_line`; a twin track builds a Zephyr image")
    # A track whose CHAPTER builds the image (`twin_build`, the build
    # directory its steps leave) boots that one; its locator is the chapter's
    # own Kconfig, so the track states none. Otherwise the probe scaffolds the
    # image, and the track states the serial locator it dials.
    chapter_build = p.get("twin_build")
    if chapter_build and p.get("twin_locator"):
        raise SystemExit(f"{where}: `twin_build` boots the chapter's image, whose locator "
                         "is the chapter's; drop `twin_locator`")
    if not chapter_build and not p.get("twin_locator"):
        raise SystemExit(f"{where}: a twin track states `twin_locator`, the serial "
                         "locator its image dials")
    image = ["[image.twin]", f'board = "{key}"', 'rmw = "zenoh"',
             f'locator = "{p.get("twin_locator", "")}"']
    # Issue 2194 -- the board's RAM knobs are its descriptor's `[knobs]`, which
    # every road carries below the image's own; restating them here typed one
    # fact twice. The field is refused, naming where the knobs live.
    if "twin_knobs" in p:
        raise SystemExit(f"{where}: `twin_knobs` is retired (issue 2194) -- a board's "
                         f"knobs are its descriptor's top-level `[knobs.<group>]` "
                         f"({ref[0]}), which the twin image inherits")
    family = west_board.split("/")[0]
    modules = sorted(name for name, m in sdk_index.get("zephyr_module", {}).items()
                     if line in (m.get("lines") or []) and family in (m.get("needed_by") or []))
    needs = TWIN_KIND_NEEDS[kind]
    facts = {"board": key, "west_board": west_board, "emulator": emu, "kind": kind,
             "machine": machine,
             "link": " ".join(link) if isinstance(link, list) else link,
             "image_toml": "\n".join(image), "modules": modules}
    if chapter_build:
        del facts["image_toml"]
        facts["chapter_build"] = chapter_build
    # What `ros2 topic echo` subscribes with and must print, when the image
    # publishes something other than the scaffold's `std_msgs/String`.
    if p.get("twin_echo"):
        facts["echo"] = p["twin_echo"]
    if p.get("twin_heard"):
        facts["heard"] = p["twin_heard"]
    if wiring.get("console"):
        facts["console"] = wiring["console"]
    if needs.get("secret"):
        facts["secret"] = needs["secret"]
    if needs.get("prereqs"):
        facts["prereqs"] = needs["prereqs"]
    return facts


def chapter_runs_twin(rows: list[dict], p: dict) -> bool:
    """Whether twin track `p` replays its board's own chapter, which boots the
    twin itself (`nros run`): the chapter of the board row's `book_run`."""
    row = next((r for r in rows if board_registry.row_name(r) == p.get("row")), None)
    run = (row or {}).get("book_run") or ""
    return bool(run) and run.split("#", 1)[0] == p.get("chapter")


