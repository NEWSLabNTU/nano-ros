#!/usr/bin/env python3
"""RFC-0114 D12 — every board-support view, generated from the registry.

The registry is `packages/boards/board-support.toml` (the board rows and the
probe tracks) plus the cell table it names (`cell_table`,
`packages/boards/board-support-cells.toml`). This script reads them and the
board descriptors they name, and writes every view below. Nothing it writes is
edited by hand; each output starts with a stamp naming this script and the hash
of the registry DATA it was made from (comments are not data, so a comment edit
in the registry restamps nothing).

  packages/testing/nros-tests/src/matrix_cells.rs
        the `matrix::CELLS` list, `include!`d by matrix.rs
  scripts/probe/probe-tracks.json
        the probe tracks: `run-bootstrap-probe.sh` resolves a track's chapter
        and variant from it, and `probe-platforms.yml` reads its weekly list
  packages/cli/nros-cli-core/src/cmd/probe_boot_rows.rs
        the `ROWS` of `every_probed_chapter_boot_line_is_the_printed_run_command`
        (issue 2169): every probe track whose chapter boots QEMU, and its board
  book/src/reference/board-support-levels.md
        the support level of every row: status word, cadence, where it runs,
        breadth
  book/src/reference/boards/<board>.md
        one evidence page per board row
  book/src/reference/supported-boards.md  (the generated region only)
        the registry-backed procurement rows
  book/src/SUMMARY.md  (the generated region only)
        the levels page and one entry per evidence page
  packages/boards/board-support-status.json
        every row's derived status, breadth and evidence, for the `nros` CLI
        and Rust tests (phase-522 W4/W5)

What is NOT generated, deliberately: the `examples/fixtures.toml` rows. Their
build arguments are not a function of a descriptor plus a family default
(RFC-0114 evaluation step 1 and its narrowing, recorded in the RFC), so they
stay authored and `check-board-registry` checks them against the registry
instead of writing them.

Run:
  python3 scripts/gen-board-support.py           # write every view
  python3 scripts/gen-board-support.py --check   # exit 1 naming each stale view
  python3 scripts/gen-board-support.py --out DIR # write into DIR (the gate)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts/lib"))
import board_registry  # noqa: E402

REGISTRY = "packages/boards/board-support.toml"
CELLS_RS = "packages/testing/nros-tests/src/matrix_cells.rs"
PROBE_JSON = "scripts/probe/probe-tracks.json"
BOOT_ROWS_RS = "packages/cli/nros-cli-core/src/cmd/probe_boot_rows.rs"
LEVELS_MD = "book/src/reference/board-support-levels.md"
BOARDS_DIR = "book/src/reference/boards"
SUPPORTED_MD = "book/src/reference/supported-boards.md"
STATUS_JSON = "packages/boards/board-support-status.json"
SUMMARY_MD = "book/src/SUMMARY.md"
SUMMARY_BEGIN = "<!-- BEGIN GENERATED by scripts/gen-board-support.py: board pages -->"
SUMMARY_END = "<!-- END GENERATED board pages -->"
REGION_BEGIN = "<!-- BEGIN GENERATED by scripts/gen-board-support.py: registry rows -->"
REGION_END = "<!-- END GENERATED registry rows -->"
FIXTURES = "examples/fixtures.toml"
MATRIX_RS = "packages/testing/nros-tests/src/matrix.rs"

LANG_WORD = {"Rust": "Rust", "C": "C", "Cpp": "C++"}
RMW_WORD = {"Zenoh": "zenoh", "Cyclonedds": "cyclonedds", "Xrce": "XRCE-DDS",
            "Uorb": "uORB"}


# --------------------------------------------------------------------------
# inputs

class Registry:
    def __init__(self, root: Path):
        self.root = root
        self.doc = board_registry.load(root / REGISTRY)
        self.cell_table = self.doc.get("cell_table")
        if not self.cell_table:
            raise SystemExit(f"{REGISTRY}: no top-level `cell_table` naming the "
                             "registry's cell table")
        self.cells_path = (root / REGISTRY).parent / self.cell_table
        self.cells_doc = board_registry.load(self.cells_path)
        self.cells = self.cells_doc.get("cell", [])
        self.rows = self.doc.get("board", [])
        crates = [r["crate"] for r in self.rows]
        _SHARED.update(c for c in crates if crates.count(c) > 1)
        self.probes = self.doc.get("probe", [])
        self.stale_days = self.doc.get("manual_stale_days",
                                       board_registry.DEFAULT_STALE_DAYS)
        data = json.dumps([self.doc, self.cells_doc], sort_keys=True).encode()
        self.digest = hashlib.sha256(data).hexdigest()[:16]
        fixtures = (root / FIXTURES).read_text()
        self.fixture_boards = set(re.findall(r'NROS_BOARD\s*=\s*"([^"]+)"', fixtures))

    def cells_for(self, plat: str) -> list[dict]:
        return [c for c in self.cells if c["at"][0] == plat]

    def built(self, row: dict) -> bool:
        plat = row.get("matrix_platform")
        if plat and any(c["status"].startswith(("Runtime", "BuildOnly"))
                        for c in self.cells_for(plat)):
            return True
        return board_registry.board_name(row) in self.fixture_boards

    # No clock for the COMMITTED views: a tracked file must not change on a day
    # nobody edited anything, or the gate turns red for every pull request on
    # day 121. The RENDERED book applies the date instead: book/book.toml runs
    # scripts/mdbook-board-status.py, which sets `today` and re-renders these
    # pages at build time (RFC-0114 D10, decision log 2026-11-01).
    today = None

    def status(self, row: dict) -> str:
        word = board_registry.status_word(row, self.built(row),
                                          stale_days=self.stale_days, today=self.today)
        until = board_registry.stale_from(row, self.stale_days)
        if until and not word.startswith("Builds"):
            word += f"; reads *Builds* from {until}"
        return word

    def stamp(self, comment: str) -> str:
        return (f"{comment} GENERATED by scripts/gen-board-support.py from {REGISTRY} "
                f"(registry data {self.digest}) — do not edit; edit the registry "
                "and regenerate.")


_SHARED: set[str] = set()


def page_name(row: dict) -> str:
    """The evidence page's file stem: the board name, or the matrix platform in
    kebab case when one package carries several rows (`nros-board-zephyr` is
    native_sim and the FVP)."""
    plat = row.get("matrix_platform")
    if plat and row["crate"] in _SHARED:
        return re.sub(r"(?<!^)(?=[A-Z])", "-", plat).lower()
    return board_registry.board_name(row)


# --------------------------------------------------------------------------
# views

def render_cells(reg: Registry) -> str:
    out = [f"// {reg.stamp('')[1:]}",
           "//",
           "// The `matrix::CELLS` list (RFC-0051), one entry per `[[cell]]` of the",
           f"// registry's cell table ({reg.cell_table}). A cell's history is its",
           "// `comment`, kept here so a reader of the list still sees why a cell is",
           "// what it is. `matrix::CELLS` is this const.",
           "#[rustfmt::skip]",
           "const CELLS_GENERATED: &[Cell] = &["]
    for c in reg.cells:
        comment = c.get("comment")
        if comment:
            for line in comment.rstrip("\n").split("\n"):
                out.append(f"    {line}" if line else "")
        coords = ", ".join(c["at"])
        status = c["status"]
        if "\n" in status:
            call = f"    cell({coords},\n         {status})"
        else:
            call = f"    cell({coords}, {status})"
        if c.get("with"):
            call += f".with({c['with']})"
        out.append(call + ",")
    out.append("];")
    return "\n".join(out) + "\n"


def render_probe_json(reg: Registry) -> str:
    tracks = []
    for p in reg.probes:
        t = {"track": p["track"], "chapter": p["chapter"],
             "variant": p.get("variant", ""), "weekly": bool(p.get("weekly"))}
        if p.get("row"):
            t["row"] = p["row"]
        if p.get("qemu_board"):
            t["qemu_board"] = p["qemu_board"]
        if p.get("offline"):
            t["offline"] = True
        tracks.append(t)
    doc = {"_generated": reg.stamp("")[1:].strip(), "tracks": tracks}
    return json.dumps(doc, indent=2) + "\n"


def render_boot_rows(reg: Registry) -> str:
    out = [f"// {reg.stamp('')[1:]}",
           "//",
           "// (chapter, block variant, board the chapter's image is built for): every",
           "// probe track whose chapter boots QEMU (`qemu_board` in the registry's",
           "// `[[probe]]`), for issue 2169's printed-run-command test.",
           "#[rustfmt::skip]",
           "const PROBE_BOOT_ROWS: &[(&str, &str, &str)] = &["]
    for p in reg.probes:
        if not p.get("qemu_board"):
            continue
        chapter = Path(p["chapter"]).name
        out.append(f'    ("{chapter}", "{p.get("variant", "")}", "{p["qemu_board"]}"),')
    out.append("];")
    return "\n".join(out) + "\n"


def breadth_of(reg: Registry, plat: str | None) -> str:
    if not plat:
        return "no matrix cells"
    cells = reg.cells_for(plat)
    rt = [c for c in cells if c["status"].startswith("Runtime")]
    bo = [c for c in cells if c["status"].startswith("BuildOnly")]
    if not rt and not bo:
        return "no Runtime or BuildOnly cells"

    def axis(cs, i, words=None):
        seen = []
        for c in cs:
            v = c["at"][i]
            v = (words or {}).get(v, v)
            if v not in seen:
                seen.append(v)
        return ", ".join(seen)

    parts = []
    if rt:
        parts.append(f"Runtime: {axis(rt, 3)} in {axis(rt, 1, LANG_WORD)} over "
                     f"{axis(rt, 2, RMW_WORD)}")
    only_built = [c for c in bo if c["at"][3] not in {r["at"][3] for r in rt}]
    if only_built:
        parts.append(f"build-only: {axis(only_built, 3)}")
    return "; ".join(parts)


def breadth_text(reg: Registry, row: dict) -> str:
    b = row.get("breadth")
    if row.get("infra"):
        return "—"
    if b is None:
        return "none claimed (nothing boots it)"
    if b == "witness":
        return f"witness — {breadth_of(reg, row.get('matrix_platform'))}"
    src = b.split(" ", 1)[1]
    own = row.get("matrix_platform")
    text = f"inherited from {src} — {breadth_of(reg, src)}"
    if own:
        text += f". Board-specific: {breadth_of(reg, own)}"
    return text


def where_text(row: dict) -> str:
    runs = row.get("runs")
    parts = []
    if runs == "host":
        parts.append("host executable")
    if row.get("emulator"):
        parts.append(f"`{row['emulator']}`" + ("" if runs == "emulator" else " (twin)"))
    if row.get("hardware"):
        parts.append(f"`{row['hardware']}`" + ("" if runs == "hardware" else " (target)"))
    return ", ".join(parts) or "—"


def chapter_link(ref: str, prefix: str) -> str:
    chapter, _, anchor = ref.partition("#")
    title = Path(chapter).stem.replace("-", " ")
    return f"[{title}]({prefix}{chapter}#{anchor})"


def board_rows(reg: Registry) -> list[dict]:
    return [r for r in reg.rows if not r.get("infra")]


def render_levels(reg: Registry) -> str:
    out = [f"<!-- {reg.stamp('')[1:].strip()} -->", "",
           "# Board Support Levels", "",
           "What nano-ros can show for each board it knows about. Each level is "
           "derived from evidence, never typed: **where** the board's image runs "
           "(on a host, in an emulator, on hardware, or nowhere yet), **how often** "
           "that run happens (every merge, daily, weekly, or by hand on a date) and "
           "**which board's test matrix** stands for its breadth.", "",
           "| Status | What it means |", "|---|---|",
           "| Verified on host / in emulator / on hardware (cadence) | an automated "
           "lane boots it and asserts a message, at that cadence |",
           "| Boots, manual (date) | a maintainer booted it by hand on that date; "
           f"after {reg.stale_days} days it reads *Builds* until booted again |",
           "| Builds | a lane builds it; nothing boots it |",
           "| Not supported | nothing builds or boots it |", "",
           "A **witness** board runs its platform family's test matrix; a board that "
           "**inherits** shares the witness's code path and adds its own smoke "
           "evidence. Each board links to its evidence page.", "",
           "| Board | Status | Runs on | Breadth |", "|---|---|---|---|"]
    for row in board_rows(reg):
        name = page_name(row)
        label = f"`{row['crate']}`" + (f" ({row['matrix_platform']})"
                                       if row.get("matrix_platform") else "")
        out.append(f"| [{label}](boards/{name}.md) | {reg.status(row)} | "
                   f"{where_text(row)} | {breadth_text(reg, row)} |")
    infra = [r for r in reg.rows if r.get("infra")]
    out += ["", "## Infrastructure", "",
            "Packages under `packages/boards/` that are not boards: shared traits, "
            "family drivers, ABI mirrors, PACs and descriptor directories.", "",
            ", ".join(f"`{r['crate']}`" for r in infra), ""]
    return "\n".join(out)


def render_board_page(reg: Registry, row: dict) -> str:
    plat = row.get("matrix_platform")
    title = row["crate"] + (f" ({plat})" if plat else "")
    out = [f"<!-- {reg.stamp('')[1:].strip()} -->", "", f"# {title}", "",
           f"**Status:** {reg.status(row)}", "",
           "| | |", "|---|---|",
           f"| Package | `{row['crate']}`"
           + (f" (in `{row['external']}`, outside this tree)" if row.get("external")
              else "") + " |",
           f"| Test-matrix platform | {plat or '—'} |",
           f"| Runs on | {where_text(row)} |",
           f"| Cadence | {row.get('cadence') or '—'}"
           + (f", last run {row['last_run']}" if row.get("last_run") else "") + " |",
           f"| Breadth | {breadth_text(reg, row)} |"]
    links = []
    for key, verb in (("book_run", "Run"), ("book_flash", "Flash")):
        if row.get(key):
            links.append(f"{verb}: {chapter_link(row[key], '../../')}")
    tracks = [f"`{p['track']}`" + (" (weekly)" if p.get("weekly") else "")
              for p in reg.probes if p.get("row") == board_registry.row_name(row)]
    out.append(f"| Book | {'; '.join(links) or '—'} |")
    out.append(f"| Book probe tracks | {', '.join(tracks) or '—'} |")
    if row.get("notes"):
        out += ["", "## Notes", "", row["notes"]]
    out += ["", "See [Board Support Levels](../board-support-levels.md) for what each "
            "status means.", ""]
    return "\n".join(out)


def render_supported_region(reg: Registry) -> str:
    out = [REGION_BEGIN,
           "| Board package | Status | Runs on | Evidence |",
           "|---|---|---|---|"]
    for row in board_rows(reg):
        out.append(f"| `{row['crate']}`"
                   + (f" ({row['matrix_platform']})" if row.get("matrix_platform") else "")
                   + f" | {reg.status(row)} | {where_text(row)} | "
                   f"[evidence page](boards/{page_name(row)}.md) |")
    out.append(REGION_END)
    return "\n".join(out)


def splice(path: str, current: str, begin: str, end: str, region: str) -> str:
    if begin in current and end in current:
        a = current.index(begin)
        b = current.index(end) + len(end)
        return current[:a] + region + current[b:]
    raise SystemExit(f"{path}: no generated region markers ({begin!r} … {end!r})")


def splice_supported(reg: Registry, current: str) -> str:
    return splice(SUPPORTED_MD, current, REGION_BEGIN, REGION_END,
                  render_supported_region(reg))


def render_summary_region(reg: Registry) -> str:
    out = [SUMMARY_BEGIN, "- [Board Support Levels](./reference/board-support-levels.md)"]
    for row in board_rows(reg):
        plat = row.get("matrix_platform")
        title = row["crate"] + (f" ({plat})" if plat else "")
        out.append(f"  - [{title}](./reference/boards/{page_name(row)}.md)")
    out.append(SUMMARY_END)
    return "\n".join(out)


def render_status_json(reg: Registry) -> str:
    """Every row's derived facts, for readers that are not Python: the `nros`
    CLI (`nros board list|show`, `nros doctor --report`) and Rust tests. The
    status is on no clock; a reader applies `stale_days` to `last_run` itself,
    because a reader knows what day it is and a committed file must not."""
    rows = []
    for row in reg.rows:
        until = board_registry.stale_from(row, reg.stale_days)
        rows.append({
            "key": board_registry.row_name(row),
            "crate": row["crate"],
            "matrix_platform": row.get("matrix_platform"),
            "status": board_registry.status_word(row, reg.built(row),
                                                 stale_days=reg.stale_days),
            "built": reg.built(row),
            "infra": bool(row.get("infra")),
            "runs": row.get("runs"),
            "emulator": row.get("emulator"),
            "hardware": row.get("hardware"),
            "cadence": row.get("cadence"),
            "last_run": row.get("last_run"),
            "stale_from": until.isoformat() if until else None,
            "breadth": breadth_text(reg, row),
            "external": row.get("external"),
            "board_keys": row.get("board_keys") or [],
            "book_run": row.get("book_run"),
            "book_flash": row.get("book_flash"),
            "page": None if row.get("infra") else
                    f"book/src/reference/boards/{page_name(row)}.md",
        })
    doc = {"_generated": reg.stamp("")[1:].strip(), "stale_days": reg.stale_days,
           "rows": rows}
    return json.dumps(doc, indent=2) + "\n"


def outputs(reg: Registry) -> dict[str, str]:
    out = {
        CELLS_RS: render_cells(reg),
        PROBE_JSON: render_probe_json(reg),
        BOOT_ROWS_RS: render_boot_rows(reg),
        STATUS_JSON: render_status_json(reg),
        LEVELS_MD: render_levels(reg),
        SUPPORTED_MD: splice_supported(reg, (reg.root / SUPPORTED_MD).read_text()),
        SUMMARY_MD: splice(SUMMARY_MD, (reg.root / SUMMARY_MD).read_text(),
                           SUMMARY_BEGIN, SUMMARY_END, render_summary_region(reg)),
    }
    for row in board_rows(reg):
        out[f"{BOARDS_DIR}/{page_name(row)}.md"] = render_board_page(reg, row)
    return out


def stale_board_pages(reg: Registry, produced: dict[str, str]) -> list[str]:
    """Evidence pages on disk that no row produces any more."""
    d = reg.root / BOARDS_DIR
    if not d.is_dir():
        return []
    return sorted(f"{BOARDS_DIR}/{p.name}" for p in d.glob("*.md")
                  if f"{BOARDS_DIR}/{p.name}" not in produced)


def stale_views(root: Path, produced: dict[str, str]) -> list[str]:
    return [p for p, text in produced.items()
            if not (root / p).exists() or (root / p).read_text() != text]


def self_test() -> None:
    """Negative controls: a hand edit to a view must read as stale, and the
    cell renderer must keep a cell's status, configuration and comment."""
    import tempfile

    class Fake:
        cell_table = "cells.toml"
        digest = "0" * 16
        cells = [{"at": ["Linux", "Rust", "Zenoh", "Pubsub", "Example"],
                  "status": "Runtime", "with": "&[Config::Lending]",
                  "comment": "// why\n"}]
        probes = [{"track": "t", "chapter": "getting-started/a.md", "variant": "v",
                   "weekly": True, "qemu_board": "b"}]
        stamp = Registry.stamp

    cells = render_cells(Fake())
    assert "    // why\n    cell(Linux, Rust, Zenoh, Pubsub, Example, Runtime)" \
        ".with(&[Config::Lending])," in cells, cells
    rows = render_boot_rows(Fake())
    assert '("a.md", "v", "b"),' in rows, rows
    with tempfile.TemporaryDirectory() as d:
        root = Path(d)
        (root / "v.rs").write_text(cells)
        assert not stale_views(root, {"v.rs": cells})
        (root / "v.rs").write_text(cells.replace("Runtime", "BuildOnly(\"x\")"))
        assert stale_views(root, {"v.rs": cells}) == ["v.rs"], \
            "a hand edit to a generated view must read as stale"
        assert stale_views(root, {"absent.rs": cells}) == ["absent.rs"], \
            "a missing view must read as stale"


def main() -> int:
    self_test()
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", type=Path)
    ap.add_argument("--today", help="evaluate manual-row staleness on this ISO date "
                    "(a demonstration; the tracked views use no clock)")
    args = ap.parse_args()
    reg = Registry(ROOT)
    if args.today:
        import datetime
        reg.today = datetime.date.fromisoformat(args.today)
    produced = outputs(reg)
    if args.check:
        stale = stale_views(ROOT, produced)
        orphans = stale_board_pages(reg, produced)
        for p in stale:
            print(f"[STALE] {p}", file=sys.stderr)
        for p in orphans:
            print(f"[ORPHAN] {p}: an evidence page no registry row produces",
                  file=sys.stderr)
        if stale or orphans:
            print("regenerate: python3 scripts/gen-board-support.py", file=sys.stderr)
            return 1
        print(f"gen-board-support: {len(produced)} view(s) current "
              f"(registry data {reg.digest})")
        return 0
    base = args.out or ROOT
    for p, text in produced.items():
        dest = base / p
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text)
    if not args.out:
        for p in stale_board_pages(reg, produced):
            (ROOT / p).unlink()
            print(f"removed {p}")
    print(f"wrote {len(produced)} view(s) (registry data {reg.digest})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
