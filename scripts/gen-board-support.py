def platform_rows(reg: Registry) -> dict[str, list[dict]]:
    """{book/src page: [rows]} for every row's `book_platform`, in row order.
    Refuses a row RFC-0124 D8 does not admit, and a page whose rows sit in two
    status groups: it splits by status, so its generated header and its
    SUMMARY group stay one."""
    out: dict[str, list[dict]] = {}
    for row in board_rows(reg):
        page = row.get("book_platform")
        if not page:
            continue
        if not page.startswith("guide/platforms/") or "#" in page:
            raise SystemExit(f"{REGISTRY}: `{row['crate']}` book_platform = {page!r}: a page "
                             "under guide/platforms/, with no anchor")
        if book_charter.platform_group(row, reg.status(row)) is None:
            raise SystemExit(f"{REGISTRY}: `{row['crate']}` names the platform page {page}, but "
                             f"its row ({reg.status(row)}) is not admitted to the book (RFC-0124 D8)")
        out.setdefault(f"book/src/{page}", []).append(row)
    for page, rows in out.items():
        groups = {book_charter.platform_group(r, reg.status(r)) for r in rows}
        if len(groups) > 1:
            raise SystemExit(f"{page}: its rows sit in {len(groups)} status groups "
                             f"({', '.join(sorted(groups))}); split the page by status (RFC-0124 D8)")
    return out


