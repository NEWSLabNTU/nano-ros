    # phase-537 W4 — a starter's slot and title come from its row and its H1.
    class Slot:
        def __init__(self, word):
            self.word = word

        def status(self, row):
            return self.word
    twin = {"emulator": "renode:m", "hardware": "b"}
    assert starter_group(Slot("Boots, manual (2026-01-01)"), twin) == (0, "Twin and hardware")
    assert starter_group(Slot("Verified on host (merge)"), {}) == (3, "Verified on host")
