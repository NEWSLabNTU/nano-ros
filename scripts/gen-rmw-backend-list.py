#!/usr/bin/env python3
"""Generate the "Backends in the tree" table of the platform API reference
from the RMW providers the tree announces (phase-545 W4).

RFC-0071 D14 made the provider scan the one answer to "which RMW backends
exist": a backend is a package whose `package.xml` exports
`<nano_ros_provides kind="rmw" name="..."/>`, with an `nros-rmw.toml` beside
it. The book's list of backends was typed by hand and named four of them in
three places; a fifth backend in the tree would have left all three stale.
This script reads the same announcements the CLI's scan reads, over the same
in-tree root (`packages/rmw/`, the scan's `InTreeScope::Rmw`), and writes the
table between the markers below. A backend in the user's own workspace is
found by the same scan at build time; it is not in this table because it is
not in the tree.

One row per package. Columns: the names an image may select
(`rmw = "..."`; the first announcement first, then its aliases), the package, the first
paragraph of the package's `<description>`, and how the backend reaches the
link (`[rmw.provides.cargo] crate` and/or `[rmw.provides.cmake] target` of its
descriptor).

Run:  python3 scripts/gen-rmw-backend-list.py [--check]
Gate: just check rmw-backend-list (fast lane)
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

try:
    import tomllib  # Python 3.11+
except ModuleNotFoundError:  # 3.10
    import tomli as tomllib

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))
import book_pages  # noqa: E402  the page map (RFC-0123 D7)
from tracked import REPO, tracked  # noqa: E402  issue 0721: the index, not a walk

PAGE = book_pages.page_file("reference/platform-api.md")
SCAN_ROOT = "packages/rmw"
SOURCE_URL = "https://github.com/NEWSLabNTU/nano-ros/tree/main/"
BEGIN = "<!-- BEGIN GENERATED by scripts/gen-rmw-backend-list.py: rmw backends -->"
END = "<!-- END GENERATED rmw backends -->"


def first_paragraph(text: str) -> str:
    para = re.split(r"\n\s*\n", (text or "").strip(), maxsplit=1)[0]
    return " ".join(para.split()).replace("|", "\\|")


class Refused(Exception):
    """A provider the table cannot describe."""


def providers(xmls, base: Path) -> list[dict]:
    """One row per `package.xml` in `xmls` that announces an rmw."""
    rows = []
    for xml in xmls:
        root = ET.parse(xml).getroot()
        names = [
            el.get("name")
            for el in root.iter("nano_ros_provides")
            if el.get("kind") == "rmw" and el.get("name")
        ]
        if not names:
            continue
        desc_file = xml.parent / "nros-rmw.toml"
        if not desc_file.is_file():
            raise Refused(f"{xml.relative_to(base)} announces rmw {', '.join(names)} "
                          "with no nros-rmw.toml beside it")
        desc = tomllib.loads(desc_file.read_text()).get("rmw", {})
        provides = desc.get("provides", {})
        link = []
        cargo = provides.get("cargo", {})
        if crate := cargo.get("crate") or cargo.get("register_crate"):
            link.append(f"cargo crate `{crate}`")
        if target := provides.get("cmake", {}).get("target"):
            link.append(f"CMake target `{target}`")
        rows.append({
            "names": names,
            "package": root.findtext("name", "").strip(),
            "about": first_paragraph(root.findtext("description", "")),
            "link": ", ".join(link) or "—",
            "rel": xml.parent.relative_to(base).as_posix(),
        })
    if not rows:
        raise Refused(f"no package under {SCAN_ROOT}/ announces an rmw")
    return sorted(rows, key=lambda r: r["names"][0])


def render(rows: list[dict]) -> str:
    out = [
        BEGIN,
        "",
        "| `rmw =` | Package | About | Links through |",
        "|---|---|---|---|",
    ]
    for r in rows:
        out.append(
            f"| {' or '.join(f'`{n}`' for n in r['names'])} | [`{r['package']}`]({SOURCE_URL}{r['rel']}) "
            f"| {r['about']} | {r['link']} |"
        )
    out += ["", END]
    return "\n".join(out)


def splice(text: str, rows: list[dict]) -> str:
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise Refused(f"the page must hold exactly one `{BEGIN}` … `{END}` region")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + render(rows) + tail


def self_test() -> None:
    """The negative controls, run on every invocation: an alias is a second
    name on one row, a provider with no descriptor is refused, a page whose
    table lacks a backend reads as stale, and a page with no region is
    refused."""
    import tempfile

    def pkg(d: Path, names, desc=True):
        d.mkdir(parents=True)
        provides = "".join(f'<nano_ros_provides kind="rmw" name="{n}"/>' for n in names)
        (d / "package.xml").write_text(
            f"<package><name>{d.name}</name><description>One.\n\nTwo.</description>"
            f"<export>{provides}</export></package>")
        if desc:
            (d / "nros-rmw.toml").write_text('[rmw.provides.cargo]\ncrate = "c"\n')
        return d / "package.xml"

    with tempfile.TemporaryDirectory() as tmp:
        base = Path(tmp)
        a = pkg(base / "a", ["alpha", "rmw-alpha"])
        b = pkg(base / "b", ["beta"])
        rows = providers([b, a], base)
        assert [r["names"] for r in rows] == [["alpha", "rmw-alpha"], ["beta"]], rows
        assert rows[0]["about"] == "One." and rows[0]["link"] == "cargo crate `c`", rows
        page = f"x\n{BEGIN}\n{END}\ny\n"
        full = splice(page, rows)
        assert "`alpha` or `rmw-alpha`" in full and "`beta`" in full, full
        assert splice(full, providers([a], base)) != full, "a dropped backend must read stale"
        for bad in (lambda: providers([pkg(base / "c", ["gamma"], desc=False)], base),
                    lambda: splice("no region", rows)):
            try:
                bad()
            except Refused:
                continue
            raise AssertionError("gen-rmw-backend-list self-test: a refusal did not fire")


def main() -> int:
    self_test()
    check = "--check" in sys.argv[1:]
    text = PAGE.read_text()
    try:
        new = splice(text, providers(tracked(SCAN_ROOT, name="package.xml", repo=REPO), REPO))
    except Refused as e:
        sys.exit(f"gen-rmw-backend-list: {PAGE.relative_to(REPO)}: {e}")
    if new == text:
        return 0
    if check:
        print(f"check-rmw-backend-list: {PAGE.relative_to(REPO)} is stale against the rmw "
              f"providers under {SCAN_ROOT}/.\n  Regenerate: python3 scripts/gen-rmw-backend-list.py",
              file=sys.stderr)
        return 1
    PAGE.write_text(new)
    print(f"gen-rmw-backend-list: wrote {PAGE.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
