#!/usr/bin/env python3
"""Phase 380 W0 — committed generated messages must be CURRENT, in two ways.

Why this needs a gate
---------------------
`nros_serdes::schema::Message::FIELDS` is the static field list a generated
message exposes. Two things read it, and they fail in opposite ways when it is
absent:

* `nros-rmw-cyclonedds` walks it to build a `dds_topic_descriptor_t` at runtime.
  A missing schema there is loud — the backend cannot register the type.
* **`nros_serdes::size` computes a message's serialized size bound from it**
  (phase-380 W1), and a missing schema there is SILENT. The bound simply cannot
  be computed, so phase-380 W4's build-time assertion — "this subscription's
  buffer can hold its own message type" — has nothing to check and passes. The
  subscription then keeps dropping samples in the field, which is the exact
  failure W4 exists to prevent. A check that cannot see its subject does not
  fail; it reports success.

That is why this is a gate and not a convention. Measured 2026-08-26, before
phase-380 W0 regenerated them: **27 of 64** generated message structs in
`packages/interfaces` had no `FIELDS`, including `builtin_interfaces/Time`,
`builtin_interfaces/Duration` and every `rcl_interfaces` service type. The cause
was vintage, not a conditional emitter — those crates were last generated in
March/April 2026 and the schema emitter landed before July, so the three crates
nobody had regenerated since simply predated it. Nothing anywhere said so.

Scope: `packages/interfaces/generated/**`, the pre-generated message crates
this repo COMMITS (CLAUDE.md's exception — core crates need those messages
before any codegen runs). A user's own `generated/` tree is never committed and
is regenerated by `nros sync` from whatever CLI they have, so it is not this
gate's business.

The second property, and why one gate covers both
-------------------------------------------------
Schema presence is not the only thing that goes stale by vintage. The XCDR2
DHEADER wrap (phase-303 W4 / #0267) landed on its own timeline, and a crate can
have one and not the other: `nros-std-msgs-diag`, generated 2026-07-17, carried
`FIELDS` and emitted NO `begin_dheader`, so it could not speak XCDR2 at all —
and the first version of this gate passed it, because it only asked the first
question. That was found by phase-380 W2's property test failing, not by the
gate that exists to prevent exactly this.

So both are checked here. They share one cause (a crate nobody regenerated) and
one remedy (regenerate it), and splitting them across two gates would mean the
next dimension gets its own blind spot.

Exit 0 when every generated message struct declares `FIELDS` and every file with
a `serialize` wraps a DHEADER, 1 otherwise.
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts" / "lib"))
import comments  # noqa: E402  phase-472 W3
import per_item  # noqa: E402  phase-472 W6 — one verdict per struct, per serializer

# A file that declares a message struct. `mod.rs` / `lib.rs` are re-export
# shims and declare none, so they are skipped by the struct test below rather
# than by name — a future layout that puts a struct in `mod.rs` should still be
# checked.
STRUCT_RE = re.compile(r"^pub struct \w+", re.M)
FIELDS_RE = re.compile(r"const FIELDS\s*:")
# phase-303 W4 — a generated `serialize` opens with `begin_dheader()`, a no-op
# under XCDR1 and the appendable delimiter under XCDR2. Its absence means the
# crate predates that emitter and cannot speak XCDR2.
SERIALIZE_RE = re.compile(r"fn serialize\s*\(")
DHEADER_RE = re.compile(r"begin_dheader\s*\(")


def generated_sources() -> list[Path]:
    """Tracked generated sources under `packages/interfaces`.

    Via the git index, not a filesystem walk: an untracked `target/` or a stray
    regeneration output must not be able to fail this gate.
    """
    # phase-465 — ONE output tree, so `generated/` now sits directly under
    # `packages/interfaces/`. The pathspec was
    # `packages/interfaces/**/generated/**/*.rs`, which required a driver-package
    # component before `generated`; after the collapse it matched NOTHING, and the
    # empty-list precondition below is what reported that instead of a green run
    # over zero files.
    out = subprocess.run(
        ["git", "ls-files", "packages/interfaces/generated/**/*.rs"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.split()
    return [ROOT / p for p in out]


# A struct WITH fields (`pub struct X {`). A unit struct (`pub struct Srv;`) is a
# service/action marker and carries no schema.
FIELD_STRUCT_RE = re.compile(r"^pub struct (\w+)\s*(?=\{)", re.M)
SERIALIZE_FN_RE = re.compile(r"\bfn serialize\s*\(")


def audit_text(text):
    """(structs, [struct without FIELDS], serializers, [line of one without a DHEADER]).

    PER ITEM (phase-472 W6). This asked "does the FILE contain a `const FIELDS`
    / a `begin_dheader`", so a service file whose Request carried FIELDS and
    whose Response did not passed — and its "structs" count was files.
    """
    code = comments.strip_comments(text, "rust", strings=True)
    structs = [m.group(1) for m in FIELD_STRUCT_RE.finditer(code)]
    missing = []
    for name in structs:
        impls = per_item.blocks(code, rf"\bimpl\s+[\w:]*\bMessage\s+for\s+{name}\b")
        if not any(FIELDS_RE.search(code[o:e]) for _m, o, e in impls):
            missing.append(name)
    sers = per_item.blocks(code, SERIALIZE_FN_RE)
    no_dh = [per_item.line_of(code, m.start()) for m, o, e in sers
             if not DHEADER_RE.search(code[o:e])]
    return len(structs), missing, len(sers), no_dh


def selftest():
    """Negative controls on the normal path (phase-472 W6/W9)."""
    per_item.self_test()
    one = ("pub struct {n} {{ a: u8 }}\n"
           "impl Serialize for {n} {{ fn serialize(&self, w: &mut W) -> R {{ "
           "let __dh = w.begin_dheader()?; Ok(()) }} }}\n"
           "impl ::nros_serdes::Message for {n} {{ const FIELDS: &'static [F] = &[]; }}\n")
    good = one.format(n="Req") + one.format(n="Resp") + "pub struct Srv;\n"
    assert audit_text(good) == (2, [], 2, []), audit_text(good)
    no_fields = good.replace("const FIELDS", "const NOT_FIELDS", 2).replace(
        "const NOT_FIELDS", "const FIELDS", 1)
    assert audit_text(no_fields)[1] == ["Resp"], audit_text(no_fields)
    no_dh = good[::-1].replace("begin_dheader"[::-1], "no_dheader"[::-1], 1)[::-1]
    assert audit_text(no_dh)[3] == [5], audit_text(no_dh)  # the Response's, line 5
    in_comment = good.replace("const FIELDS: &'static [F] = &[]; }\n",
                              "/* const FIELDS */ }\n")
    assert audit_text(in_comment)[1] == ["Req", "Resp"], audit_text(in_comment)


def main() -> int:
    selftest()
    files = generated_sources()
    # Precondition, not decoration: an empty list would make the loop below
    # vacuous and this gate would report success having checked nothing — the
    # very shape it exists to catch one level down.
    if not files:
        print(
            "error: no tracked generated sources found under packages/interfaces —"
            " this gate would pass having checked nothing",
            file=sys.stderr,
        )
        return 1

    missing = []
    no_dheader = []
    checked = 0
    checked_ser = 0
    for path in files:
        n_st, miss, n_ser, no_dh = audit_text(path.read_text())
        rel = path.relative_to(ROOT)
        checked += n_st
        checked_ser += n_ser
        missing += [f"{rel}: {name}" for name in miss]
        no_dheader += [f"{rel}:{line}" for line in no_dh]

    if not missing and not no_dheader:
        print(
            f"generated schema coverage: OK ({checked} message struct(s) carry FIELDS,"
            f" {checked_ser} serializer(s) wrap a DHEADER)"
        )
        return 0

    if no_dheader and not missing:
        print(
            f"error: {len(no_dheader)} of {checked_ser} generated serializer(s) do not"
            f" wrap a DHEADER, so they cannot speak XCDR2.\n",
            file=sys.stderr,
        )
        for rel in no_dheader[:10]:
            print(f"  {rel}", file=sys.stderr)
        print(REMEDY, file=sys.stderr)
        return 1

    print(
        f"error: {len(missing)} of {checked} generated message struct(s) declare no"
        f" `Message::FIELDS`.\n",
        file=sys.stderr,
    )
    for rel in missing[:10]:
        print(f"  {rel}", file=sys.stderr)
    if len(missing) > 10:
        print(f"  … and {len(missing) - 10} more", file=sys.stderr)
    print(REMEDY_SCHEMA, file=sys.stderr)
    return 1


REMEDY = (
    "\nThe whole set is regenerated by ONE recipe, in place (phase-465 W1):"
    "\n    just generate-interfaces"
    "\nIt needs a ROS 2 ament host. Nothing under `generated/` is hand-maintained"
    "\nany more — the four per-package recipes, and the 'restore the committed"
    "\nCargo.toml afterwards' step they needed, are gone — and the recipe runs"
    "\n`cargo +nightly fmt` on the six crates itself, so a second run is a no-op."
)

REMEDY_SCHEMA = (
    "\nWithout a schema, `nros_serdes::size` cannot compute a bound for the type,"
        "\nso phase-380 W4's build-time buffer assertion has nothing to check and"
    "\nPASSES — the subscription then drops samples at runtime instead."
) + REMEDY


if __name__ == "__main__":
    sys.exit(main())
