#!/usr/bin/env python3
"""Generate `packages/cli/cli-planning-set.txt` -- the CLI's PLANNING set.

Issue 2441. A workspace fixture is built by `nros configure` + `nros build`,
so it is a function of the CLI's PLANNING (the seeds configure writes, the
image statement, the configure options), not only of what its emitters
produce. The fixture signature used to name the CLI by its codegen
fingerprint alone, which planning code does not move, so a planning change
left every workspace fixture reading FRESH. The source stamp (issue 2439's
key) is correct but moves for a `doctor.rs` edit. The ruling (2026-11-12)
took the middle: a fingerprint over the files the fixture road RUNS.

The set, as issue 2441 "Measurements (2026-11-11)" method (b) defined it:

* every in-repo crate the `nros` binary compiles -- the SAME cargo resolve
  `gen-cli-source-dirs.py` makes (`closure_package_dirs`), not a second one;
* minus each crate's test-only trees (`tests/`, `benches/`, `testdata/`,
  `examples/`), which `--bin nros` never compiles;
* minus the `nros-cli-core/src` files the fixture road cannot reach. That is
  the one part with file granularity, and it is COMPUTED: a module-reference
  walk from `lib.rs` (see `reach`). The one authored input is `LEAF_VERBS`,
  the verbs no build runs; the walk enters a leaf only through a dispatcher
  edge, which it drops. Any other edge into a leaf is followed, and then the
  leaf is not a leaf: the generator FAILS and names the edge, so the authored
  list cannot quietly drift into excluding planning code;
* plus `packages/cli/Cargo.{toml,lock}` and this file's own output (it decides
  the set, so it is an input of the stamp over it).

## Why a generated file and not a walk at stamp time

The stamp is computed by `source_stamp.rs`, which `build.rs` `include!`s: no
TOML parser, no `cargo metadata` (cargo holds the package-cache lock during a
build). The crate half therefore has to be recorded, exactly as issue 0604
recorded `cli-source-dirs.txt`; the reach walk is a regex parse of ~185 files
that has no business running on every `nros build`. So both halves are written
here and `check-cli-planning-set` fails when the file disagrees with them.

## Fail-safe direction

The file lists INCLUDED crate dirs and EXCLUDED paths inside them. A new
`nros-cli-core/src` file nobody regenerated for is therefore INSIDE the set
(an over-watch: a fixture restales for nothing) rather than outside it (an
under-watch: a planning change reads fresh). The gate still reports it.

## The walk (over-approximating on purpose)

Per file, after blanking comments, string/char literals and `#[cfg(test)]`
items:

* paths: `crate::a::b`, `self::`, `super::`, and a bare `a::b` resolved as a
  child, a sibling (a `use super::*` brings siblings into scope) or a root
  module; `use` trees are expanded, braces and all. The longest prefix that
  names a module file is the edge;
* macros: a `name!` use is an edge to every file defining `macro_rules! name`;
* impls: `impl [Trait for] T` in a file that does not define `T` is an edge
  INTO that file from every file defining `T` -- a method call reaches an impl
  by type, never by path, so a path walk alone would drop impl-only modules;
* `include!("x.rs")` is an edge to the included file.

`mod x;` declarations are NOT edges: declaring a module runs none of it.

Run: python3 scripts/gen-cli-planning-set.py [--check]
"""

import argparse
import importlib.util
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT_REL = "packages/cli/cli-planning-set.txt"
OUT = REPO / OUT_REL

CORE = "packages/cli/nros-cli-core"
CORE_SRC = f"{CORE}/src"

# Top-level crate subdirectories `--bin nros` never compiles.
TEST_TREES = ("tests", "benches", "testdata", "examples")

# Files that only DISPATCH: they name every verb, so an edge from one of them
# into a verb says "the CLI can run it", not "the build runs it". Their edges
# into a LEAF_VERBS file are dropped; every other edge they have is followed.
DISPATCHERS = {"lib.rs", "cmd/mod.rs", "cmd/dev.rs"}

# THE authored input: verbs no fixture build runs (issue 2441, method (b)'s
# leaf list). Each is checked: reached by anything but a dispatcher, the
# generator fails.
LEAF_VERBS = {
    "cmd/completions.rs",
    "cmd/config.rs",
    "cmd/doctor.rs",
    "cmd/explain.rs",
    "cmd/flash.rs",
    "cmd/graph.rs",
    "cmd/interface.rs",
    "cmd/monitor.rs",
    "cmd/probe_boot_rows.rs",
    "cmd/reserved.rs",
    "cmd/sdk_front.rs",
    "cmd/update.rs",
    "cmd/user.rs",
}

# The workspace-level files every crate compiles under.
WORKSPACE_FILES = ("packages/cli/Cargo.lock", "packages/cli/Cargo.toml")

HEADER = """\
# GENERATED by scripts/gen-cli-planning-set.py -- do not edit by hand.
#
# Issue 2441 -- the CLI's PLANNING set: what the workspace fixture road runs.
# `nros planning-stamp` (source_stamp.rs) hashes every tracked or untracked
# source under a `+` path that no `-` path covers; workspace fixtures and the
# `nros configure` stamp key on that hash. `check-cli-planning-set` fails when
# this file disagrees with cargo's resolve or with the reach walk.
#
# Regenerate: python3 scripts/gen-cli-planning-set.py
"""


def _load_source_dirs():
    spec = importlib.util.spec_from_file_location(
        "gen_cli_source_dirs", REPO / "scripts" / "gen-cli-source-dirs.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def git_ls(*paths):
    out = subprocess.run(["git", "-C", str(REPO), "ls-files", "--", *paths],
                         capture_output=True, text=True, check=True).stdout
    return [line for line in out.splitlines() if line]


# --------------------------------------------------------------------------
# Lexing: blank comments and literals, keeping offsets (so a span found in the
# blanked text cuts the same span out of the raw one).

def blank(text):
    out = list(text)
    i, n = 0, len(text)

    def wipe(a, b):
        for k in range(a, b):
            if out[k] != "\n":
                out[k] = " "

    while i < n:
        c = text[i]
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            wipe(i, j)
            i = j
        elif text.startswith("/*", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if text.startswith("/*", j):
                    depth, j = depth + 1, j + 2
                elif text.startswith("*/", j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
            wipe(i, j)
            i = j
        elif (c == "r" or (c == "b" and text.startswith("br", i))) and \
                re.match(r"b?r#*\"", text[i:i + 40]) and \
                (i == 0 or not (text[i - 1].isalnum() or text[i - 1] == "_")):
            m = re.match(r"b?r(#*)\"", text[i:])
            close = '"' + m.group(1)
            j = text.find(close, i + m.end())
            j = n if j < 0 else j + len(close)
            wipe(i + 1, j)
            i = j
        elif c == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            wipe(i + 1, j)
            i = j + 1
        elif c == "'":
            m = re.match(r"'(?:\\.[^']{0,8}|[^'\\])'", text[i:])
            if m:
                wipe(i + 1, i + m.end() - 1)
                i += m.end()
            else:
                i += 1  # a lifetime
        else:
            i += 1
    return "".join(out)


CFG_TEST = re.compile(r"#\[cfg\((?:test|all\(\s*test\b[^\]]*)\)\]")


def item_end(clean, i):
    """End of the item starting at `i`: its `;` or its matching `}`."""
    n = len(clean)
    while True:  # skip further attributes
        m = re.compile(r"\s*#\[").match(clean, i)
        if not m:
            break
        j, depth = m.end(), 1
        while j < n and depth:
            depth += {"[": 1, "]": -1}.get(clean[j], 0)
            j += 1
        i = j
    depth = 0
    while i < n:
        c = clean[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        elif c == ";" and depth == 0:
            return i + 1
        i += 1
    return n


def strip_tests(raw):
    clean = blank(raw)
    spans = []
    for m in CFG_TEST.finditer(clean):
        spans.append((m.start(), item_end(clean, m.end())))
    keep_clean, keep_raw, last = [], [], 0
    for a, b in sorted(spans):
        if a < last:
            continue
        keep_clean.append(clean[last:a])
        keep_raw.append(raw[last:a])
        last = b
    keep_clean.append(clean[last:])
    keep_raw.append(raw[last:])
    return "".join(keep_clean), "".join(keep_raw)


# --------------------------------------------------------------------------
# Module paths.

def module_of(rel):
    parts = rel[:-3].split("/")
    if parts[-1] in ("mod", "lib"):
        parts = parts[:-1]
    return tuple(parts)


IDENT = r"[A-Za-z_][A-Za-z0-9_]*"
PATH = re.compile(rf"(?<![A-Za-z0-9_:]){IDENT}(?:\s*::\s*{IDENT})+")
USE = re.compile(r"\buse\s+([^;]*);")


def expand_use(tree):
    """`a::{b, c::{d as e, self}}` -> [([a,b],b), ([a,c,d],e), ([a,c],c)].

    Each leaf of a `use` tree with the name it BINDS (its alias, else its last
    segment), so a later `e::x` can be resolved through it.
    """
    tree = re.sub(r"\s+as\s+", " as ", tree)
    tree = re.sub(r"\s+(?!as )", "", tree.replace(" as ", "\0")).replace("\0", " as ")
    out = []

    def go(prefix, s):
        depth, parts, cur = 0, [], ""
        for ch in s:
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
            if ch == "," and depth == 0:
                parts.append(cur)
                cur = ""
            else:
                cur += ch
        parts.append(cur)
        for p in parts:
            p = p.strip()
            if not p:
                continue
            if "{" in p:
                head, rest = p.split("{", 1)
                head = [x for x in head.split("::") if x]
                go(prefix + head, rest[:rest.rfind("}")])
                continue
            alias = None
            if " as " in p:
                p, alias = p.split(" as ", 1)
            segs = [x for x in p.split("::") if x and x != "*"]
            if segs and segs[-1] == "self":
                segs = segs[:-1]
            segs = prefix + segs
            if segs:
                out.append((segs, alias or segs[-1]))

    go([], tree)
    return out


class Crate:
    def __init__(self, files):
        self.files = files  # rel (to src) -> raw text
        self.by_mod = {module_of(f): f for f in files}

    def bases(self, me, segs, binds):
        """(module base, remaining segments) candidates for a path in `me`."""
        if segs[0] == "crate":
            return [((), segs[1:])]
        if segs[0] == "self":
            return [(me, segs[1:])]
        if segs[0] == "super":
            base = me
            while segs and segs[0] == "super":
                base, segs = base[:-1], segs[1:]
            return [(base, segs)]
        out = [(b, segs) for b in (me, me[:-1], ())]  # child, sibling, root
        out += [(m, segs[1:]) for m in binds.get(segs[0], ())]
        return out

    def modules(self, me, segs, binds):
        """Module paths (tuples) a path names: the longest existing prefix."""
        segs = [s for s in segs if s]
        if not segs:
            return set()
        hits = set()
        for base, rest in self.bases(me, segs, binds):
            for k in range(len(rest), -1, -1):
                mod = base + tuple(rest[:k])
                if mod in self.by_mod and (k or base != () or not rest):
                    hits.add(mod)
                    break
        return hits

    def exact(self, me, segs, binds):
        """Module a `use` path names EXACTLY (it imports a module), if any."""
        segs = [s for s in segs if s]
        if not segs:
            return set()
        return {base + tuple(rest) for base, rest in self.bases(me, segs, binds)
                if base + tuple(rest) in self.by_mod and (rest or base != ())}

    def resolve(self, me, segs, binds=None):
        return {self.by_mod[m] for m in self.modules(me, segs, binds or {})}


DEF = re.compile(rf"\b(?:struct|enum|union|trait|type)\s+({IDENT})")
MACRO_DEF = re.compile(rf"\bmacro_rules!\s*({IDENT})")
MACRO_USE = re.compile(rf"(?<![A-Za-z0-9_])({IDENT})!")
IMPL = re.compile(r"\bimpl\b")
INCLUDE = re.compile(r'\binclude!\(\s*"([^"]+\.rs)"\s*\)')


def impl_target(clean, at):
    """Self type name of the `impl` at `at`, and its generic parameter names."""
    i, n = at + 4, len(clean)
    generics = set()
    m = re.compile(r"\s*<").match(clean, i)
    if m:
        j, depth = m.end(), 1
        while j < n and depth:
            depth += {"<": 1, ">": -1}.get(clean[j], 0)
            j += 1
        generics = set(re.findall(rf"(?:^|[<,])\s*({IDENT})", clean[m.end() - 1:j]))
        i = j
    j = clean.find("{", i)
    head = clean[i:j if j >= 0 else n]
    head = head.split(" where ")[0]
    if re.search(r"\bfor\b", head):
        head = re.split(r"\bfor\b", head, maxsplit=1)[1]
    head = re.sub(r"<.*", "", head, flags=re.S).strip()
    names = re.findall(IDENT, head)
    names = [x for x in names if x not in ("dyn", "mut", "const")]
    return (names[-1] if names else None), generics


def edges_of(crate):
    defs, macros = {}, {}
    cleaned = {}
    for f, raw in crate.files.items():
        clean, raw_kept = strip_tests(raw)
        cleaned[f] = (clean, raw_kept)
        for m in DEF.finditer(clean):
            defs.setdefault(m.group(1), set()).add(f)
        for m in MACRO_DEF.finditer(clean):
            macros.setdefault(m.group(1), set()).add(f)

    edges = {f: {} for f in crate.files}  # src -> {dst: why}

    def add(a, b, why):
        if a != b and b not in edges[a]:
            edges[a][b] = why

    for f, (clean, raw_kept) in cleaned.items():
        me = module_of(f)
        # A `use` binding a MODULE (`use crate::codegen::entry as ec;`, or just
        # `use super::build;`) makes `ec::x` / `build::x` resolve through it.
        # Bound file-wide: a function-local `use` shadows nothing we care
        # about, and over-binding only adds edges.
        binds, uses = {}, []
        for m in USE.finditer(clean):
            uses += expand_use(m.group(1))
        for _ in range(3):  # a binding may be spelled through an earlier one
            for segs, name in uses:
                for mod in crate.exact(me, segs, binds):
                    binds.setdefault(name, set()).add(mod)
        for segs, _name in uses:
            for d in crate.resolve(me, segs, binds):
                add(f, d, "use " + "::".join(segs))
        for m in PATH.finditer(clean):
            segs = re.sub(r"\s+", "", m.group(0)).split("::")
            for d in crate.resolve(me, segs, binds):
                add(f, d, "::".join(segs))
        for m in MACRO_USE.finditer(clean):
            for d in macros.get(m.group(1), ()):
                add(f, d, m.group(1) + "!")
        for m in INCLUDE.finditer(raw_kept):
            d = str((Path(f).parent / m.group(1)).as_posix())
            if d in crate.files:
                add(f, d, f'include!("{m.group(1)}")')
        local = {m.group(1) for m in DEF.finditer(clean)}
        for m in IMPL.finditer(clean):
            ty, generics = impl_target(clean, m.start())
            if not ty or ty in local or ty in generics:
                continue
            for d in defs.get(ty, ()):
                add(d, f, f"impl {ty}")
    return edges


def reach(crate):
    edges = edges_of(crate)
    seen, stack = {"lib.rs": None}, ["lib.rs"]
    while stack:
        f = stack.pop()
        for d, why in edges[f].items():
            if d in LEAF_VERBS and f in DISPATCHERS:
                continue
            if d not in seen:
                seen[d] = (f, why)
                stack.append(d)
    return seen


def core_exclusions():
    files = {}
    for rel in git_ls(CORE_SRC):
        if rel.endswith(".rs"):
            files[rel[len(CORE_SRC) + 1:]] = (REPO / rel).read_text()
    missing = (LEAF_VERBS | DISPATCHERS) - files.keys()
    if missing:
        raise SystemExit(
            "gen-cli-planning-set: LEAF_VERBS/DISPATCHERS name files that do not "
            f"exist under {CORE_SRC}: {sorted(missing)} -- drop the entry")
    seen = reach(Crate(files))
    bad = []
    for leaf in sorted(LEAF_VERBS & seen.keys()):
        src, why = seen[leaf]
        bad.append(f"  {leaf} is reached from {src} (`{why}`)")
    if bad:
        raise SystemExit(
            "gen-cli-planning-set: a LEAF_VERBS entry is not a leaf -- planning "
            "code reaches it, so it belongs in the planning set:\n" + "\n".join(bad)
            + "\n  Drop it from LEAF_VERBS (scripts/gen-cli-planning-set.py).")
    return sorted(f"{CORE_SRC}/{f}" for f in files if f not in seen), len(files)


def planning_set():
    crates = sorted(_load_source_dirs().closure_package_dirs())
    plus = sorted(set(crates) | set(WORKSPACE_FILES) | {OUT_REL})
    minus = []
    for d in crates:
        subs = {p[len(d) + 1:].split("/", 1)[0] for p in git_ls(d) if "/" in p[len(d) + 1:]}
        minus += [f"{d}/{t}" for t in TEST_TREES if t in subs]
    core_minus, n_core = core_exclusions()
    return plus, sorted(minus + core_minus), n_core


def render(plus, minus):
    return (HEADER + "".join(f"+ {p}\n" for p in plus)
            + "".join(f"- {m}\n" for m in minus))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="fail if the committed file disagrees with the resolve + walk")
    args = ap.parse_args()

    plus, minus, n_core = planning_set()
    want = render(plus, minus)
    n_core_minus = sum(1 for m in minus if m.startswith(CORE_SRC + "/"))
    summary = (f"{len(plus)} included path(s), {len(minus)} excluded; "
               f"{n_core - n_core_minus} of {n_core} {CORE_SRC} files reached")

    if not args.check:
        OUT.write_text(want)
        print(f"gen-cli-planning-set: wrote {OUT_REL} ({summary})")
        return 0

    have = OUT.read_text() if OUT.is_file() else ""
    if have == want:
        print(f"check-cli-planning-set: OK ({summary})")
        return 0

    def body(text):
        return {line for line in text.splitlines() if line and not line.startswith("#")}

    hb, wb = body(have), body(want)
    print(f"check-cli-planning-set: {OUT_REL} is out of date.", file=sys.stderr)
    for line in sorted(wb - hb):
        what = ("the CLI plans with it; the fixture key and configure stamp are BLIND "
                "to edits there" if line.startswith("+") else
                "planning no longer reaches it; edits there restale every workspace "
                "fixture for nothing")
        print(f"  want {line}   ({what})", file=sys.stderr)
    for line in sorted(hb - wb):
        what = ("the CLI no longer compiles it; edits there restale every workspace "
                "fixture for nothing" if line.startswith("+") else
                "planning NOW reaches it; the fixture key and configure stamp are "
                "BLIND to edits there")
        print(f"  drop {line}   ({what})", file=sys.stderr)
    print("\n  Regenerate:  python3 scripts/gen-cli-planning-set.py\n", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
