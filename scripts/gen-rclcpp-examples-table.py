#!/usr/bin/env python3
"""Render the measured ros2/examples table in reference/rclcpp-compatibility.

`packages/api/nros-cpp/tests/compile/rclcpp-examples/edits.json` records, per
stock rclcpp example, how many lines its port edits and why each remaining edit
is needed; `edit_count.py --check` holds the counts to the upstream/ported file
pairs. The book's table is that record, so it is rendered from it between the
`rclcpp-examples` markers and never typed (RFC-0124 Principle 9, phase-537
W11). The rest of the page is hand-kept.

Internal ids in a cause (`RFC-0018`, `issue 2015`) are dropped: the reader has
no tree to look them up in.

Run:  python3 scripts/gen-rclcpp-examples-table.py [--check | --self-test]
Gate: just check rclcpp-examples-table
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE / "lib"))
import book_pages  # noqa: E402

PAGE = "reference/rclcpp-compatibility.md"
RECORD = ROOT / "packages/api/nros-cpp/tests/compile/rclcpp-examples/edits.json"
BEGIN = "<!-- rclcpp-examples:begin (generated by scripts/gen-rclcpp-examples-table.py) -->"
END = "<!-- rclcpp-examples:end -->"
ID = r"(?:RFC-?\d{4}|[Ii]ssue \d{3,4}|[Pp]hase[- ]\d{2,4}(?: W\d+)?)"


def scrub(text: str) -> str:
    text = re.sub(r"\s*\(" + ID + r"\)", "", text)          # "(issue 2015)"
    text = re.sub(r"\(" + ID + r"[,;:]\s*", "(", text)      # "(RFC-0018, -fno-exceptions"
    text = re.sub(r",\s*" + ID + r"(?=[,;)])", "", text)    # "..., RFC-0090, for one line"
    text = re.sub(r"\s+\(\)", "", text)
    if re.search(ID, text):
        sys.exit(f"gen-rclcpp-examples-table: an id this script cannot drop: {text!r}")
    return text


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def render(record: dict) -> str:
    rows = ["| Example | Edited lines | What the edits are |", "| --- | --- | --- |"]
    for _, ex in record["examples"].items():
        why = "; ".join(scrub(r) for r in ex["remaining"]) or "—"
        rows.append(f"| `{ex['source']}` | {ex['edited_lines']} | {cell(why)} |")
    return "\n".join([BEGIN, *rows, END])


def splice(page: str, region: str) -> str:
    i, j = page.find(BEGIN), page.find(END)
    if i < 0 or j < i:
        sys.exit(f"gen-rclcpp-examples-table: {PAGE} has no {BEGIN!r} … {END!r} region")
    return page[:i] + region + page[j + len(END):]


def self_test() -> None:
    assert scrub("exceptions: removed (RFC-0018, -fno-exceptions; x)") == "exceptions: removed (-fno-exceptions; x)"
    assert scrub("races (issue 2015)") == "races"
    assert scrub("would move it, RFC-0090, for one line") == "would move it, for one line"
    rec = {"examples": {"a": {"source": "x/a.cpp", "edited_lines": 0, "remaining": []},
                        "b": {"source": "x/b.cpp", "edited_lines": 3, "remaining": ["one | two"]}}}
    out = render(rec)
    assert "| `x/a.cpp` | 0 | — |" in out and "| `x/b.cpp` | 3 | one \\| two |" in out, out
    page = f"head\n{BEGIN}\nold\n{END}\ntail\n"
    assert splice(page, out) == f"head\n{out}\ntail\n"
    try:
        splice("no region", out)
    except SystemExit:
        pass
    else:
        raise AssertionError("a page with no region passed")


def main() -> int:
    self_test()
    if "--self-test" in sys.argv:
        print("gen-rclcpp-examples-table self-test: OK")
        return 0
    path = next((p.current() or p.target) for p in book_pages.load()
                if p.book == "user" and p.path == PAGE)
    page = path.read_text(encoding="utf8")
    want = splice(page, render(json.loads(RECORD.read_text(encoding="utf8"))))
    if "--check" in sys.argv:
        if page != want:
            sys.exit(f"gen-rclcpp-examples-table: STALE — {path.relative_to(ROOT)} differs from "
                     f"{RECORD.relative_to(ROOT)}. Regenerate: python3 scripts/gen-rclcpp-examples-table.py")
        print(f"rclcpp-examples-table OK ({len(json.loads(RECORD.read_text())['examples'])} examples)")
        return 0
    path.write_text(want, encoding="utf8")
    print(f"wrote the rclcpp-examples table in {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
