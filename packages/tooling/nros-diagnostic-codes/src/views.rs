//! The views generated from [`ALL`](crate::ALL) (RFC-0129 D3, D4).
//!
//! Each returns the whole file as a `String`; `nros-diagnostics-gen` writes
//! them, and with `--check` compares them with what is committed.

use std::{format, string::String, vec::Vec};

use crate::{ALL, Entry};

/// The heading that starts an explanation's history section. Everything from
/// it on is for contributors: the book page shows it, `nros explain` does not.
pub const DESIGN_BACKGROUND: &str = "## Design background";

/// `codes.lock`: one line per code ever allocated.
#[must_use]
pub fn lock() -> String {
    let mut out = String::from(
        "# GENERATED by nros-diagnostics-gen from src/codes.rs. Do not edit by hand.\n\
         #\n\
         # Every diagnostic code ever allocated, one per line: the code, its name, and\n\
         # `live` or `retired <successor>`. A row may be added or retired, never removed\n\
         # or renumbered; check-diagnostics holds this file to origin/main's copy.\n\
         #\n\
         # Every number is CLAIMED on origin before it is written here, with\n\
         # `just code-new <Name>` (a ref `refs/diag-codes/NNNN`); the pre-push hook\n\
         # refuses a new number with no claim. The one exception is the founding\n\
         # range below, allocated in the founding commit before claims existed: it\n\
         # has no claim refs, and the guard exempts exactly this range. It never grows.\n\
         #\n",
    );
    out.push_str(&format!(
        "# founding: NROS-0001..NROS-{:04}\n",
        crate::FOUNDING_MAX
    ));
    for e in ALL {
        match e.successor() {
            None => out.push_str(&format!("{} {} live\n", e.code, e.name)),
            Some(s) => out.push_str(&format!("{} {} retired {}\n", e.code, e.name, s.code)),
        }
    }
    out
}

/// One parsed `codes.lock` row: code, name, and whether it is live.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockRow {
    /// `NROS-NNNN`.
    pub code: String,
    /// The declared name.
    pub name: String,
    /// `live` or `retired`.
    pub live: bool,
}

/// Parse `codes.lock` text. Comment and blank lines are skipped; a line that
/// is not a row is returned as an error naming it.
pub fn parse_lock(text: &str) -> Result<Vec<LockRow>, String> {
    let mut rows = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let f: Vec<&str> = line.split_whitespace().collect();
        let live = match f.as_slice() {
            [_, _, "live"] => true,
            [_, _, "retired", _] => false,
            _ => return Err(format!("codes.lock: cannot read the line `{line}`")),
        };
        rows.push(LockRow {
            code: f[0].into(),
            name: f[1].into(),
            live,
        });
    }
    Ok(rows)
}

/// The explanation without its `## Design background` section: what a user
/// reads in `nros explain`.
#[must_use]
pub fn user_explanation(e: &Entry) -> &'static str {
    let text = e.explanation;
    let cut = text
        .match_indices(DESIGN_BACKGROUND)
        .find(|(i, _)| *i == 0 || text.as_bytes()[i - 1] == b'\n')
        .map_or(text.len(), |(i, _)| i);
    text[..cut].trim_end()
}

/// What `nros explain NROS-NNNN` prints for an entry, live or retired.
#[must_use]
pub fn explain_text(e: &Entry) -> String {
    explain_text_in(e, ALL)
}

/// [`explain_text`] with a retired code's successor looked up in `table`.
#[must_use]
pub fn explain_text_in(e: &Entry, table: &[Entry]) -> String {
    let successor = e.retired.and_then(|n| table.iter().find(|s| s.number == n));
    match (e.retired, successor) {
        (Some(n), None) => format!(
            "{}: retired.\n\nThis code is no longer raised. Its successor, NROS-{n:04}, is \
             unknown to this binary.\n",
            e.code
        ),
        (_, Some(s)) => format!(
            "{}: retired.\n\nThis code is no longer raised. It was replaced by {}: {}\n\
             Run `nros explain {}` for its explanation.\n",
            e.code, s.code, s.title, s.code
        ),
        (None, None) => format!(
            "{}: {}\n\n{}\n\nThe refusal's help line: {}\n",
            e.code,
            e.title,
            user_explanation(e),
            e.remedy
        ),
    }
}

/// The book's reference page: an index of every code, then one section per
/// live code (its anchor is the code, `#NROS-0004`). The section is what
/// `nros explain` prints, without the design background, which is for
/// maintainers. One page, so the book's sidebar lists the page and not
/// every code.
#[must_use]
pub fn book_page() -> String {
    let mut out = String::from(
        "<!-- GENERATED by nros-diagnostics-gen. Do not edit by hand; edit the \
         crate packages/tooling/nros-diagnostic-codes. -->\n\n\
         # Diagnostic codes\n\n\
         <!-- type: reference · level: 1 -->\n\n\
         Every refusal nano-ros prints carries a code, `NROS-` and four digits:\n\n\
         ```text\n\
         error[NROS-0004]: src/demo_bringup/system.toml: names no board\n  \
         help: add `board = \"<board>\"` to the `[image.<id>]` table in system.toml\n  \
         explain: nros explain NROS-0004\n\
         ```\n\n\
         The `explain:` line is a command: `nros explain NROS-0004` prints the\n\
         code's section below without a network or a checkout. A code never\n\
         changes its meaning, and a retired code names the one that replaced it.\n\n\
         | Code | What went wrong |\n\
         | --- | --- |\n",
    );
    for e in ALL {
        match e.successor() {
            None => out.push_str(&format!("| [{c}](#{c}) | {} |\n", e.title, c = e.code)),
            Some(s) => out.push_str(&format!(
                "| {} | retired; replaced by [{c}](#{c}) |\n",
                e.code,
                c = s.code
            )),
        }
    }
    for e in ALL.iter().filter(|e| e.is_live()) {
        out.push_str(&book_section(e));
    }
    out
}

/// One live code's section of the book page. The explanation's own `##`
/// headings sit one level down, under the code's.
fn book_section(e: &Entry) -> String {
    let mut body = String::new();
    for (i, l) in user_explanation(e).lines().enumerate() {
        if i > 0 {
            body.push('\n');
        }
        if l.starts_with("## ") {
            body.push('#');
        }
        body.push_str(l);
    }
    format!(
        "\n<a id=\"{c}\"></a>\n\n\
         ## {c}: {}\n\n\
         {body}\n\n\
         The refusal's `help` line, unless the site gives a more specific one:\n\n\
         > {}\n\n\
         [Back to the list of codes](#diagnostic-codes)\n",
        e.title,
        e.remedy,
        c = e.code
    )
}

/// A declared name as a C macro suffix: `AmentPrefixUnset` -> `AMENT_PREFIX_UNSET`.
#[must_use]
pub fn upper_snake(name: &str) -> String {
    let mut out = String::new();
    for (i, ch) in name.chars().enumerate() {
        if ch.is_ascii_uppercase() && i > 0 {
            out.push('_');
        }
        out.push(ch.to_ascii_uppercase());
    }
    out
}

/// `s` as a CMake quoted argument's body. A `;` needs no escape there (a
/// quoted argument is never split), and `\;` would be kept literally.
fn cmake_quote(s: &str) -> String {
    let mut out = String::new();
    for ch in s.chars() {
        match ch {
            '\\' | '"' | '$' => {
                out.push('\\');
                out.push(ch);
            }
            '\n' => out.push_str("\\n"),
            _ => out.push(ch),
        }
    }
    out
}

/// `s` as a Python string literal (double-quoted).
fn py_quote(s: &str) -> String {
    let mut out = String::from("\"");
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            _ => out.push(ch),
        }
    }
    out.push('"');
    out
}

/// The CMake view: `nros_refuse(<Name> <detail>... [HELP <text>])` stops the
/// configure with the refusal rendered as every surface renders it, and an
/// unknown or retired name is itself a configure error.
#[must_use]
pub fn cmake_module() -> String {
    let mut out = String::from(
        "# GENERATED by nros-diagnostics-gen from packages/tooling/nros-diagnostic-codes.\n\
         # Do not edit by hand: declare or retire a code in src/codes.rs and regenerate.\n\
         #\n\
         # nros_refuse(<Name> <detail>... [HELP <text>])\n\
         #\n\
         # Stops the configure with the refusal for the code declared as <Name>:\n\
         #\n\
         #   error[NROS-NNNN]: <detail>\n\
         #     help: <text, or the code's remedy>\n\
         #     explain: nros explain NROS-NNNN\n\
         #\n\
         # The <detail> arguments are concatenated, as message() does. A name no\n\
         # live code was declared with is a configure error of its own.\n\
         \n\
         include_guard(GLOBAL)\n\
         \n",
    );
    for e in ALL.iter().filter(|e| e.is_live()) {
        out.push_str(&format!(
            "set(_NROS_DIAG_CODE_{n} \"{}\")\nset(_NROS_DIAG_REMEDY_{n} \"{}\")\n",
            e.code,
            cmake_quote(e.remedy),
            n = e.name
        ));
    }
    for e in ALL {
        if let Some(s) = e.successor() {
            out.push_str(&format!(
                "set(_NROS_DIAG_RETIRED_{} \"{}\")\n",
                e.name, s.name
            ));
        }
    }
    out.push_str(
        "\n\
         function(nros_refuse _name)\n    \
             if(DEFINED _NROS_DIAG_RETIRED_${_name})\n        \
                 message(FATAL_ERROR \"nros_refuse: `${_name}` is retired; raise \
         `${_NROS_DIAG_RETIRED_${_name}}` instead\")\n    \
             endif()\n    \
             if(NOT DEFINED _NROS_DIAG_CODE_${_name})\n        \
                 message(FATAL_ERROR \"nros_refuse: no diagnostic code is declared as \
         `${_name}`; declare it in packages/tooling/nros-diagnostic-codes/src/codes.rs\")\n    \
             endif()\n    \
             cmake_parse_arguments(PARSE_ARGV 1 _r \"\" \"HELP\" \"\")\n    \
             string(CONCAT _detail ${_r_UNPARSED_ARGUMENTS})\n    \
             if(DEFINED _r_HELP)\n        \
                 set(_help \"${_r_HELP}\")\n    \
             else()\n        \
                 set(_help \"${_NROS_DIAG_REMEDY_${_name}}\")\n    \
             endif()\n    \
             set(_code \"${_NROS_DIAG_CODE_${_name}}\")\n    \
             message(FATAL_ERROR \"error[${_code}]: ${_detail}\\n  help: ${_help}\\n  \
         explain: nros explain ${_code}\")\n\
         endfunction()\n",
    );
    out
}

/// The C header: `NROS_DIAG_<NAME>`, the code as a string, for a C or C++
/// runtime log site.
#[must_use]
pub fn c_header() -> String {
    let mut out = String::from(
        "/* GENERATED by nros-diagnostics-gen from packages/tooling/nros-diagnostic-codes.\n \
         * Do not edit by hand: declare or retire a code in src/codes.rs and regenerate.\n \
         *\n \
         * One macro per live diagnostic code, the code as printed. A refusal\n \
         * prints `error[<code>]: ...` and ends with `explain: nros explain <code>`;\n \
         * `nros explain <code>` says what went wrong and how to fix it.\n \
         */\n\
         #ifndef NROS_DIAGNOSTICS_H\n\
         #define NROS_DIAGNOSTICS_H\n\n",
    );
    for e in ALL.iter().filter(|e| e.is_live()) {
        out.push_str(&format!(
            "/** {} */\n#define NROS_DIAG_{} \"{}\"\n",
            e.title,
            upper_snake(e.name),
            e.code
        ));
    }
    out.push_str("\n#endif /* NROS_DIAGNOSTICS_H */\n");
    out
}

/// The colcon plugin's view: every live code by name, and `refuse()`, which
/// renders a refusal the way every other surface does.
#[must_use]
pub fn colcon_module() -> String {
    let mut out = String::from(
        "# GENERATED by nros-diagnostics-gen from packages/tooling/nros-diagnostic-codes.\n\
         # Do not edit by hand: declare or retire a code in src/codes.rs and regenerate.\n\
         \"\"\"The diagnostic codes, for the plugin's refusals.\n\
         \n\
         `refuse(name, detail)` renders a refusal as every nano-ros surface does:\n\
         \n\
         \x20   error[NROS-NNNN]: <detail>\n\
         \x20     help: <help, or the code's remedy>\n\
         \x20     explain: nros explain NROS-NNNN\n\
         \"\"\"\n\
         \n\
         # name: (code, title, remedy)\n\
         CODES = {\n",
    );
    for e in ALL.iter().filter(|e| e.is_live()) {
        out.push_str(&format!(
            "    {}: ({}, {}, {}),\n",
            py_quote(e.name),
            py_quote(e.code),
            py_quote(e.title),
            py_quote(e.remedy)
        ));
    }
    out.push_str(
        "}\n\
         \n\
         \n\
         def refuse(name, detail, help=None):\n    \
             \"\"\"The refusal for the code declared as `name`, rendered.\"\"\"\n    \
             if name not in CODES:\n        \
                 raise KeyError(\n            \
                     f\"no diagnostic code is declared as `{name}`; declare it in \"\n            \
                     \"packages/tooling/nros-diagnostic-codes/src/codes.rs\"\n        \
                 )\n    \
             code, _title, remedy = CODES[name]\n    \
             return (\n        \
                 f\"error[{code}]: {detail}\\n\"\n        \
                 f\"  help: {help if help is not None else remedy}\\n\"\n        \
                 f\"  explain: nros explain {code}\"\n    \
             )\n",
    );
    out
}

/// Every generated file, as (path relative to the repository root, content).
#[must_use]
pub fn all_files() -> Vec<(String, String)> {
    let files = std::vec![
        (
            "packages/tooling/nros-diagnostic-codes/codes.lock".into(),
            lock(),
        ),
        (BOOK_PAGE.into(), book_page()),
        (CMAKE_MODULE.into(), cmake_module()),
        (C_HEADER.into(), c_header()),
        (COLCON_MODULE.into(), colcon_module()),
    ];
    files
}

