//! The views generated from [`ALL`](crate::ALL) (RFC-0129 D3, D4).
//!
//! Each returns the whole file as a `String`; `nros-diagnostics-gen` writes
//! them, and with `--check` compares them with what is committed.

use std::{format, string::String, vec::Vec};

use crate::{ALL, Entry};

/// The heading that starts an explanation's history section. Everything from
/// it on is for contributors: the book page shows it, `nros explain` does not.
pub const DESIGN_BACKGROUND: &str = "## Design background";

/// `codes.lock`: one line per code ever allocated.
#[must_use]
pub fn lock() -> String {
    let mut out = String::from(
        "# GENERATED by nros-diagnostics-gen from src/codes.rs. Do not edit by hand.\n\
         #\n\
         # Every diagnostic code ever allocated, one per line: the code, its name, and\n\
         # `live` or `retired <successor>`. A row may be added or retired, never removed\n\
         # or renumbered; check-diagnostics holds this file to origin/main's copy.\n\
         #\n\
         # Every number is CLAIMED on origin before it is written here, with\n\
         # `just code-new <Name>` (a ref `refs/diag-codes/NNNN`); the pre-push hook\n\
         # refuses a new number with no claim. The one exception is the founding\n\
         # range below, allocated in the founding commit before claims existed: it\n\
         # has no claim refs, and the guard exempts exactly this range. It never grows.\n\
         #\n",
    );
    out.push_str(&format!(
        "# founding: NROS-0001..NROS-{:04}\n",
        crate::FOUNDING_MAX
    ));
    for e in ALL {
        match e.successor() {
            None => out.push_str(&format!("{} {} live\n", e.code, e.name)),
            Some(s) => out.push_str(&format!("{} {} retired {}\n", e.code, e.name, s.code)),
        }
    }
    out
}

/// One parsed `codes.lock` row: code, name, and whether it is live.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockRow {
    /// `NROS-NNNN`.
    pub code: String,
    /// The declared name.
    pub name: String,
    /// `live` or `retired`.
    pub live: bool,
}

/// Parse `codes.lock` text. Comment and blank lines are skipped; a line that
/// is not a row is returned as an error naming it.
pub fn parse_lock(text: &str) -> Result<Vec<LockRow>, String> {
    let mut rows = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let f: Vec<&str> = line.split_whitespace().collect();
        let live = match f.as_slice() {
            [_, _, "live"] => true,
            [_, _, "retired", _] => false,
            _ => return Err(format!("codes.lock: cannot read the line `{line}`")),
        };
        rows.push(LockRow {
            code: f[0].into(),
            name: f[1].into(),
            live,
        });
    }
    Ok(rows)
}

/// The explanation without its `## Design background` section: what a user
/// reads in `nros explain`.
#[must_use]
pub fn user_explanation(e: &Entry) -> &'static str {
    let text = e.explanation;
    let cut = text
        .match_indices(DESIGN_BACKGROUND)
        .find(|(i, _)| *i == 0 || text.as_bytes()[i - 1] == b'\n')
        .map_or(text.len(), |(i, _)| i);
    text[..cut].trim_end()
}

/// What `nros explain NROS-NNNN` prints for an entry, live or retired.
#[must_use]
pub fn explain_text(e: &Entry) -> String {
    explain_text_in(e, ALL)
}

/// [`explain_text`] with a retired code's successor looked up in `table`.
#[must_use]
pub fn explain_text_in(e: &Entry, table: &[Entry]) -> String {
    let successor = e.retired.and_then(|n| table.iter().find(|s| s.number == n));
    match (e.retired, successor) {
        (Some(n), None) => format!(
            "{}: retired.\n\nThis code is no longer raised. Its successor, NROS-{n:04}, is \
             unknown to this binary.\n",
            e.code
        ),
        (_, Some(s)) => format!(
            "{}: retired.\n\nThis code is no longer raised. It was replaced by {}: {}\n\
             Run `nros explain {}` for its explanation.\n",
            e.code, s.code, s.title, s.code
        ),
        (None, None) => format!(
            "{}: {}\n\n{}\n\nThe refusal's help line: {}\n",
            e.code,
            e.title,
            user_explanation(e),
            e.remedy
        ),
    }
}

/// The book's reference page: an index of every code, then one section per
/// live code (its anchor is the code, `#NROS-0004`). The section is what
/// `nros explain` prints, without the design background, which is for
/// maintainers. One page, so the book's sidebar lists the page and not
/// every code.
#[must_use]
pub fn book_page() -> String {
    let mut out = String::from(
        "<!-- GENERATED by nros-diagnostics-gen. Do not edit by hand; edit the \
         crate packages/tooling/nros-diagnostic-codes. -->\n\n\
         # Diagnostic codes\n\n\
         <!-- type: reference · level: 1 -->\n\n\
         Every refusal nano-ros prints carries a code, `NROS-` and four digits:\n\n\
         ```text\n\
         error[NROS-0004]: src/demo_bringup/system.toml: names no board\n  \
         help: add `board = \"<board>\"` to the `[image.<id>]` table in system.toml\n  \
         explain: nros explain NROS-0004\n\
         ```\n\n\
         The `explain:` line is a command: `nros explain NROS-0004` prints the\n\
         code's section below without a network or a checkout. A code never\n\
         changes its meaning, and a retired code names the one that replaced it.\n\n\
         | Code | What went wrong |\n\
         | --- | --- |\n",
    );
    for e in ALL {
        match e.successor() {
            None => out.push_str(&format!("| [{c}](#{c}) | {} |\n", e.title, c = e.code)),
            Some(s) => out.push_str(&format!(
                "| {} | retired; replaced by [{c}](#{c}) |\n",
                e.code,
                c = s.code
            )),
        }
    }
    for e in ALL.iter().filter(|e| e.is_live()) {
        out.push_str(&book_section(e));
    }
    out
}

/// One live code's section of the book page. The explanation's own `##`
/// headings sit one level down, under the code's.
fn book_section(e: &Entry) -> String {
    let mut body = String::new();
    for (i, l) in user_explanation(e).lines().enumerate() {
        if i > 0 {
            body.push('\n');
        }
        if l.starts_with("## ") {
            body.push('#');
        }
        body.push_str(l);
    }
    format!(
        "\n<a id=\"{c}\"></a>\n\n\
         ## {c}: {}\n\n\
         {body}\n\n\
         The refusal's `help` line, unless the site gives a more specific one:\n\n\
         > {}\n\n\
         [Back to the list of codes](#diagnostic-codes)\n",
        e.title,
        e.remedy,
        c = e.code
    )
}

/// Every generated file, as (path relative to the repository root, content).
#[must_use]
pub fn all_files() -> Vec<(String, String)> {
    let files = std::vec![
        (
            "packages/tooling/nros-diagnostic-codes/codes.lock".into(),
            lock(),
        ),
        (BOOK_PAGE.into(), book_page()),
    ];
    files
}

/// The book's reference page, relative to the repository root.
pub const BOOK_PAGE: &str = "book/src/reference/diagnostic-codes.md";

/// Where the book had one page per code, before they were folded into
/// [`BOOK_PAGE`]. The generator treats any file left there as an orphan.
pub const BOOK_DIR: &str = "book/src/reference/diagnostics";

/// Where the explanations live, relative to the repository root.
pub const EXPLAIN_DIR: &str = "packages/tooling/nros-diagnostic-codes/explain";
