//! `nros-diagnostics-gen` — write (or, with `--check`, verify) every view of
//! the diagnostic list: `codes.lock` and the book reference pages.
//!
//!   cargo run -p nros-diagnostic-codes --features gen --bin nros-diagnostics-gen [-- --check]
//!
//! `--root <dir>` names the repository root; the default is the one this
//! crate sits in. With `--check`, nothing is written: a stale or missing view,
//! or a stray file in the book directory, is reported and the exit status is 1.

use std::{
    collections::BTreeSet,
    path::{Path, PathBuf},
    process::ExitCode,
};

use nros_diagnostic_codes::views;

fn main() -> ExitCode {
    let mut check = false;
    let mut root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..");
    let mut args = std::env::args().skip(1);
    while let Some(a) = args.next() {
        match a.as_str() {
            "--check" => check = true,
            "--root" => match args.next() {
                Some(r) => root = PathBuf::from(r),
                None => return usage(),
            },
            _ => return usage(),
        }
    }

    let files = views::all_files();
    let mut stale = Vec::new();
    for (rel, want) in &files {
        let path = root.join(rel);
        let have = std::fs::read_to_string(&path).ok();
        if have.as_deref() == Some(want.as_str()) {
            continue;
        }
        if check {
            stale.push(format!(
                "{rel}: {}",
                if have.is_none() { "missing" } else { "stale" }
            ));
        } else {
            if let Some(dir) = path.parent()
                && let Err(e) = std::fs::create_dir_all(dir)
            {
                eprintln!("nros-diagnostics-gen: create {}: {e}", dir.display());
                return ExitCode::FAILURE;
            }
            if let Err(e) = std::fs::write(&path, want) {
                eprintln!("nros-diagnostics-gen: write {}: {e}", path.display());
                return ExitCode::FAILURE;
            }
            println!("wrote {rel}");
        }
    }

    // A page in the book directory that no live code generates: an orphan
    // (a code was retired, or a page was hand-added). Removed on write,
    // reported on check.
    let wanted: BTreeSet<&str> = files.iter().map(|(r, _)| r.as_str()).collect();
    if let Ok(dir) = std::fs::read_dir(root.join(views::BOOK_DIR)) {
        for ent in dir.flatten() {
            let rel = format!("{}/{}", views::BOOK_DIR, ent.file_name().to_string_lossy());
            if wanted.contains(rel.as_str()) {
                continue;
            }
            if check {
                stale.push(format!("{rel}: generated by no code"));
            } else if let Err(e) = std::fs::remove_file(ent.path()) {
                eprintln!("nros-diagnostics-gen: remove {rel}: {e}");
                return ExitCode::FAILURE;
            } else {
                println!("removed {rel}");
            }
        }
    }

    if stale.is_empty() {
        return ExitCode::SUCCESS;
    }
    for s in &stale {
        eprintln!("nros-diagnostics-gen --check: {s}");
    }
    eprintln!(
        "nros-diagnostics-gen --check: regenerate with \
         `cargo run -p nros-diagnostic-codes --features gen --bin nros-diagnostics-gen`"
    );
    ExitCode::FAILURE
}

fn usage() -> ExitCode {
    eprintln!("usage: nros-diagnostics-gen [--check] [--root <repository root>]");
    ExitCode::from(2)
}
