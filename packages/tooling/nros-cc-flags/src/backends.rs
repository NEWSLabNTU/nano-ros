//! The backend-registration TU a CARGO-ROOTED C/C++ image links -- phase-499 W3.
//!
//! `rclc_support_init` (and the C++ init) call `nros_app_register_backends()`
//! unconditionally, and since phase-249 P4a there is no weak no-op, so every
//! image supplies a strong definition. On the cmake road `nano_ros_link_rmw()`
//! GENERATES it from the image's RMW (`cmake/NanoRosLink.cmake`). A
//! cargo-rooted image -- a bare-metal C or C++ leaf whose link root is Rust and
//! whose C is compiled by `cc` in `build.rs` -- had no generator, so each
//! application wrote the function by hand. RFC-0089 (2026-10-13) keeps that
//! configuration out of user code: this writes the same TU from the backends
//! `nros-c` publishes over its `links = "nros_c"` key (`cargo:rmw_backends`).

use std::path::PathBuf;

/// The `links` metadata `nros-c`'s build script publishes.
pub const BACKENDS_ENV: &str = "DEP_NROS_C_RMW_BACKENDS";

/// The TU's text for `backends` (each `nros_rmw_<name>_register`), byte for
/// byte the shape `nano_ros_link_rmw()` writes.
pub fn source(backends: &[&str]) -> String {
    let mut s = String::from(
        "/* Auto-generated by nros_cc_flags::backends (phase-499 W3), the cargo\n \
         * road's twin of nano_ros_link_rmw().\n",
    );
    s.push_str(&format!(
        " * Backends registered: {}\n */\n",
        backends.join(", ")
    ));
    // A C++ leaf compiles this through its C++ `cc::Build`; C linkage keeps
    // the symbols the runtime looks for.
    s.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n");
    for b in backends {
        s.push_str(&format!("extern int nros_rmw_{b}_register(void);\n"));
    }
    s.push_str("void nros_app_register_backends(void) {\n");
    for b in backends {
        s.push_str(&format!("    (void)nros_rmw_{b}_register();\n"));
    }
    s.push_str("}\n#ifdef __cplusplus\n}\n#endif\n");
    s
}

/// Write the TU into `OUT_DIR` and add it to `build`.
///
/// # Panics
///
/// When `nros-c` published no backend: an image with no RMW cannot open a
/// session, and saying so here beats an empty registration that fails at
/// `rclc_support_init` on the target.
/// The backends this crate's DIRECT dependencies announce.
///
/// RFC-0071 D9 (phase-506 W4c) — each backend crate declares `links =
/// "nros_rmw_<name>"` and prints `cargo:nros_rmw_backend=<name>`, which cargo
/// hands a direct dependent as `DEP_NROS_RMW_<NAME>_NROS_RMW_BACKEND`. The image
/// chooses its backend by depending on it, and this reads that choice; the
/// `nros-c` feature list ([`BACKENDS_ENV`]) is still honoured until the API
/// crates drop their backend features. Sorted and de-duplicated.
pub fn collect(vars: impl Iterator<Item = (String, String)>) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for (k, v) in vars {
        if k == BACKENDS_ENV {
            out.extend(v.split(',').filter(|b| !b.is_empty()).map(str::to_string));
        } else if k.starts_with("DEP_") && k.ends_with("_NROS_RMW_BACKEND") && !v.is_empty() {
            out.push(v);
        }
    }
    out.sort();
    out.dedup();
    out
}

pub fn generate(build: &mut cc::Build) {
    let backends = collect(std::env::vars());
    let backends: Vec<&str> = backends.iter().map(String::as_str).collect();
    assert!(
        !backends.is_empty(),
        "this image depends on no RMW backend, so it has none to register: add the \
         backend crate (e.g. `nros-rmw-zenoh`) as a dependency (RFC-0071 D9)"
    );
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let path = out.join("nros_app_register_backends.c");
    let text = source(&backends);
    // Write-if-changed, as the cmake twin does (issue 1419): a fresh mtime on
    // every build would recompile and relink an unchanged image.
    if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(&path, &text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    }
    build.file(path);
}

#[cfg(test)]
mod tests {
    use super::source;

    #[test]
    fn collects_announced_and_legacy_backends() {
        let vars = [
            ("DEP_NROS_RMW_ZENOH_NROS_RMW_BACKEND", "zenoh"),
            ("DEP_NROS_C_RMW_BACKENDS", "zenoh"),
            ("DEP_NROS_RMW_XRCE_NROS_RMW_BACKEND", "xrce"),
            ("UNRELATED", "x"),
        ]
        .into_iter()
        .map(|(k, v)| (k.to_string(), v.to_string()));
        assert_eq!(super::collect(vars), vec!["xrce", "zenoh"]);
    }

    #[test]
    fn registers_each_backend_in_order() {
        let s = source(&["zenoh", "xrce"]);
        assert!(s.contains("extern int nros_rmw_zenoh_register(void);"));
        assert!(s.contains("extern int nros_rmw_xrce_register(void);"));
        let body = &s[s.find("void nros_app_register_backends").unwrap()..];
        assert!(body.find("zenoh").unwrap() < body.find("xrce").unwrap());
    }
}
