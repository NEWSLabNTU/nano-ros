//! The program writes `main` on a CARGO-ROOTED C/C++ image too -- phase-499 W5.
//!
//! RFC-0089 (amendment 2026-10-13): an application writes `main`, as an rclc or
//! rclcpp program does. The cmake road compiles the program's sources with
//! `main` renamed to `nros_ported_main` and generates the `nros_app_main`
//! forwarder (`_nros_apply_app_main`, `cmake/NanoRosVerbs.cmake`). A
//! cargo-rooted image (a bare-metal leaf whose link root is Rust) does the same
//! here; its `main.rs` calls `nros_app_main` once the board is up, so no
//! platform shim is needed.
//!
//! Why a private name and not `main=nros_app_main`: a platform header may
//! declare `extern int main(void)` (Zephyr's does), which that rename would
//! turn into a second, conflicting `nros_app_main`.

use std::path::PathBuf;

/// The name the program's `main` is compiled as.
pub const PORTED_MAIN: &str = "nros_ported_main";

/// The forwarder's text. `cxx` gives `nros_ported_main` C++ linkage, matching
/// a C++ `int main(int argc, char** argv)` compiled under the rename.
pub fn source(cxx: bool) -> String {
    let linkage = if cxx { "extern \"C\" " } else { "" };
    format!(
        "/* Generated by nros_cc_flags::app_main (phase-499 W5): the program's\n \
         * `main`, renamed by the build, reached as nros_app_main. */\n\
         int {PORTED_MAIN}(int argc, char** argv);\n\
         {linkage}int nros_app_main(int argc, char** argv) {{\n    \
         return {PORTED_MAIN}(argc, argv);\n}}\n"
    )
}

/// Rename `main` on `build`'s sources and add the forwarder TU. Call it on the
/// `cc::Build` that compiles the program; `cxx` says whether that build is C++.
pub fn generate(build: &mut cc::Build, cxx: bool) {
    build.define("main", Some(PORTED_MAIN));
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let path = out.join(if cxx {
        "nros_app_main.cpp"
    } else {
        "nros_app_main.c"
    });
    let text = source(cxx);
    // Write-if-changed (issue 1419).
    if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(&path, &text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    }
    build.file(path);
}

#[cfg(test)]
mod tests {
    use super::source;

    #[test]
    fn forwards_to_the_renamed_main_with_the_right_linkage() {
        let c = source(false);
        assert!(c.contains("int nros_ported_main(int argc, char** argv);"));
        assert!(c.contains("\nint nros_app_main(int argc, char** argv) {"));
        let cxx = source(true);
        assert!(cxx.contains("extern \"C\" int nros_app_main(int argc, char** argv) {"));
    }
}
