    /// The component is built by its OWN CMakeLists, not a reimplementation of
    /// it — that is what makes "it compiled here" mean "it compiles in an
    /// entry".
    #[test]
    fn cmakelists_adds_the_component_package_and_enables_metadata_mode() {
        let txt = render_probe_cmakelists(std::slice::from_ref(&opts()));
        assert!(
            txt.contains("add_subdirectory(/ws/src/talker_pkg talker_pkg)"),
            "{txt}"
        );
        assert!(txt.contains("find_package(nano_ros REQUIRED)"), "{txt}");
        assert!(
            txt.contains("set(NROS_EXTRA_CPP_FEATURES \"metadata-mode\")"),
            "the recording backend rides in on this feature:\n{txt}"
        );
        assert!(
            txt.contains("nano_ros_link_rmw(probe_talker_pkg__talker)"),
            "{txt}"
        );
        // NanoRosCpp, not NanoRos: only the Cpp target carries the `nros/*.hpp`
        // include dirs, and the probe TU is C++ even for a C component.
        assert!(
            txt.contains("NanoRos::NanoRosCpp"),
            "probe needs the C++ include dirs:\n{txt}"
        );
        // Linking the component lib is what brings its own header's include dir.
        assert!(txt.contains("PRIVATE talker_lib"), "{txt}");
    }

    /// The probe TU comes from the entry emitter, so the construction and
    /// `configure` call are the ones a real entry would make.
    #[test]
    fn probe_main_is_the_entry_setup_body_with_a_dump_tail() {
        let src = render_probe_main(&opts()).expect("emit");
        assert!(src.contains("#include \"talker_pkg/Talker.hpp\""), "{src}");
        assert!(src.contains(".configure("), "{src}");
        assert!(
            src.contains("nros_cpp_metadata_dump(\"talker_pkg\", \"talker\", \"talker\", \"cpp\""),
            "{src}"
        );
        assert!(
            src.contains("/ws/src/talker_pkg/metadata/talker.json"),
            "{src}"
        );
        assert!(
            !src.contains("::run_components("),
            "a probe never spins:\n{src}"
        );
    }

    /// A C component takes the C-ABI factory seam, not a C++ class construct —
    /// routed by `lang`, by the same emitter branch a real entry uses.
    #[test]
    fn c_components_route_through_the_c_abi_seam() {
        let mut o = opts();
        o.language = "c".into();
        o.package = "c_talker_pkg".into();
        o.class = "c_talker_pkg::Talker".into();
        let src = render_probe_main(&o).expect("emit");
        assert!(
            src.contains("__nros_c_component_c_talker_pkg_configure"),
            "{src}"
        );
    }

    /// phase-313 — ONE project for the workspace. Per-component dirs are what
    /// made every probe rebuild the runtime and the nested sizes probes.
    #[test]
    fn the_probe_project_is_per_workspace() {
        assert_eq!(
            probe_dir_for_workspace(Path::new("/b")),
            Path::new("/b/metadata-probe-cmake")
        );
    }

    /// Several components share one project: one `add_subdirectory` per
    /// PACKAGE (deduped), one executable per COMPONENT.
    #[test]
    fn a_batch_adds_each_package_once_and_one_target_per_component() {
        let mut a = opts();
        let mut b = opts();
        b.component = "second".into();
        b.class = "talker_pkg::Second".into();
        b.header = "talker_pkg/Second.hpp".into();
        let mut c = opts();
        c.package = "listener_pkg".into();
        c.component = "listener".into();
        c.package_dir = PathBuf::from("/ws/src/listener_pkg");
        c.library_target = "listener_lib".into();
        a.component = "talker".into();

        let txt = render_probe_cmakelists(&[a, b, c]);
        assert_eq!(
            txt.matches("add_subdirectory(/ws/src/talker_pkg").count(),
            1,
            "one package, added once even with two components:\n{txt}"
        );
        assert!(
            txt.contains("add_subdirectory(/ws/src/listener_pkg"),
            "{txt}"
        );
        for t in [
            "probe_talker_pkg__talker",
            "probe_talker_pkg__second",
            "probe_listener_pkg__listener",
        ] {
            assert!(
                txt.contains(&format!("add_executable({t} {t}.cpp)")),
                "{t}\n{txt}"
            );
        }
    }
