//! phase-527 W1 / RFC-0119 D7 — the verbs a `command` package may not take.
//!
//! A command package adds `nros <verb>`; a built-in or reserved verb cannot be
//! provided, and announcing one is a refusal at discovery, not a shadow.
//! `check-provider-announcements` enforces that, and it is buildless Python,
//! so it cannot ask clap. It reads `packages/cli/nros-cli-core/builtin-verbs.txt`
//! instead, and the test below holds that file equal to the clap tree, both
//! directions. Regenerate after adding, renaming or hiding a verb:
//!
//! ```text
//! NROS_BLESS_BUILTIN_VERBS=1 cargo test --manifest-path packages/cli/Cargo.toml \
//!     -p nros-cli-core builtin_verbs
//! ```
//!
//! The file lists three tiers:
//!
//! - `user <verb>` — every top-level subcommand and alias, hidden ones included;
//! - `dev <verb>` — every subcommand of `nros dev` (phase-526 W1); a
//!   `tier = "dev"` command may not take one of these;
//! - `reserved <verb>` — [`RESERVED_VERBS`], named by RFC-0117/RFC-0118 and
//!   not necessarily in the tree yet.

/// Verbs RFC-0117/RFC-0118 reserve. phase-526 W2 placed the target-execution
/// verbs in the clap tree, so they also appear as `user` rows; listing them
/// here keeps them refused even while a verb is only a reserved stub.
pub const RESERVED_VERBS: &[&str] = &["run", "flash", "monitor", "bench", "debug", "help", "dev"];

/// The path of the generated list, relative to the nros-cli-core crate.
pub const BUILTIN_VERBS_FILE: &str = "builtin-verbs.txt";

/// The verb names of one clap command: each subcommand's name and every alias.
fn verb_names(cmd: &clap::Command) -> Vec<String> {
    let mut out: Vec<String> = cmd
        .get_subcommands()
        .flat_map(|s| {
            std::iter::once(s.get_name().to_string()).chain(s.get_all_aliases().map(str::to_string))
        })
        .collect();
    out.sort();
    out.dedup();
    out
}

/// The file's content, rendered from the clap tree.
#[must_use]
pub fn render(root: &clap::Command) -> String {
    let mut s = String::from(
        "# GENERATED by nros-cli-core's `builtin_verbs` test (phase-527 W1, RFC-0119 D7).\n\
         # The verbs a `command` package may not provide; read by\n\
         # scripts/check-provider-announcements.py. Regenerate with:\n\
         #   NROS_BLESS_BUILTIN_VERBS=1 cargo test --manifest-path packages/cli/Cargo.toml \\\n\
         #       -p nros-cli-core builtin_verbs\n",
    );
    for v in verb_names(root) {
        s.push_str(&format!("user {v}\n"));
    }
    if let Some(dev) = root.find_subcommand("dev") {
        for v in verb_names(dev) {
            s.push_str(&format!("dev {v}\n"));
        }
    }
    let mut reserved: Vec<&str> = RESERVED_VERBS.to_vec();
    reserved.sort_unstable();
    for v in reserved {
        s.push_str(&format!("reserved {v}\n"));
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use clap::Subcommand;

    fn tree() -> clap::Command {
        crate::cmd::Cmd::augment_subcommands(clap::Command::new("nros"))
    }

    /// The tracked list equals the clap tree. Set `NROS_BLESS_BUILTIN_VERBS=1`
    /// to rewrite it after adding, renaming or hiding a verb.
    #[test]
    fn builtin_verbs_file_matches_the_clap_tree() {
        // `release` exists only with the maintainer feature; the tracked file
        // describes the default build.
        if cfg!(feature = "release") {
            return;
        }
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(BUILTIN_VERBS_FILE);
        let want = render(&tree());
        if std::env::var_os("NROS_BLESS_BUILTIN_VERBS").is_some() {
            std::fs::write(&path, &want).unwrap();
            return;
        }
        let have = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            have == want,
            "{} is stale: the `nros` verb tree changed. Regenerate it with\n  \
             NROS_BLESS_BUILTIN_VERBS=1 cargo test --manifest-path packages/cli/Cargo.toml \
             -p nros-cli-core builtin_verbs\nand commit it. check-provider-announcements reads \
             it to refuse a command package named like a built-in verb (RFC-0119 D7).",
            path.display()
        );
    }

    #[test]
    fn the_list_names_known_verbs_hidden_ones_included() {
        let text = render(&tree());
        for line in [
            "user build",
            "user ws",
            "user codegen-fingerprint",
            "reserved run",
        ] {
            assert!(text.lines().any(|l| l == line), "missing {line:?}:\n{text}");
        }
    }
}
