//! phase-446 W6 -- the C++ table of the parameters each node's contract
//! DECLARES, `<nros/nros_declared_params_generated.h>`.
//!
//! `nros/declared_params.hpp` expands it and `Node::declare_parameter`
//! refuses a name the node's contract does not declare, or a type that differs.
//! The rows come from `nros_orchestration_ir::declared_params`, the same
//! function the `nros::main!` expansion reads for a Rust image, so the two
//! languages check against one answer.
//!
//! Rendered beside the declared-QoS header by the same `nros ws
//! entity-inventory` call (`--output-params-header`), from the model the entry
//! resolved. The table is image-wide and keyed on node FQN: the header is
//! per-component, but one component class may run as several nodes, and each
//! node's contract entry is its own.

use ros_launch_manifest_model::SystemModel;

/// The generated header. `model` is `None` when no SystemModel reached this
/// render: the header then says so and defines no table, and every lookup in
/// `declared_params.hpp` answers "not checked".
pub fn render(model: Option<&SystemModel>, source: &str) -> String {
    let mut s = String::new();
    for line in [
        "/* GENERATED by `nros ws entity-inventory --output-params-header` (phase-446 W6).",
        " * Do not edit.",
        " *",
        " * The parameters each node's launch contract DECLARES (`nodes.<n>.params`),",
        " * keyed by node FQN. `nros/declared_params.hpp` expands this and",
        " * `Node::declare_parameter` refuses a name the contract does not",
        " * declare, or a type that differs, naming the node, the parameter and the",
        " * contract.",
        " *",
        " * A node with no row has no `params:` in its contract and is NOT checked:",
        " * absence is not a declaration of nothing.",
        " *",
    ] {
        s.push_str(line);
        s.push('\n');
    }
    s.push_str(&format!(
        " * Source: {}\n */\n",
        source.replace("*/", "*_/")
    ));
    s.push_str("#ifndef NROS_DECLARED_PARAMS_GENERATED_H\n");
    s.push_str("#define NROS_DECLARED_PARAMS_GENERATED_H\n\n");

    let nodes = model
        .map(|m| nros_orchestration_ir::declared_params::declared_params(m, |_| true))
        .unwrap_or_default();
    if nodes.is_empty() {
        s.push_str("#define NROS_DECLARED_PARAMS_STATUS \"absent\"\n");
        s.push_str(
            "/* No node's contract declares `params:`, so there is no table and nothing\n \
             * is checked. NROS_DECLARED_PARAM_NODES stays undefined -- an empty table\n \
             * and \"nobody declared\" must not look alike. */\n",
        );
    } else {
        s.push_str("#define NROS_DECLARED_PARAMS_STATUS \"declared\"\n\n");
        s.push_str(
            "/* X-macros. `nros/declared_params.hpp` defines NROS_DECLARED_PARAM_NODE and\n \
             * NROS_DECLARED_PARAM_ROW and expands these; nothing else may. A ROW's type\n \
             * is the rcl_interfaces/msg/ParameterType code. */\n",
        );
        s.push_str("#define NROS_DECLARED_PARAM_NODES \\\n");
        for n in &nodes {
            s.push_str(&format!(
                "    NROS_DECLARED_PARAM_NODE(\"{}\", \"{}\") \\\n",
                c_escape(&n.fqn),
                c_escape(&n.contract)
            ));
        }
        s.push_str("    /* end */\n");
        s.push_str(&format!(
            "#define NROS_DECLARED_PARAM_NODE_COUNT {}\n\n",
            nodes.len()
        ));
        s.push_str("#define NROS_DECLARED_PARAM_ROWS \\\n");
        let mut rows = 0usize;
        for n in &nodes {
            for (name, ty) in &n.params {
                s.push_str(&format!(
                    "    NROS_DECLARED_PARAM_ROW(\"{}\", \"{}\", {}) /* {} */ \\\n",
                    c_escape(&n.fqn),
                    c_escape(name),
                    nros_orchestration_ir::declared_params::ros_type_code(*ty),
                    ty.as_str()
                ));
                rows += 1;
            }
        }
        s.push_str("    /* end */\n");
        s.push_str(&format!("#define NROS_DECLARED_PARAM_ROW_COUNT {rows}\n"));
    }
    s.push_str("\n#endif /* NROS_DECLARED_PARAMS_GENERATED_H */\n");
    s
}

fn c_escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn model(y: &str) -> SystemModel {
        SystemModel::from_yaml_str(y).expect("fixture parses")
    }

    #[test]
    fn a_declaring_node_renders_its_rows_and_its_contract() {
        let m = model(
            r#"
meta: { version: 1 }
structure:
  scopes:
    s.launch.xml: { file: s.launch.xml }
  nodes:
    /system/mrm_handler:
      { scope: s.launch.xml, pkg: p, exec: mrm_handler, node_name: mrm_handler }
    /talker: { scope: s.launch.xml, pkg: p, exec: talker, node_name: talker }
contracts:
  node_params:
    /system/mrm_handler:
      update_rate: { type: integer }
"#,
        );
        let h = render(Some(&m), "m.yaml");
        assert!(
            h.contains("#define NROS_DECLARED_PARAMS_STATUS \"declared\"\n"),
            "{h}"
        );
        assert!(
            h.contains("NROS_DECLARED_PARAM_NODE(\"/system/mrm_handler\", \"s.contract.yaml\")"),
            "{h}"
        );
        assert!(
            h.contains("NROS_DECLARED_PARAM_ROW(\"/system/mrm_handler\", \"update_rate\", 2)"),
            "{h}"
        );
        assert!(
            h.contains("#define NROS_DECLARED_PARAM_ROW_COUNT 1\n"),
            "{h}"
        );
        // `/talker` declares nothing, so it is not in the table at all.
        assert!(!h.contains("\"/talker\""), "{h}");
    }

    /// The header `just check cpp` compiles `declared_params.cpp` against is
    /// what this renderer produces from the fixture model beside it. A stale
    /// fixture would leave that TU's assertions green against a table no build
    /// renders any more. Regenerate with the command in the fixture model's
    /// header comment; never hand-edit.
    #[test]
    fn the_committed_compile_fixture_is_what_this_emitter_renders() {
        const REL: &str = "packages/api/nros-cpp/tests/compile/declared-params-fixture";
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../..")
            .canonicalize()
            .expect("repo root");
        let dir = root.join(REL);
        let yaml = std::fs::read_to_string(dir.join("declared_params.yaml"))
            .unwrap_or_else(|e| panic!("read {}/declared_params.yaml: {e}", dir.display()));
        let want = std::fs::read_to_string(dir.join("nros/nros_declared_params_generated.h"))
            .expect("the committed fixture header exists");
        assert_eq!(
            render(Some(&model(&yaml)), &format!("{REL}/declared_params.yaml")),
            want,
            "the committed declared-params fixture header is not what this emitter renders"
        );
    }

    /// No model, or a model whose contract declares no parameters: no table.
    #[test]
    fn no_declaration_renders_no_table() {
        for h in [
            render(None, "none"),
            render(
                Some(&model(
                    "meta: { version: 1 }\nstructure:\n  nodes:\n    /talker: \
                     { scope: s.launch.xml, pkg: p, exec: talker, node_name: talker }\n",
                )),
                "m.yaml",
            ),
        ] {
            assert!(
                h.contains("#define NROS_DECLARED_PARAMS_STATUS \"absent\"\n"),
                "{h}"
            );
            assert!(!h.contains("#define NROS_DECLARED_PARAM_NODES"), "{h}");
        }
    }
}
