//! One derivation of "what is this generated artifact called?".
//!
//! Every message-like artifact's name is built from the same stem —
//! `<c_package>_<kind>_<type_snake>` — carrying a suffix chosen by the language
//! surface. That rule used to be AUTHORED six times (`msg.rs`, `srv.rs`,
//! `action.rs` and three arms of `cpp.rs`), each copy differing only in a kind
//! word and an extension, with the `constant_prefix` half written three more
//! times and the intra-package include path twice inside one function. No gate
//! covered the class, so a fourth language surface would have added three more
//! copies. The kind word and the suffixes are PARAMETERS here instead.
//!
//! ## Where the parameters live (phase-469 W1)
//!
//! The suffixes are PACK DATA, not Rust rows. Each `packs/<dir>/pack.toml`
//! declares `header_extension`, `guard_suffix` and — for a surface that compiles
//! one — `source_extension`; `build.rs` reads every manifest and GENERATES
//! [`Surface`] plus its three lookups from the packs that declare them. So a
//! surface declares its own suffixes, and adding one is adding a pack directory
//! rather than editing an enum and three `match`es in this file.
//!
//! What deliberately did NOT move: [`Kind`]. The kind word (`msg` / `srv` /
//! `action`) is a property of the ROS INTERFACE and is identical on every
//! surface, so putting it in a pack would give each pack its own copy of one
//! fact — the very defect this module removed one level down. It also is not a
//! thing a pack author may choose: `msg` is what ROS calls a `.msg`.
//!
//! The formats are unchanged, deliberately: this module is a refactor, so every
//! golden stays byte-identical. See [`Surface`] for what a new surface has to
//! declare.

use crate::{
    types::to_c_package_name,
    utils::{to_rosidl_snake_case, to_snake_case},
};

// `Surface` and its `pack` / `header_ext` / `guard_suffix` / `source_ext`
// lookups — GENERATED by `build.rs` from the packs that declare
// `header_extension`. Read the expansion at
// `packages/cli/target/**/build/rosidl-codegen-*/out/naming_surfaces.rs`.
include!(concat!(env!("OUT_DIR"), "/naming_surfaces.rs"));

/// The ROS interface kind an artifact describes — the word that sits between
/// the package and the type in every generated name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    /// A `.msg` type.
    Msg,
    /// A `.srv` type.
    Srv,
    /// An `.action` type.
    Action,
}

impl Kind {
    /// The kind word: `msg`, `srv` or `action`.
    pub const fn word(self) -> &'static str {
        match self {
            Kind::Msg => "msg",
            Kind::Srv => "srv",
            Kind::Action => "action",
        }
    }
}

/// Every name one generated artifact needs, all derived from [`Self::stem`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ArtifactNames {
    /// The stem every other name here is built from and the generated struct
    /// name: `std_msgs__msg__Int32` on the C surface (rosidl's, phase-492 W7);
    /// `std_msgs_msg_int32` on the C++ surface, which appends `_t` and splits
    /// the FFI into `<stem>_types.rs` / `<stem>_exports.rs`.
    pub stem: String,
    /// `STD_MSGS__MSG__INT32_H_` (C) / `STD_MSGS_MSG_INT32_HPP` (C++).
    pub include_guard: String,
    /// The prefix every generated constant macro for this type carries:
    /// `std_msgs__msg__Int32` (C, then `__<CONST>`) / `STD_MSGS_MSG_INT32`.
    pub constant_prefix: String,
    /// `int32.h` (C, under `<pkg>/msg/`) / `std_msgs_msg_int32.hpp`.
    pub header: String,
    /// `int32.c` — the translation unit, for a surface that compiles one.
    /// `None` on the header-only C++ surface.
    pub source: Option<String>,
}

/// Derive every name for one `<package>/<kind>/<type>` artifact on `surface`.
///
/// The C surface takes rosidl_generator_c's names (RFC-0089 "Messages take
/// rosidl's C names AND its member shape", phase-492 W7): the struct is
/// `<pkg>__<kind>__<Type>`, the header `<pkg>/<kind>/<rosidl_snake>.h`, the
/// guard `<PKG>__<KIND>__<SNAKE>_H_`. A ported file names the same identifiers
/// and includes the same paths. The C++ surface keeps its own stem; its
/// spelling is `rclcpp`'s business, not rosidl C's.
pub fn artifact_names(
    surface: Surface,
    kind: Kind,
    package_name: &str,
    type_name: &str,
) -> ArtifactNames {
    let c_pkg = to_c_package_name(package_name);
    if surface == Surface::C {
        let snake = to_rosidl_snake_case(type_name);
        let stem = c_struct_name(package_name, kind, type_name);
        return ArtifactNames {
            include_guard: format!(
                "{}__{}__{}{}_",
                c_pkg.to_uppercase(),
                kind.word().to_uppercase(),
                snake.to_uppercase(),
                surface.guard_suffix()
            ),
            constant_prefix: stem.clone(),
            header: format!("{}.{}", snake, surface.header_ext()),
            source: surface.source_ext().map(|ext| format!("{}.{}", snake, ext)),
            stem,
        };
    }
    let stem = format!("{}_{}_{}", c_pkg, kind.word(), to_snake_case(type_name));
    let upper = stem.to_uppercase();
    ArtifactNames {
        include_guard: format!("{}{}", upper, surface.guard_suffix()),
        constant_prefix: upper,
        header: format!("{}.{}", stem, surface.header_ext()),
        source: surface.source_ext().map(|ext| format!("{}.{}", stem, ext)),
        stem,
    }
}

/// rosidl's C struct name for `<package>/<kind>/<type>`: `std_msgs__msg__String`.
///
/// The one producer of the spelling, used for a type's own struct and for every
/// reference to it (a nested field, a sequence element, an include).
pub fn c_struct_name(package_name: &str, kind: Kind, type_name: &str) -> String {
    format!(
        "{}__{}__{}",
        to_c_package_name(package_name),
        kind.word(),
        type_name
    )
}

/// rosidl's include path for a message header: `std_msgs/msg/string.h`.
pub fn c_msg_header_path(package_name: &str, type_name: &str) -> String {
    format!(
        "{}/msg/{}.h",
        to_c_package_name(package_name),
        to_rosidl_snake_case(type_name)
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_c_surface_names_a_message_as_rosidl_does() {
        let n = artifact_names(Surface::C, Kind::Msg, "std_msgs", "Int32");
        assert_eq!(n.stem, "std_msgs__msg__Int32");
        assert_eq!(n.include_guard, "STD_MSGS__MSG__INT32_H_");
        assert_eq!(n.constant_prefix, "std_msgs__msg__Int32");
        assert_eq!(n.header, "int32.h");
        assert_eq!(n.source.as_deref(), Some("int32.c"));
    }

    /// rosidl's file names, including the two shapes a plain CamelCase split
    /// gets wrong: a digit before a capital and a leading acronym.
    #[test]
    fn the_c_header_takes_rosidl_snake_case() {
        for (ty, file) in [
            ("LaserScan", "laser_scan.h"),
            ("Float32MultiArray", "float32_multi_array.h"),
            ("UInt8", "u_int8.h"),
            ("TFMessage", "tf_message.h"),
            ("String", "string.h"),
        ] {
            assert_eq!(artifact_names(Surface::C, Kind::Msg, "p", ty).header, file);
        }
        assert_eq!(
            c_msg_header_path("std_msgs", "Header"),
            "std_msgs/msg/header.h"
        );
    }

    #[test]
    fn the_cpp_surface_keeps_its_own_stem() {
        let cpp = artifact_names(Surface::Cpp, Kind::Srv, "example_interfaces", "AddTwoInts");
        assert_eq!(cpp.stem, "example_interfaces_srv_add_two_ints");
        assert_eq!(cpp.include_guard, "EXAMPLE_INTERFACES_SRV_ADD_TWO_INTS_HPP");
        assert_eq!(cpp.header, "example_interfaces_srv_add_two_ints.hpp");
        // Header-only: no translation unit to name.
        assert_eq!(cpp.source, None);
    }

    #[test]
    fn the_kind_word_is_the_only_difference_between_kinds() {
        for (kind, word) in [
            (Kind::Msg, "msg"),
            (Kind::Srv, "srv"),
            (Kind::Action, "action"),
        ] {
            let n = artifact_names(Surface::C, kind, "test_msgs", "Fibonacci");
            assert_eq!(n.stem, format!("test_msgs__{word}__Fibonacci"));
            assert_eq!(
                n.include_guard,
                format!("TEST_MSGS__{}__FIBONACCI_H_", word.to_uppercase())
            );
        }
    }

    /// phase-469 W1 — the generated surfaces and the discovered packs are the
    /// same set.
    ///
    /// `Surface` comes from the packs that declare `header_extension`, so a pack
    /// directory rename would silently DROP a surface: every remaining caller
    /// still compiles (they name `Surface::C` / `Surface::Cpp`, which is what
    /// would go), so nothing would fail until a build asked for the missing
    /// variant. This ties each variant back to a manifest that exists.
    #[test]
    fn every_naming_surface_is_a_discovered_pack() {
        assert_eq!(
            Surface::ALL,
            [Surface::C, Surface::Cpp],
            "the naming surfaces changed — a pack gained or lost its \
             `header_extension`, which moves what every artifact is CALLED"
        );
        for surface in Surface::ALL {
            let pack = surface.pack();
            let info = crate::render::PACK_INFO
                .iter()
                .find(|p| p.dir == pack)
                .unwrap_or_else(|| {
                    panic!("surface {surface:?} names pack `{pack}`, which no manifest declares")
                });
            assert!(
                !info.shared,
                "pack `{pack}` is a shared partial pack and cannot be a naming surface"
            );
            assert!(
                info.language.is_some(),
                "pack `{pack}` names artifacts but declares no language"
            );
        }
    }
}
