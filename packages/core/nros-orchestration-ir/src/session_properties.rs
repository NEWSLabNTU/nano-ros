//! RFC-0109 D8 (phase-514 W3) — the session properties an image bakes, as
//! the one text the CLI hands its build.
//!
//! A backend whose configuration file the target cannot parse has it lowered
//! on the host (`[rmw.config] format = "session-json5"`), to an ordered list
//! of `(key, value)` session properties. Which file, which keys and which
//! backend are the CLI's business (`nros_cli_core::orchestration::rmw_config`,
//! keyed by the backend's descriptor); a core consumer such as `nros::main!`
//! only receives the list, so it names no backend (RFC-0071).
//!
//! The text is the JSON array `[["key", "value"], …]`, carried in
//! [`ENV`] the way `NROS_IMAGE_NET` carries the image's network: written into
//! the build's settings by `nros sync` / `nros build`, read at expansion time.
//! Absent or empty means the image bakes none.

/// The variable that carries an image's session properties to its build.
pub const ENV: &str = "NROS_SESSION_PROPERTIES";

/// Issue 2051 — the file, in `nros build`'s resolve directory
/// (`NROS_RESOLVED_DIR`), that carries a Zephyr RUST west application's session
/// properties: the table [`rust_table`] renders, which the `nros` crate's build
/// copies in for `zephyr_component_main!` to install. The west lane has no
/// `--config` seam (issue 1288), and its cargo command is an unquoted shell
/// line inside a CMake list, which would take [`ENV`]'s JSON apart (the shell
/// strips its `"`, the list splits an ISO-TP endpoint's `;`) — so the module
/// hands cargo this file's PATH as [`WEST_FILE_ENV`], never the text.
pub const WEST_FILE: &str = "session-properties.rs";

/// Issue 2051 — the variable that names [`WEST_FILE`] to the `nros` crate's
/// build. A path, so the build watches the file's content, not the spelling.
pub const WEST_FILE_ENV: &str = "NROS_SESSION_PROPERTIES_RS";

/// The property that carries a configuration file a backend parses itself
/// (`[rmw.config] format = "verbatim-xml"`, Cyclone's XML) to a session that
/// is not the image's default one — a `[[domain]]` a bridge opens (phase-514
/// W3b). Its value is the file's whole text; a backend that reads such a file
/// takes it in place of the document its road bakes for the default session.
pub const DOCUMENT: &str = "config";

/// The text for `props`.
#[must_use]
pub fn encode(props: &[(String, String)]) -> String {
    let rows: Vec<[&str; 2]> = props
        .iter()
        .map(|(k, v)| [k.as_str(), v.as_str()])
        .collect();
    serde_json::to_string(&rows).unwrap_or_default()
}

/// Issue 2051 — `props` as the Rust source of [`WEST_FILE`]: one
/// `SESSION_PROPERTIES` static of `nros`'s `SessionProperty` rows, in the
/// `nros` crate's own scope (it is `include!`d there). Empty `props` is an
/// empty table, which installs nothing.
///
/// # Errors
///
/// A key or value holds a NUL byte, which no C string can carry.
pub fn rust_table(props: &[(String, String)]) -> Result<String, String> {
    let mut rows = String::new();
    for (k, v) in props {
        if k.contains('\0') || v.contains('\0') {
            return Err(format!(
                "session property `{k}` (from the bringup's RMW file) holds a NUL byte"
            ));
        }
        // `{:?}` writes a Rust string literal; a `c` before it is the C-string
        // literal of the same text.
        rows.push_str(&format!(
            "    crate::__macro_support::SessionProperty::new(c{k:?}, c{v:?}),\n"
        ));
    }
    Ok(format!(
        "// Generated by `nros build` (issue 2051): the bringup's lowered RMW file.\n\
         pub static SESSION_PROPERTIES: [crate::__macro_support::SessionProperty; {}] = [\n{rows}];\n",
        props.len()
    ))
}

/// The properties `text` carries; empty text carries none.
///
/// # Errors
///
/// The text is not the array [`encode`] writes.
pub fn decode(text: &str) -> Result<Vec<(String, String)>, String> {
    if text.trim().is_empty() {
        return Ok(Vec::new());
    }
    let rows: Vec<[String; 2]> = serde_json::from_str(text)
        .map_err(|e| format!("{ENV}: not a `[[\"key\", \"value\"], …]` list ({e})"))?;
    Ok(rows.into_iter().map(|[k, v]| (k, v)).collect())
}

/// The first endpoint the session dials or listens on, whose scheme is the
/// image's link (RFC-0109 D6) — the role a locator plays without a file.
#[must_use]
pub fn endpoint(props: &[(String, String)]) -> Option<&str> {
    props
        .iter()
        .find(|(k, _)| k == "connect" || k == "listen")
        .map(|(_, v)| v.as_str())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_text_round_trips_in_order_and_names_its_endpoint() {
        let props = vec![
            ("mode".to_string(), "client".to_string()),
            ("connect".to_string(), "tcp/10.0.2.2:7447".to_string()),
            (
                "connect".to_string(),
                "serial//dev/ttyS0#baudrate=115200".to_string(),
            ),
        ];
        let text = encode(&props);
        assert_eq!(decode(&text).unwrap(), props);
        assert_eq!(endpoint(&props), Some("tcp/10.0.2.2:7447"));
        assert_eq!(decode("").unwrap(), Vec::new());
        assert!(decode("mode=client").unwrap_err().contains(ENV));
    }

    /// Issue 2051 — the table the Zephyr Rust lane bakes: one row per
    /// property, each a C-string literal of the same text (an ISO-TP
    /// endpoint's `;` and `#` included), and a NUL refused.
    #[test]
    fn the_rust_table_holds_every_row_as_c_string_literals() {
        let props = vec![
            (
                "connect".to_string(),
                "isotp/can#tx_id=0x200;rx_id=0x201".to_string(),
            ),
            ("mode".to_string(), "client".to_string()),
        ];
        let t = rust_table(&props).unwrap();
        assert!(
            t.contains("[crate::__macro_support::SessionProperty; 2]"),
            "{t}"
        );
        assert!(
            t.contains(r#"new(c"connect", c"isotp/can#tx_id=0x200;rx_id=0x201")"#),
            "{t}"
        );
        assert!(t.contains(r#"new(c"mode", c"client")"#), "{t}");
        assert!(
            rust_table(&[])
                .unwrap()
                .contains("SessionProperty; 0] = [\n];")
        );
        assert!(
            rust_table(&[("k".into(), "a\0b".into())])
                .unwrap_err()
                .contains("NUL")
        );
    }
}
