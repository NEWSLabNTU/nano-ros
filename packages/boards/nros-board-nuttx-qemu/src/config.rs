//! Network and node configuration for the NuttX QEMU boards.
//!
//! phase-337 W3.a — composed on [`nros_board_common::BaseConfig`] rather than
//! re-declaring the `{ip, netmask, gateway, locator, domain_id}` core. NuttX
//! owns no MAC (the virtio-net device takes its address from QEMU), so the
//! board reads every other field off the shared type and ignores `mac`.
//!
//! The address fields are the KERNEL's (RFC-0109 D2): generated from the
//! `defconfig` NuttX brings `eth0` up from, and never written back into the
//! interface (issue 2048 retired the `SIOCSIFADDR` push). Setting them on a
//! `Config` changes nothing on the wire; an image that wants another address
//! changes the kernel's `CONFIG_NETINIT_*`.

use nros_board_common::{BaseConfig, base_config::parse_u32};

/// Network and node configuration for the QEMU NuttX boards.
///
/// # Default configuration
///
/// The kernel `defconfig`'s `CONFIG_NETINIT_*` (RFC-0109 D2 — NuttX owns this
/// board's network): QEMU's own SLIRP network — IP `10.0.2.15/24`, gateway and
/// router `10.0.2.2` (`tcp/10.0.2.2:7447`).
///
/// Issue 2048 — there are no per-role presets (`listener()` / `server()` /
/// `client()` used to advance the last octet by 1 / 2 / 3). They existed to
/// give the retired `SIOCSIFADDR` push distinct addresses; with the kernel
/// owning `eth0` they would name an address no guest has.
#[derive(Clone, Copy, Debug)]
pub struct Config {
    /// The shared network/node core (RFC-0064 / phase-337 W1.b).
    pub base: BaseConfig,
}

// `BOARD_NET_*`, generated by the build script from the kernel `defconfig`
// (RFC-0109 D2, the one home; `entry_212n`'s SLIRP defaults read it too).
include!(concat!(env!("OUT_DIR"), "/nros_board_net.rs"));

impl Default for Config {
    /// The board's network defaults over the shared core (RFC-0103 D10).
    ///
    /// The connect pair also takes a build-time `NROS_LOCATOR` /
    /// `NROS_DOMAIN_ID` (a fixture row's `env`, for a workspace image whose
    /// `system.toml` states none). It is a BOARD-level default: the image's
    /// own `[image.<id>] locator` / `domain_id` still win, applied by
    /// [`Config::with_deploy`] (issue 1836).
    fn default() -> Self {
        let base = BaseConfig::default();
        Self {
            base: BaseConfig {
                ip: BOARD_NET_IP,
                netmask: BOARD_NET_NETMASK,
                gateway: BOARD_NET_GATEWAY,
                mac: BOARD_NET_MAC,
                zenoh_locator: match option_env!("NROS_LOCATOR") {
                    Some(locator) => locator,
                    None => BOARD_NET_LOCATOR,
                },
                domain_id: option_env!("NROS_DOMAIN_ID")
                    .and_then(|s| s.parse().ok())
                    .unwrap_or(base.domain_id),
            },
        }
    }
}

impl Config {
    /// IP address.
    pub const fn ip(&self) -> [u8; 4] {
        self.base.ip
    }

    /// Network prefix length.
    pub const fn prefix(&self) -> u8 {
        self.base.prefix()
    }

    /// Gateway IP.
    pub const fn gateway(&self) -> [u8; 4] {
        self.base.gateway
    }

    /// Transport locator the RMW backend dials.
    pub const fn locator(&self) -> &'static str {
        self.base.zenoh_locator
    }

    /// ROS 2 domain ID.
    pub const fn domain_id(&self) -> u32 {
        self.base.domain_id
    }

    /// Builder: set IP address.
    pub const fn with_ip(mut self, ip: [u8; 4]) -> Self {
        self.base.ip = ip;
        self
    }

    /// Builder: set network prefix length.
    pub const fn with_prefix(mut self, prefix: u8) -> Self {
        self.base = self.base.with_prefix(prefix);
        self
    }

    /// Builder: set gateway.
    pub const fn with_gateway(mut self, gateway: [u8; 4]) -> Self {
        self.base.gateway = gateway;
        self
    }

    /// Builder: set the transport locator the RMW backend connects
    /// through (e.g. `"tcp/192.0.3.1:7447"`,
    /// `"serial/UART_0#baudrate=115200"`).
    pub const fn with_locator(mut self, locator: &'static str) -> Self {
        self.base.zenoh_locator = locator;
        self
    }

    /// Builder: set ROS 2 domain ID.
    pub const fn with_domain_id(mut self, domain_id: u32) -> Self {
        self.base.domain_id = domain_id;
        self
    }

    /// The image's deploy overlay (`system.toml` `[image.<id>]` `locator`,
    /// `domain_id`, `ip`, `netmask`, `gateway`) over this config, field by
    /// field — the one merge every embedded board makes
    /// ([`BaseConfig::apply_overlay`]).
    ///
    /// Issue 1836 — NuttX was the one board that skipped it for the connect
    /// pair, so an image's own locator never reached its session.
    #[must_use]
    pub fn with_deploy(mut self, deploy: &nros_platform::DeployOverlay) -> Self {
        self.base.apply_overlay(deploy);
        self
    }

    /// Parse a direct-mode board file (RFC-0109 D4,
    /// [`nros_board_common::parse_direct_toml`]).
    ///
    /// Missing fields use board-specific defaults. This is designed to work
    /// with `include_str!("../config.toml")` for compile-time embedding.
    /// NuttX takes its MAC from the host TAP, so a `mac` is read and unused.
    ///
    /// ```toml
    /// [node]
    /// domain_id = 0
    /// locator = "tcp/10.0.2.2:7447"
    ///
    /// [eth0]
    /// network = "qemu"
    /// host = 30
    /// ```
    pub fn from_toml(toml: &'static str) -> Self {
        let mut config = Self::default();
        // This board has no board-specific keys.
        config
            .base
            .apply_direct(&nros_board_common::parse_direct_toml(toml, |_, _, _| {}));

        // Phase 177.38 — build-time ROS-domain override for per-fixture
        // isolation. `NROS_DOMAIN_ID` set at build time bakes a distinct domain
        // into this fixture without editing config.toml (the example default
        // stays clean). Cyclone derives RTPS ports from the domain, so
        // build-fixtures gives each communicating role-set its own domain and
        // concurrent fixtures don't collide. Empty/unset keeps the config value.
        if let Some(d) = option_env!("NROS_DOMAIN_ID").and_then(parse_u32) {
            config.base.domain_id = d;
        }

        config
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The default is the kernel's own `eth0` plan, generated from the
    /// `defconfig`'s `CONFIG_NETINIT_*` (phase-514 W4): QEMU's SLIRP network.
    /// Issue 2117 — this asserted the pre-W4 `192.0.3.10` for as long as the
    /// crate's tests could not link, so nothing noticed it had gone stale.
    #[test]
    fn the_default_is_the_kernels_eth0_plan() {
        let c = Config::default();
        assert_eq!(c.ip(), [10, 0, 2, 15]);
        assert_eq!(c.gateway(), [10, 0, 2, 2]);
        assert_eq!(c.prefix(), 24);
        assert_eq!(c.domain_id(), 0);
    }

    /// The prefix↔netmask bridge: the board reports in CIDR while
    /// `DeployOverlay` carries a netmask, and exactly one conversion should
    /// exist.
    #[test]
    fn prefix_round_trips_through_the_shared_netmask() {
        for p in [0u8, 8, 16, 24, 30, 32] {
            assert_eq!(Config::default().with_prefix(p).prefix(), p);
        }
    }

    #[test]
    fn from_toml_reads_the_direct_mode_board_file() {
        let c = Config::from_toml(
            "[eth0]\nnetwork = \"qemu\"\nhost = 30\n\
             [node]\nlocator = \"tcp/10.0.2.2:7447\"\ndomain_id = 7\n",
        );
        assert_eq!(c.ip(), [10, 0, 2, 30]);
        assert_eq!(c.prefix(), 24);
        assert_eq!(c.gateway(), [10, 0, 2, 2]);
        assert_eq!(c.locator(), "tcp/10.0.2.2:7447");
        // NROS_DOMAIN_ID is unset in a plain `cargo test`, so the TOML wins.
        if option_env!("NROS_DOMAIN_ID").is_none() {
            assert_eq!(c.domain_id(), 7);
        }
    }
}
