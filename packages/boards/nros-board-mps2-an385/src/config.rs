//! Configuration for QEMU bare-metal nodes
//!
//! # IP Configuration Modes
//!
//! The platform crate supports several IP configuration modes:
//!
//! 1. **Static IP** (default) - Use `Config::default()` or `Config::listener()`
//! 2. **Link-local auto-config** - Use `Config::link_local()` for zero-config networking
//! 3. **Custom** - Use builder methods to configure any settings

/// Network and node configuration
///
/// Provides sensible defaults for QEMU MPS2-AN385 development.
///
/// # Default Configuration (Talker)
///
/// - **QEMU network** (default): the board's `[board.net]` (phase-484 W4b-2,
///   RFC-0103 D10) — QEMU's own SLIRP network, `10.0.2.15/24`, gateway and
///   router `10.0.2.2` (`tcp/10.0.2.2:7447`). A TAP/bridge network is a
///   project-defined network (phase-497); until then an image states its own
///   address.
///
/// - **Docker** (`tests/qemu-baremetal`): not a board mode. The container's
///   network is a project network, `[network.docker]` in the board network
///   file the leaves' `[image.docker]` names, with the image's address on it
///   and `[image.docker.run] nic` the TAP (RFC-0109 D4/D6; this was a `docker`
///   cargo feature).
///
/// - **QEMU user-mode / slirp** ([`Config::qemu_slirp`], NOT the default):
///   - IP: 10.0.2.10/24
///   - Gateway: 10.0.2.2
///   - Zenoh: tcp/10.0.2.2:7450
///
/// Slirp's NAT subnet is fixed by how QEMU was launched, which the firmware
/// cannot observe — so the plan is a named preset, never an implicit default.
/// See [`Config::qemu_slirp`].
#[derive(Clone)]
pub struct Config {
    // -- Ethernet-specific fields --
    /// MAC address (default: locally administered 02:00:00:00:00:00)
    #[cfg(feature = "ethernet")]
    pub mac: [u8; 6],
    /// IP address
    #[cfg(feature = "ethernet")]
    pub ip: [u8; 4],
    /// Network prefix (default: 24)
    #[cfg(feature = "ethernet")]
    pub prefix: u8,
    /// Gateway IP
    #[cfg(feature = "ethernet")]
    pub gateway: [u8; 4],

    // -- Serial-specific fields --
    /// UART base address (default: UART0 = 0x4000_4000)
    #[cfg(feature = "serial")]
    pub uart_base: usize,
    /// Baud rate (default: 115200). Ignored by QEMU (infinite speed),
    /// but required for real hardware.
    #[cfg(feature = "serial")]
    pub baudrate: u32,

    // -- Common fields --
    /// Zenoh locator (Rust string, null termination handled internally)
    pub zenoh_locator: &'static str,
    /// ROS 2 domain ID (default: 0)
    pub domain_id: u32,
}

// phase-484 W4b-2 — `BOARD_NET_*`: this crate's `[board.net]` (QEMU's own SLIRP
// network, RFC-0103 D10), generated by the build script.
include!(concat!(env!("OUT_DIR"), "/nros_board_net.rs"));

/// The default IP with its last octet replaced.
#[cfg(feature = "ethernet")]
const fn ip_last(last: u8) -> [u8; 4] {
    [BOARD_NET_IP[0], BOARD_NET_IP[1], BOARD_NET_IP[2], last]
}

#[cfg(feature = "ethernet")]
impl Default for Config {
    fn default() -> Self {
        Self {
            mac: BOARD_NET_MAC,
            ip: BOARD_NET_IP,
            prefix: nros_board_common::prefix_from_netmask(BOARD_NET_NETMASK),
            gateway: BOARD_NET_GATEWAY,
            #[cfg(feature = "serial")]
            uart_base: cmsdk_uart::UART0_BASE,
            #[cfg(feature = "serial")]
            baudrate: 115200,
            zenoh_locator: BOARD_NET_LOCATOR,
            domain_id: 0,
        }
    }
}

#[cfg(all(feature = "serial", not(feature = "ethernet")))]
impl Default for Config {
    fn default() -> Self {
        Self::serial_default()
    }
}

impl Config {
    /// Configuration preset for serial transport with default settings.
    ///
    /// Uses UART0 at 115200 baud with a serial zenoh locator.
    #[cfg(feature = "serial")]
    pub fn serial_default() -> Self {
        Self {
            #[cfg(feature = "ethernet")]
            mac: BOARD_NET_MAC,
            #[cfg(feature = "ethernet")]
            ip: BOARD_NET_IP,
            #[cfg(feature = "ethernet")]
            prefix: nros_board_common::prefix_from_netmask(BOARD_NET_NETMASK),
            #[cfg(feature = "ethernet")]
            gateway: BOARD_NET_GATEWAY,
            uart_base: cmsdk_uart::UART0_BASE,
            baudrate: 115200,
            zenoh_locator: "serial/UART_0#baudrate=115200",
            domain_id: 0,
        }
    }

    /// Create a new config with custom ethernet settings
    #[cfg(feature = "ethernet")]
    pub fn new(mac: [u8; 6], ip: [u8; 4], gateway: [u8; 4], zenoh_locator: &'static str) -> Self {
        Self {
            mac,
            ip,
            prefix: 24,
            gateway,
            #[cfg(feature = "serial")]
            uart_base: cmsdk_uart::UART0_BASE,
            #[cfg(feature = "serial")]
            baudrate: 115200,
            zenoh_locator,
            domain_id: 0,
        }
    }

    /// Configuration preset for a listener/subscriber node
    #[cfg(feature = "ethernet")]
    pub fn listener() -> Self {
        // The default's identity with the last IP octet and MAC byte
        // advanced by one — derived, so the pair cannot drift apart.
        let mut c = Self::default();
        c.ip[3] = c.ip[3].wrapping_add(1);
        c.mac[5] = c.mac[5].wrapping_add(1);
        c
    }

    /// Alias for `Config::default()`
    #[cfg(feature = "ethernet")]
    pub fn talker() -> Self {
        Self::default()
    }

    /// The QEMU **user-mode (slirp)** address plan: `10.0.2.10/24`, gateway
    /// `10.0.2.2`, locator `tcp/10.0.2.2:7450`.
    ///
    /// Since phase-484 W4b-2 this is the SAME network as [`Config::default`]
    /// (the board's `[board.net]`, QEMU's SLIRP plan, RFC-0103 D10). Before it
    /// the board had two address plans, the default being a `192.0.3.0/24`
    /// bridge plan, and which one was right depended on how QEMU was launched,
    /// a fact the firmware cannot observe. What remains distinct here is the
    /// RTIC examples' own guest address (`.10`) and router port (`7450`).
    ///
    /// phase-337 W6 folded `nros-board-rtic-mps2-an385` into this crate; this
    /// preset is that crate's `qemu_config()`, which was a second `Default`-
    /// shaped function in a sibling crate — the divergence was invisible until
    /// a node failed to reach the router at runtime. Naming it is the fix: the
    /// two plans now sit three lines apart with the runner each one matches
    /// written down.
    ///
    /// `NROS_LOCATOR` / `NROS_DOMAIN_ID` at BUILD time override the locator and
    /// domain (bare-metal has no host `getenv`, so these are baked, not read).
    #[cfg(feature = "ethernet")]
    pub fn qemu_slirp() -> Self {
        Self {
            mac: BOARD_NET_MAC,
            ip: ip_last(10),
            prefix: nros_board_common::prefix_from_netmask(BOARD_NET_NETMASK),
            gateway: BOARD_NET_GATEWAY,
            #[cfg(feature = "serial")]
            uart_base: cmsdk_uart::UART0_BASE,
            #[cfg(feature = "serial")]
            baudrate: 115200,
            zenoh_locator: option_env!("NROS_LOCATOR").unwrap_or("tcp/10.0.2.2:7450"),
            domain_id: match option_env!("NROS_DOMAIN_ID") {
                Some(s) => parse_u32(s).unwrap_or_default(),
                None => 0,
            },
        }
    }

    /// Builder: set MAC address
    #[cfg(feature = "ethernet")]
    pub fn with_mac(mut self, mac: [u8; 6]) -> Self {
        self.mac = mac;
        self
    }

    /// Builder: set IP address
    #[cfg(feature = "ethernet")]
    pub fn with_ip(mut self, ip: [u8; 4]) -> Self {
        self.ip = ip;
        self
    }

    /// Builder: set network prefix length
    #[cfg(feature = "ethernet")]
    pub fn with_prefix(mut self, prefix: u8) -> Self {
        self.prefix = prefix;
        self
    }

    /// Builder: set gateway
    #[cfg(feature = "ethernet")]
    pub fn with_gateway(mut self, gateway: [u8; 4]) -> Self {
        self.gateway = gateway;
        self
    }

    /// Builder: set the transport locator the RMW backend connects
    /// through (e.g. `"tcp/192.0.3.1:7447"`,
    /// `"serial/UART_0#baudrate=115200"`).
    pub fn with_locator(mut self, locator: &'static str) -> Self {
        self.zenoh_locator = locator;
        self
    }

    /// Builder: set ROS 2 domain ID
    pub fn with_domain_id(mut self, domain_id: u32) -> Self {
        self.domain_id = domain_id;
        self
    }

    /// Builder: set UART base address
    #[cfg(feature = "serial")]
    pub fn with_uart_base(mut self, base: usize) -> Self {
        self.uart_base = base;
        self
    }

    /// Builder: set baud rate
    #[cfg(feature = "serial")]
    pub fn with_baudrate(mut self, baudrate: u32) -> Self {
        self.baudrate = baudrate;
        self
    }

    /// Create a link-local configuration with auto-generated IP
    #[cfg(feature = "ethernet")]
    pub fn link_local() -> Self {
        Self::link_local_with_mac([0x02, 0x00, 0x00, 0x00, 0x00, 0x00])
    }

    /// Create a link-local configuration for a second node (listener)
    #[cfg(feature = "ethernet")]
    pub fn link_local_listener() -> Self {
        Self::link_local_with_mac([0x02, 0x00, 0x00, 0x00, 0x00, 0x01])
    }

    /// Create a link-local configuration with a specific MAC address
    #[cfg(feature = "ethernet")]
    pub fn link_local_with_mac(mac: [u8; 6]) -> Self {
        let ip = Self::mac_to_link_local(&mac);
        let gateway = [0, 0, 0, 0];

        let zenoh_locator: &'static str = "tcp/192.0.3.1:7447";

        Self {
            mac,
            ip,
            prefix: 16,
            gateway,
            #[cfg(feature = "serial")]
            uart_base: cmsdk_uart::UART0_BASE,
            #[cfg(feature = "serial")]
            baudrate: 115200,
            zenoh_locator,
            domain_id: 0,
        }
    }

    /// Generate a link-local IP address from a MAC address (RFC 3927)
    #[cfg(feature = "ethernet")]
    fn mac_to_link_local(mac: &[u8; 6]) -> [u8; 4] {
        let third = match mac[4] {
            0 => 1,
            255 => 254,
            x => x,
        };
        let fourth = match mac[5] {
            0 => 1,
            255 => 254,
            x => x,
        };

        [169, 254, third, fourth]
    }

    /// Check if this configuration uses a link-local IP address
    #[cfg(feature = "ethernet")]
    pub fn is_link_local(&self) -> bool {
        self.ip[0] == 169 && self.ip[1] == 254
    }

    /// Parse a direct-mode board file (RFC-0109 D4,
    /// [`nros_board_common::parse_direct_toml`]).
    ///
    /// Missing fields use board-specific defaults. This is designed to work
    /// with `include_str!("../config.toml")` for compile-time embedding.
    ///
    /// # Supported fields
    ///
    /// ```toml
    /// [node]
    /// domain_id = 0
    /// locator = "tcp/10.0.2.2:7447"
    ///
    /// [eth0]               # `ethernet`
    /// network = "qemu"     # built in: 10.0.2.0/24, gateway 10.0.2.2
    /// host = 15            # or: address = "10.0.2.15"
    /// mac = "02:00:00:00:00:00"
    ///
    /// [uart0]              # `serial`
    /// baud = 115200
    /// ```
    pub fn from_toml(toml: &'static str) -> Self {
        let mut config = Self::default();
        #[cfg(feature = "serial")]
        let mut baud = None;
        let d = nros_board_common::parse_direct_toml(toml, |_section, _key, _value| {
            // The serial link's own fact, on its interface table (`[uart0] baud`).
            #[cfg(feature = "serial")]
            if nros_board_common::is_interface_section(_section) && _key == "baud" {
                baud = parse_u32(_value);
            }
        });
        #[cfg(feature = "serial")]
        if let Some(b) = baud {
            config.baudrate = b;
        }
        #[cfg(feature = "ethernet")]
        {
            if let Some(ip) = d.ip {
                config.ip = ip;
            }
            if let Some(p) = d.prefix() {
                config.prefix = p;
            }
            if let Some(gw) = d.gateway {
                config.gateway = gw;
            }
            if let Some(mac) = d.mac {
                config.mac = mac;
            }
        }
        if let Some(l) = d.locator {
            config.zenoh_locator = l;
        }
        if let Some(id) = d.domain_id {
            config.domain_id = id;
        }

        // Phase 177.38 — build-time ROS-domain override for per-fixture
        // isolation. `NROS_DOMAIN_ID` set at build time bakes a distinct domain
        // into this fixture without editing config.toml (the example default
        // stays clean). Cyclone derives RTPS ports from the domain, so
        // build-fixtures gives each communicating role-set its own domain and
        // concurrent fixtures don't collide. Empty/unset keeps the config value.
        if let Some(d) = option_env!("NROS_DOMAIN_ID").and_then(parse_u32) {
            config.domain_id = d;
        }

        config
    }
}

use nros_board_common::base_config::parse_u32;

impl Config {
    /// The board default overlaid with the IMAGE's declared network identity —
    /// issue 1512, for a cargo-rooted C/C++ leaf.
    ///
    /// A Rust leaf gets `[image.<id>] locator/domain_id` and its resolved
    /// network from `nros::main!`'s deploy overlay (`entry.rs::config_with_overlay`). A
    /// C or C++ leaf whose link root is Rust (`run_bare` from its own
    /// `main.rs`) has no such macro, so it booted `Config::default()` whatever
    /// its `system.toml` said. `nros sync` renders the same declared values
    /// into the image's `build/<image>/nros-cargo.toml` as `NROS_ENTRY_*`
    /// `[env]` rows, and its resolved network as `NROS_IMAGE_NET` (RFC-0103
    /// D10f); this reads them at compile time. An absent row keeps the board
    /// default — nothing here is derived.
    ///
    /// `NROS_ENTRY_LOCATOR` also reaches the C/C++ TU as the macro the app
    /// dials (`nros_cc_flags::entry_config`); the copy here keeps the board's
    /// own `BoardConfig::locator()` saying the same thing.
    #[must_use]
    pub fn from_image() -> Self {
        let mut cfg = Self::default();
        if let Some(loc) = option_env!("NROS_ENTRY_LOCATOR") {
            cfg.zenoh_locator = loc;
        }
        #[cfg(feature = "ethernet")]
        cfg.apply_image_net(option_env!("NROS_IMAGE_NET"));
        if let Some(id) = option_env!("NROS_ENTRY_DOMAIN_ID").and_then(|s| s.parse().ok()) {
            cfg.domain_id = id;
        }
        cfg
    }
}

#[cfg(feature = "ethernet")]
impl Config {
    /// Apply an image's resolved network (`NROS_IMAGE_NET`, RFC-0103 D10f) —
    /// its primary interface's address, prefix, gateway and MAC. `None` keeps
    /// the board default. The one place this board reads the text, for the
    /// macro road (`DeployOverlay::net`) and the C road (`from_image`) alike.
    pub(crate) fn apply_image_net(&mut self, text: Option<&'static str>) {
        if let Some(i) = nros_board_common::image_net::boot_interface(text) {
            if let Some(ip) = i.ip() {
                self.ip = ip;
            }
            self.prefix = i.prefix;
            if let Some(gw) = i.gateway {
                self.gateway = gw;
            }
            self.mac = i.mac;
        }
    }
}

impl nros_platform::BoardConfig for Config {
    fn locator(&self) -> &str {
        self.zenoh_locator
    }

    fn domain_id(&self) -> u32 {
        self.domain_id
    }
}

