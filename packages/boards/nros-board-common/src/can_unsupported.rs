// RFC-0132 D3, issue 2788.

//! The CAN frame driver's weak fail-loud defaults,
//! for a board with no CAN backend of its own, on the cargo road.
//!
//! The source is ONE file, `c/nros_board_can_unsupported.c`. A board build
//! script that compiles board glue adds it with
//! [`add_defaults`](crate::can_unsupported::add_defaults), which writes a
//! one-line TU naming the board into `OUT_DIR`, so `open` reports
//! `NROS_PLATFORM_CAN_ENOTSUP` and prints a line naming the board. The cmake
//! road compiles the same file into every entry
//! (`cmake/NanoRosCanImage.cmake`, `nros_entry_can_defaults`).
//!
//! Every symbol is weak: a board package's or a consumer's strong driver in
//! an object of the image wins. Never call this on a board with a real backend
//! (a `"host"` stack's SocketCAN, Zephyr's).

use std::{env, fs, path::PathBuf};

/// The defaults' source, by its path in this crate.
pub fn defaults_source() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("c/nros_board_can_unsupported.c")
}

/// Add the defaults, naming `board`, to a board's glue build.
pub fn add_defaults(build: &mut cc::Build, board: &str) {
    let src = defaults_source();
    let out_dir =
        PathBuf::from(env::var_os("OUT_DIR").expect("nros-board-common: OUT_DIR not set"));
    let tu = out_dir.join("nros_board_can_unsupported_tu.c");
    let body = format!(
        "/* Generated by nros_board_common::can_unsupported. */\n\
         #define NROS_BOARD_CAN_BOARD_NAME \"{board}\"\n\
         #include \"{}\"\n",
        src.display()
    );
    if fs::read_to_string(&tu).ok().as_deref() != Some(body.as_str()) {
        fs::write(&tu, &body)
            .unwrap_or_else(|e| panic!("nros-board-common: write({}): {e}", tu.display()));
    }
    build.file(&tu);
    build.include(nros_build_paths::nros_platform_cffi_include());
    println!("cargo:rerun-if-changed={}", src.display());
}
